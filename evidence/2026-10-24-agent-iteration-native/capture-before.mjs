import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {createInteractionBridgeBackend} from '../../dist/interactionbridge.js';
import {bindInteractionTarget,liveInteractionTargetProbes,revalidateInteractionTarget} from '../../dist/interactiontarget.js';
import {captureAdbFrame,sha256Bytes} from '../../dist/observation.js';
const ev=path.dirname(fileURLToPath(import.meta.url));
const adb='/Users/sushantsrikrish/Library/Android/sdk/platform-tools/adb',serial='emulator-5554',packageName='com.example.picofixture.iteration.debug';
const bridge=createInteractionBridgeBackend({adb,serial,packageName});
const probes=liveInteractionTargetProbes(adb,t=>bridge.observe(t));
const target=await bindInteractionTarget({serial,packageName,expectedApkSha256:'24704bdee8d5547b09621d48e073abe33741b94a42627d2f6ed9afe091956e04'},probes);
const state=await bridge.observe();assert.equal(state.revision,0);assert.equal(state.state.panel.visible,false);
const frame=await captureAdbFrame(adb,serial,10000);
await revalidateInteractionTarget(target,probes);
const after=await bridge.observe();assert.equal(after.revision,0);
fs.writeFileSync(path.join(ev,'before.png'),frame.bytes,{flag:'wx'});
fs.writeFileSync(path.join(ev,'before-capture.json'),JSON.stringify({target,state,after,path:path.join(ev,'before.png'),sha256:sha256Bytes(frame.bytes),bytes:frame.bytes.length,capturedAt:frame.capturedAt,lookPending:true},null,2)+'\n',{flag:'wx'});
console.log('Fresh bound initial-state frame retained.');
