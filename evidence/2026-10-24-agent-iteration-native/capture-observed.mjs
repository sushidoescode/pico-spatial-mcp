import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createInteractionBridgeBackend} from '../../dist/interactionbridge.js';
import {bindInteractionTarget,liveInteractionTargetProbes,revalidateInteractionTarget} from '../../dist/interactiontarget.js';
import {captureAdbFrame,sha256Bytes} from '../../dist/observation.js';
const ev=path.dirname(fileURLToPath(import.meta.url)),name=process.argv[2];
if(!/^[a-z0-9-]+$/.test(name??''))throw new Error('Unique evidence name required');
const adb='/Users/sushantsrikrish/Library/Android/sdk/platform-tools/adb',serial='emulator-5554',packageName='com.example.picofixture.iteration.debug';
const bridge=createInteractionBridgeBackend({adb,serial,packageName});
const probes=liveInteractionTargetProbes(adb,t=>bridge.observe(t));
const target=await bindInteractionTarget({serial,packageName,expectedApkSha256:process.argv[3]},probes);
const state=await bridge.observe(),frame=await captureAdbFrame(adb,serial,10000);
await revalidateInteractionTarget(target,probes);
const after=await bridge.observe();
fs.writeFileSync(path.join(ev,name+'.png'),frame.bytes,{flag:'wx'});
const record={target,state,after,path:path.join(ev,name+'.png'),sha256:sha256Bytes(frame.bytes),bytes:frame.bytes.length,capturedAt:frame.capturedAt,lookPending:true};
fs.writeFileSync(path.join(ev,name+'.json'),JSON.stringify(record,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify(record));
