import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok, fail } from "./util.js";

/**
 * anim.ts — v4.7 programmatic animation (tween + orbit).
 *
 * Source-verified facts (SDK 0.13.3):
 *  - TweenAnimation/OrbitAnimation have NO public ctor — build via the @JvmStatic companion
 *    factories TweenAnimation.createTweenAnimation(...) (one overload per value type) and
 *    OrbitAnimation.createOrbitAnimation(...). The from/to value TYPE must match the bindTarget:
 *    bindPosition/bindScale -> Vector3, bindRotation -> EulerAngles/Quat.
 *  - AnimationResource.generateWithTweenAnimation(anim) / AnimationResource.generate(orbit) bake
 *    it, then entity.playAnimation(res): AnimationPlaybackController (@MainThread).
 *  - SpatialAnimation.INFINITE = -1 (repeatCount to loop forever).
 *  CAVEAT: AnimationResource does NOT propagate to runtime-built entities (v8.1) — use SceneAnimator
 *  (generate_scene_animator_kotlin) for those. When it DOES apply (editor/baked), it is VISION-verifiable: pixels change across captures
 *  (aim the decoupled free cam with emulator_look to keep it framed — C2).
 */
export function registerAnimTools(server: McpServer) {
  // ── generate_tween_animation_kotlin ────────────────────────────────────────
  server.registerTool(
    "generate_tween_animation_kotlin",
    {
      description:
        "Emit SceneTween.kt — a programmatic from→to TWEEN that moves/scales/rotates an entity over time (TweenAnimation.createTweenAnimation → AnimationResource.generateWithTweenAnimation → entity.playAnimation). Supports position/scale (Vector3) and rotation (EulerAngles), ease + repeat (none/restart/reverse) + infinite loop. Compiles against the SDK; CAVEAT (v8.1/v9.6): AnimationResource/entity.playAnimation does NOT reliably propagate to RUNTIME-built entities or through a loaded model's node hierarchy — an agent animating runtime spheres/boxes/models with this gets NO visible motion. For runtime entities use `generate_scene_animator_kotlin` (SceneAnimator coroutine frame-loop — the vision-verified path); reserve this tool for editor-authored/baked animation clips.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        property: z.enum(["position", "scale", "rotation"]).optional().describe("What to animate. position/scale use [x,y,z] meters/factor; rotation uses [x,y,z] euler degrees. Default position."),
        from: z.array(z.number()).optional().describe("Start value [x,y,z] (default position [0,1,-3] / scale [1,1,1] / rotation [0,0,0])."),
        to: z.array(z.number()).optional().describe("End value [x,y,z] (default position [0,1.5,-3] / scale [1.4,1.4,1.4] / rotation [0,360,0])."),
        duration: z.number().optional().describe("Seconds for one play (default 2)."),
        repeat: z.enum(["none", "restart", "reverse"]).optional().describe("Repeat mode (default reverse — bobs back and forth)."),
        loop: z.boolean().optional().describe("Loop forever (repeatCount = SpatialAnimation.INFINITE). Default true."),
        ease: z.enum(["LINEAR", "EASE_IN", "EASE_OUT", "EASE_INOUT", "EASE_IN_CUBIC", "EASE_OUT_CUBIC", "EASE_INOUT_CUBIC"]).optional().describe("Easing (default EASE_INOUT)."),
      },
    },
    async ({ packageName, property, from, to, duration, repeat, loop, ease }) => {
      const prop = property ?? "position";
      if (from && from.length !== 3) return fail("from must be [x,y,z] (3 numbers).");
      if (to && to.length !== 3) return fail("to must be [x,y,z] (3 numbers).");
      const defFrom = prop === "scale" ? [1, 1, 1] : prop === "rotation" ? [0, 0, 0] : [0, 1, -3];
      const defTo = prop === "scale" ? [1.4, 1.4, 1.4] : prop === "rotation" ? [0, 360, 0] : [0, 1.5, -3];
      const f = (from ?? defFrom) as number[];
      const t = (to ?? defTo) as number[];
      const dur = duration ?? 2;
      const rep = (repeat ?? "reverse").toUpperCase();
      const repeatMode = rep === "NONE" ? "NONE" : rep; // RepeatMode.NONE/RESTART/REVERSE
      const repeatCount = loop === false ? "1" : "SpatialAnimation.INFINITE";
      const easeT = ease ?? "EASE_INOUT";
      const bind = prop === "position" ? "bindPosition" : prop === "scale" ? "bindScale" : "bindRotation";
      const valueType = prop === "rotation" ? "EulerAngles" : "Vector3";
      const valExpr = (v: number[]) => `${valueType}(${v[0]}f, ${v[1]}f, ${v[2]}f)`;
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.animation.AnimationBindTarget",
        "import com.pico.spatial.core.ecs.animation.AnimationPlaybackController",
        "import com.pico.spatial.core.ecs.animation.EaseType",
        "import com.pico.spatial.core.ecs.animation.RepeatMode",
        "import com.pico.spatial.core.ecs.animation.SpatialAnimation",
        "import com.pico.spatial.core.ecs.animation.TweenAnimation",
        "import com.pico.spatial.core.ecs.resource.AnimationResource",
        prop === "rotation" ? "import com.pico.spatial.core.math.EulerAngles" : "import com.pico.spatial.core.math.Vector3",
        "",
        "/**",
        " * Generated by generate_tween_animation_kotlin. Tweens an entity over time. Call",
        " * SceneTween.play(entity) (the entity must already be in the scene). @MainThread.",
        " * VERIFY: compiles; the motion is vision-verifiable across captures.",
        " */",
        "object SceneTween {",
        '    private const val TAG = "SceneTween"',
        "",
        "    // v35.5: the resource is RETAINED so it can be closed. Previously every play() baked a",
        "    // fresh AnimationResource and dropped the only reference — a leak by construction, on a",
        "    // function an agent calls on every button press. AnimationResource extends Resource,",
        "    // which is Closeable (Resource.kt:24); close() is overridden at AnimationResource.kt:69.",
        "    private var res: AnimationResource? = null",
        "    private var controller: AnimationPlaybackController? = null",
        "",
        "    fun play(entity: Entity): AnimationPlaybackController? = runCatching {",
        "        val anim = TweenAnimation.createTweenAnimation(",
        `            name = "tween_${prop}",`,
        `            bindTarget = AnimationBindTarget.${bind}(),`,
        `            from = ${valExpr(f)},`,
        `            to = ${valExpr(t)},`,
        `            duration = ${dur}f,`,
        `            repeatMode = RepeatMode.${repeatMode},`,
        `            repeatCount = ${repeatCount},`,
        `            easeType = EaseType.${easeT},`,
        "        )",
        "        // Replacing a still-playing resource without stopping it would strand the old one.",
        "        stop(entity)",
        "        val res = AnimationResource.generateWithTweenAnimation(anim)",
        "        this.res = res",
        "        val controller = entity.playAnimation(res)",
        "        this.controller = controller",
        `        Log.i(TAG, "tween ${prop} playing (${dur}s, ${repeatMode})")`,
        "        controller",
        "    }.onFailure { Log.e(TAG, \"tween failed: ${it.message}\") }.getOrNull()",
        "",
        "    /**",
        "     * Stop playback and release the resource. REQUIRED in your teardown path (onDispose /",
        "     * onCleared / ON_PAUSE) — this is the shape PICO use.",
        "     *",
        "     * ORDER MATTERS: stopAllAnimations() FIRST, then close(). PICO's own code says it twice —",
        "     * \"Do not use use() here; animation resource must remain open for continuous playback\" and",
        "     * \"Do not close animation resources here, as they may be reused for subsequent playback\".",
        "     * Closing a resource that is still playing is the failure those comments are warning about.",
        "     */",
        "    fun stop(entity: Entity) {",
        "        runCatching {",
        "            entity.stopAllAnimations()",
        "            res?.close()",
        "        }.onFailure { Log.e(TAG, \"tween stop failed: ${it.message}\") }",
        "        res = null",
        "        controller = null",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );

  // ── generate_orbit_animation_kotlin ────────────────────────────────────────
  server.registerTool(
    "generate_orbit_animation_kotlin",
    {
      description:
        "Emit SceneOrbit.kt — an ORBIT animation: an entity revolves around an axis (OrbitAnimation.createOrbitAnimation → AnimationResource.generate → entity.playAnimation). The orbit radius is the perpendicular distance of startPosition from the axis (a startPosition ON the axis gives radius 0 = no motion). Compiles against the SDK. CAVEAT (v8.1/v9.6): AnimationResource does NOT reliably propagate to RUNTIME-built entities — for runtime entities use `generate_scene_animator_kotlin` (SceneAnimator.orbit, the vision-verified path); reserve this for editor-authored/baked clips.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        axis: z.array(z.number()).optional().describe("Orbit axis [x,y,z] (default [0,1,0] = world up). Normalized internally; never [0,0,0]."),
        startPosition: z.array(z.number()).optional().describe("The orbiting entity's start position [x,y,z]; its perpendicular distance from the axis is the radius (default [0.6,1.2,-2.5])."),
        duration: z.number().optional().describe("Seconds per revolution segment (default 4)."),
        rotationCount: z.number().optional().describe("Revolutions per play (1=360°, 0.5=180°). Default 1."),
        spinClockwise: z.boolean().optional().describe("Spin direction (default false = counter-clockwise)."),
        orientToPath: z.boolean().optional().describe("Rotate the entity to face the travel direction (default true)."),
        loop: z.boolean().optional().describe("Loop forever (default true)."),
      },
    },
    async ({ packageName, axis, startPosition, duration, rotationCount, spinClockwise, orientToPath, loop }) => {
      if (axis && axis.length !== 3) return fail("axis must be [x,y,z] (3 numbers).");
      if (startPosition && startPosition.length !== 3) return fail("startPosition must be [x,y,z] (3 numbers).");
      const ax = (axis ?? [0, 1, 0]) as number[];
      const sp = (startPosition ?? [0.6, 1.2, -2.5]) as number[];
      const dur = duration ?? 4;
      const rc = rotationCount ?? 1;
      const cw = spinClockwise === true;
      const otp = orientToPath !== false;
      const repeatCount = loop === false ? "1" : "SpatialAnimation.INFINITE";
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.animation.AnimationPlaybackController",
        "import com.pico.spatial.core.ecs.animation.OrbitAnimation",
        "import com.pico.spatial.core.ecs.animation.RepeatMode",
        "import com.pico.spatial.core.ecs.animation.SpatialAnimation",
        "import com.pico.spatial.core.ecs.resource.AnimationResource",
        "import com.pico.spatial.core.math.EulerAngles",
        "import com.pico.spatial.core.math.Transform",
        "import com.pico.spatial.core.math.Vector3",
        "",
        "/**",
        " * Generated by generate_orbit_animation_kotlin. Revolves an entity around an axis. Call",
        " * SceneOrbit.play(entity). Radius = startPosition's perpendicular distance from the axis.",
        " * VERIFY: compiles; the orbital motion is vision-verifiable across captures.",
        " */",
        "object SceneOrbit {",
        '    private const val TAG = "SceneOrbit"',
        "",
        "    // v35.5: retained so it can be closed — see SceneTween. AnimationResource is Closeable",
        "    // (Resource.kt:24; override at AnimationResource.kt:69) and every play() used to bake a",
        "    // fresh one and drop the reference.",
        "    private var res: AnimationResource? = null",
        "",
        "    fun play(entity: Entity): AnimationPlaybackController? = runCatching {",
        "        val orbit = OrbitAnimation.createOrbitAnimation(",
        '            name = "orbit",',
        `            duration = ${dur}f,`,
        `            axis = Vector3(${ax[0]}f, ${ax[1]}f, ${ax[2]}f),`,
        `            startTransform = Transform(Vector3(${sp[0]}f, ${sp[1]}f, ${sp[2]}f), EulerAngles(0f, 0f, 0f), Vector3(1f, 1f, 1f)),`,
        `            spinClockwise = ${cw},`,
        `            orientToPath = ${otp},`,
        `            rotationCount = ${rc}f,`,
        "            repeatMode = RepeatMode.RESTART,",
        `            repeatCount = ${repeatCount},`,
        "        )",
        "        stop(entity)",
        "        val res = AnimationResource.generate(orbit)",
        "        this.res = res",
        "        val controller = entity.playAnimation(res)",
        `        Log.i(TAG, "orbit playing (${dur}s/rev)")`,
        "        controller",
        "    }.onFailure { Log.e(TAG, \"orbit failed: ${it.message}\") }.getOrNull()",
        "",
        "    /** Stop playback and release the resource. REQUIRED in teardown. Stop BEFORE closing:",
        "     *  closing a resource that is still playing is what PICO's own comments warn against. */",
        "    fun stop(entity: Entity) {",
        "        runCatching {",
        "            entity.stopAllAnimations()",
        "            res?.close()",
        "        }.onFailure { Log.e(TAG, \"orbit stop failed: ${it.message}\") }",
        "        res = null",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );

  server.registerTool(
    "generate_scene_animator_kotlin",
    {
      description:
        "Emit SceneAnimator.kt — a RELIABLE frame-based animation driver (a coroutine loop that updates TransformComponents on the main thread each frame). Use this instead of the SDK Tween/Orbit when animating RUNTIME-built entities (spheres, boxes, models): the SDK AnimationResource does not reliably propagate through the SpatialView node hierarchy, but this per-frame TransformComponent update does (VISION-VERIFIED on the emulator: an orrery of 4 planets orbited a sun, MAE-confirmed motion). Register anims (orbit/spin/bob + material FX: pulseEmissive/fadeOpacity/cycleHue for energy/hologram/color-shift looks) after building the scene, then drive it from Compose: `LaunchedEffect(Unit) { SceneAnimator.run() }`. Returns the drop-in Kotlin.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
      },
    },
    async ({ packageName }) => {
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.ecs.resource.BlendingMode",
        "import com.pico.spatial.core.ecs.resource.PhysicallyBasedMaterial",
        "import com.pico.spatial.core.math.Color4",
        "import com.pico.spatial.core.math.EulerAngles",
        "import com.pico.spatial.core.math.Vector3",
        "import kotlinx.coroutines.Dispatchers",
        "import kotlinx.coroutines.delay",
        "import kotlinx.coroutines.withContext",
        "import kotlin.math.cos",
        "import kotlin.math.sin",
        "",
        "/**",
        " * Generated by generate_scene_animator_kotlin — a reliable per-frame animation driver for",
        " * runtime-built entities. The SDK AnimationResource (Tween/Orbit) does NOT reliably propagate",
        " * through the SpatialView node hierarchy; updating the TransformComponent each frame DOES.",
        " * VISION-VERIFIED on the emulator (an orrery orbited; motion MAE-confirmed).",
        " *",
        " * Each animation MUTATES only the axes it owns on the entity's EXISTING TransformComponent",
        " * (transform.position / .quaternion / .scaleVector are public vars — TransformComponent.kt:74,",
        " * 159, 203). It never constructs a replacement component. That matters twice over:",
        " *   1. Composition — orbit writes position only and spin writes rotation only, so an entity can",
        " *      orbit AND spin. Replacing the component wrote identity rotation and unit scale every",
        " *      frame, which made those two animations mutually exclusive by construction.",
        " *   2. Allocation — a new component per entity per frame at 60Hz is the per-tick recreation",
        " *      pressure that ANRs at scale. PICO go further still and avoid even a List allocation in",
        " *      the hot loop \"to prevent GC pressure and avoid judder\" (SpatialMesh AmmoSystem.kt:15-16).",
        " *",
        " * For NEW work prefer generate_ecs_system_kotlin: System + SceneUpdateContext is PICO's own",
        " * per-frame mechanism, driven by the engine rather than by a coroutine we hand-roll. This",
        " * driver stays because it is the vision-verified path for runtime-built entities.",
        " *",
        " * Usage (in a @Composable, AFTER the scene is built):",
        " *   SceneAnimator.orbit(planet, Vector3(0f, 1.25f, -3.3f), radius = 1.2f, startAngle = 0f, speed = 0.4f)",
        " *   SceneAnimator.spin(gem, degPerSec = 45f)",
        " *   SceneAnimator.bob(icon, base = Vector3(0f, 1.4f, -2f), amplitude = 0.06f, period = 2.5f)",
        " *   LaunchedEffect(Unit) { SceneAnimator.run() }   // starts the frame loop; cancelled on dispose",
        " * From a non-Compose call site you MUST call SceneAnimator.stop() in your teardown path.",
        " */",
        "object SceneAnimator {",
        '    private const val TAG = "SceneAnimator"',
        "    private val anims = mutableListOf<(Float) -> Unit>()",
        "    @Volatile private var running = false",
        "",
        "    /** The entity's live TransformComponent, or null if it has none yet. Fetching the existing",
        "     *  component and MUTATING it is the whole point (see the class doc): constructing a new",
        "     *  TransformComponent per entity per frame is the per-tick allocation pressure that ANRs at",
        "     *  scale, and it silently overwrites the axes this animation does not own. */",
        "    private inline fun xform(e: Entity, block: (TransformComponent) -> Unit) {",
        "        e.components.get<TransformComponent>()?.let(block)",
        "    }",
        "",
        "    /** Orbit an entity around [center] in the XZ plane. speed = radians/sec.",
        "     *  Writes POSITION ONLY — rotation and scale are left alone, so orbit composes with spin. */",
        "    fun orbit(e: Entity, center: Vector3, radius: Float, startAngle: Float, speed: Float) {",
        "        anims.add { t ->",
        "            val a = startAngle + speed * t",
        "            xform(e) { it.position = Vector3(center.x + radius * cos(a), center.y, center.z + radius * sin(a)) }",
        "        }",
        "    }",
        "",
        "    /** Spin an entity in place around the Y axis (degrees/sec).",
        "     *  Writes ROTATION ONLY — position and scale are left alone, so spin composes with orbit/bob. */",
        "    fun spin(e: Entity, degPerSec: Float) {",
        "        anims.add { t ->",
        "            xform(e) { it.quaternion = EulerAngles(0f, (degPerSec * t) % 360f, 0f).toQuat() }",
        "        }",
        "    }",
        "",
        "    /** Vertically bob an entity around [base]. period in seconds. Writes POSITION ONLY. */",
        "    fun bob(e: Entity, base: Vector3, amplitude: Float, period: Float) {",
        "        anims.add { t ->",
        "            val y = base.y + amplitude * sin((6.2831853f * t) / period)",
        "            xform(e) { it.position = Vector3(base.x, y, base.z) }",
        "        }",
        "    }",
        "",
        "    // ---- material-parameter FX (verified on the emulator: energy pulse / fade / color cycle) ----",
        "    /** Pulse a PBR material's EMISSIVE color between [low] and [high] — glowing energy/reactor core. */",
        "    fun pulseEmissive(mat: PhysicallyBasedMaterial, low: Color4, high: Color4, period: Float) {",
        "        anims.add { t ->",
        "            val p = 0.5f + 0.5f * sin((6.2831853f * t) / period)",
        "            mat.setEmissiveColor(Color4(low.red + (high.red - low.red) * p, low.green + (high.green - low.green) * p,",
        "                low.blue + (high.blue - low.blue) * p, 1f))",
        "        }",
        "    }",
        "",
        "    /** Fade a PBR material's OPACITY between [min] and [max] — hologram fade.",
        "     *  Sets BlendingMode.TRANSPARENT itself: a PBR material is OPAQUE by default",
        "     *  (PhysicallyBasedMaterial.kt:651), so setOpacity on an opaque material is a SILENT NO-OP.",
        "     *  Call restoreOpaque(mat) when the fade is done if the material must render solid again. */",
        "    fun fadeOpacity(mat: PhysicallyBasedMaterial, min: Float, max: Float, period: Float) {",
        "        mat.setBlendingMode(BlendingMode.TRANSPARENT)",
        "        anims.add { t -> mat.setOpacity(min + (max - min) * (0.5f + 0.5f * sin((6.2831853f * t) / period))) }",
        "    }",
        "",
        "    /** Undo fadeOpacity's blending change (PICO restore it the same way — TweenAnimationUtil.kt:258). */",
        "    fun restoreOpaque(mat: PhysicallyBasedMaterial) {",
        "        mat.setOpacity(1f)",
        "        mat.setBlendingMode(BlendingMode.OPAQUE)",
        "    }",
        "",
        "    /** Cycle a PBR material's BASE color through the hue wheel — shifting gem / color shift. */",
        "    fun cycleHue(mat: PhysicallyBasedMaterial, period: Float, saturation: Float = 0.85f) {",
        "        anims.add { t ->",
        "            val a = (6.2831853f * t) / period",
        "            val lo = 1f - saturation",
        "            mat.setBaseColor(Color4(lo + saturation * (0.5f + 0.5f * sin(a)),",
        "                lo + saturation * (0.5f + 0.5f * sin(a + 2.094f)),",
        "                lo + saturation * (0.5f + 0.5f * sin(a + 4.188f)), 1f))",
        "        }",
        "    }",
        "",
        "    /** One-shot REVEAL: grow an entity's Y-scale 0→1 (smoothstep) over [duration]s after [startDelay]s,",
        "     *  anchored so it grows UP from [base] (its bottom stays put). For data-viz bars / reveal-in. */",
        "    fun growY(e: Entity, base: Vector3, fullHeight: Float, duration: Float, startDelay: Float = 0f) {",
        "        anims.add { t ->",
        "            val p = ((t - startDelay) / duration).coerceIn(0f, 1f)",
        "            val s = p * p * (3f - 2f * p)",
        "            xform(e) {",
        "                it.position = Vector3(base.x, base.y + fullHeight * s / 2f, base.z)",
        "                it.scaleVector = Vector3(1f, s.coerceAtLeast(0.001f), 1f)",
        "            }",
        "        }",
        "    }",
        "",
        "    fun clear() { anims.clear() }",
        "",
        "    /** Stop the frame loop. REQUIRED from any non-Compose call site: run() is a suspend loop and",
        "     *  only a cancelled coroutine ends it otherwise. From Compose, LaunchedEffect cancels it for",
        "     *  you on dispose; everywhere else call this from your teardown path. */",
        "    fun stop() { running = false }",
        "",
        "    /** Drive the animation loop. Call from LaunchedEffect(Unit) { SceneAnimator.run() }. Safe to start",
        "     *  before anims are registered — the loop reads the shared list each frame and picks them up.",
        "     *  Ends on stop() or on coroutine cancellation (delay() is a cancellation point). */",
        "    suspend fun run(fps: Int = 60) {",
        "        val t0 = System.nanoTime()",
        "        val frameMs = (1000L / fps).coerceAtLeast(8L)",
        "        var announced = false",
        "        running = true",
        "        try {",
        "            while (running) {",
        "                val t = (System.nanoTime() - t0) / 1_000_000_000f",
        "                if (!announced && anims.isNotEmpty()) { announced = true; Log.i(TAG, \"animating \" + anims.size + \" entities\") }",
        "                withContext(Dispatchers.Main) { for (a in anims) runCatching { a(t) } }",
        "                delay(frameMs)",
        "            }",
        "        } finally {",
        "            running = false",
        "            Log.i(TAG, \"animation loop stopped\")",
        "        }",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
