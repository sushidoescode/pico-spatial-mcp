import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok, fail } from "./util.js";

/**
 * display.ts — v4.8 display control + portals.
 *
 * Source-verified facts (SDK 0.13.3):
 *  - OpacityControllerComponent(opacity: Float = 1f) — fades the entity AND its descendants
 *    (coerced to [0,1]). VISION (a renderable dims/disappears across captures).
 *  - LookAtComponent() + lookAtForwardDirection + alignLocalUpToWorldUp + setViewerAsTarget() /
 *    setEntityAsTarget(e) / clearTarget(). Entity-target is VISION on the emulator; viewer-target
 *    faces the HMD which is decoupled from the free cam (C2) — verify viewer mode on the headset.
 *  - DrawOrderGroupComponent(group: DrawOrderGroup, order: Int); DrawOrderGroup.create(). VISION
 *    with two overlapping renderables in the same group.
 *  - PortalComponent(targetEntity, enable, doubleSide, allowClipping, allowEntityCrossing) on the
 *    same entity as a ModelComponent(quadMesh, PortalMaterial()); the target is a PortalWorldComponent
 *    root. TOPOLOGY: the portal entity must be a SIBLING/PARENT of the world, NEVER its child.
 *    The window + nested world are VISION (aim the cam at the forward face); crossing/PASSTHROUGH
 *    are headset-only.
 */
export function registerDisplayTools(server: McpServer) {
  // ── generate_display_controllers_kotlin ────────────────────────────────────
  server.registerTool(
    "generate_display_controllers_kotlin",
    {
      description:
        "Emit SceneDisplay.kt — display-control helpers: OpacityControllerComponent (hierarchical fade 0..1), LookAtComponent billboarding (face the viewer/HMD or another entity, with forward-axis + up-align), and DrawOrderGroupComponent (explicit render layering for overlapping renderables). Compiles against the SDK. Opacity + draw-order + entity-target billboarding are vision-verifiable on the emulator; viewer-target billboarding faces the HMD (decoupled from the free cam, C2) so verify that mode on the headset.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        forwardDirection: z.enum(["NEGATIVE_Z", "POSITIVE_Z"]).optional().describe("Which local axis LookAt treats as 'forward' (default NEGATIVE_Z — correct for most quads/text)."),
      },
    },
    async ({ packageName, forwardDirection }) => {
      const fwd = forwardDirection ?? "NEGATIVE_Z";
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.DrawOrderGroup",
        "import com.pico.spatial.core.ecs.DrawOrderGroupComponent",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.LookAtComponent",
        "import com.pico.spatial.core.ecs.LookAtForwardDirection",
        "import com.pico.spatial.core.ecs.OpacityControllerComponent",
        "",
        "/**",
        " * Generated by generate_display_controllers_kotlin. Opacity fades, LookAt billboarding, and",
        " * draw-order layering. All @MainThread. VERIFY: compiles; opacity/draw-order/entity-target",
        " * billboarding are vision-verifiable; viewer-target faces the HMD (headset).",
        " */",
        "object SceneDisplay {",
        '    private const val TAG = "SceneDisplay"',
        "",
        "    /** Fade [entity] and ALL its descendants (opacity coerced to 0..1). Needs a renderable to be visible. */",
        "    fun setOpacity(entity: Entity, opacity: Float) {",
        "        runCatching { entity.components.set(OpacityControllerComponent(opacity)) }",
        "            .onFailure { Log.e(TAG, \"opacity failed: ${it.message}\") }",
        "    }",
        "",
        "    /** Billboard [entity] to continuously face the viewer (HMD). Headset behavior (HMD != free cam). */",
        "    fun billboardToViewer(entity: Entity) {",
        "        runCatching {",
        "            val look = LookAtComponent()",
        `            look.lookAtForwardDirection = LookAtForwardDirection.${fwd}`,
        "            look.alignLocalUpToWorldUp = true",
        "            entity.components.set(look)",
        "            look.setViewerAsTarget()",
        "        }.onFailure { Log.e(TAG, \"billboardToViewer failed: ${it.message}\") }",
        "    }",
        "",
        "    /** Billboard [entity] to continuously face [target] (vision-verifiable: move the target, capture). */",
        "    fun billboardToEntity(entity: Entity, target: Entity) {",
        "        runCatching {",
        "            val look = LookAtComponent()",
        `            look.lookAtForwardDirection = LookAtForwardDirection.${fwd}`,
        "            look.alignLocalUpToWorldUp = true",
        "            entity.components.set(look)",
        "            look.setEntityAsTarget(target)",
        "        }.onFailure { Log.e(TAG, \"billboardToEntity failed: ${it.message}\") }",
        "    }",
        "",
        "    /** Create a draw-order group; put overlapping renderables in the SAME group with different orders. */",
        "    fun newGroup(): DrawOrderGroup = DrawOrderGroup.create()",
        "",
        "    /** Assign [entity] (a ModelComponent/ParticleComponent) to [group] at [order] (higher = on top). */",
        "    fun setDrawOrder(entity: Entity, group: DrawOrderGroup, order: Int) {",
        "        runCatching { entity.components.set(DrawOrderGroupComponent(group, order)) }",
        "            .onFailure { Log.e(TAG, \"setDrawOrder failed: ${it.message}\") }",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );

  // ── generate_portal_kotlin ─────────────────────────────────────────────────
  server.registerTool(
    "generate_portal_kotlin",
    {
      description:
        "Emit ScenePortal.kt — a portal window that renders a nested world (PortalWorldComponent root) seen through a quad with a PortalMaterial + PortalComponent. Pass a quad MeshResource for the window and a lambda that populates the nested world; the helper enforces the topology rule (portal is a SIBLING of the world, never its child). Compiles against the SDK; the portal window + nested world are vision-verifiable (aim the cam at the forward face). Entity-crossing and PASSTHROUGH background are headset-only.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        position: z.array(z.number()).optional().describe("Portal window world position [x,y,z] (default [0,1.4,-2])."),
        doubleSide: z.boolean().optional().describe("Render the portal from both sides (default false — aim the cam at the forward face)."),
      },
    },
    async ({ packageName, position, doubleSide }) => {
      if (position && position.length !== 3) return fail("position must be [x,y,z] (3 numbers).");
      const p = (position ?? [0, 1.4, -2]) as number[];
      const ds = doubleSide === true;
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.ModelComponent",
        "import com.pico.spatial.core.ecs.PortalComponent",
        "import com.pico.spatial.core.ecs.PortalWorldComponent",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.ecs.resource.MeshResource",
        "import com.pico.spatial.core.ecs.resource.PortalMaterial",
        "import com.pico.spatial.core.math.Quat",
        "import com.pico.spatial.core.math.Vector3",
        "",
        "/**",
        " * Generated by generate_portal_kotlin. Builds a portal window onto a nested world.",
        " * Call ScenePortal.build(sceneRoot, quadMesh) { world -> /* add the world's children */ }.",
        " * TOPOLOGY: the portal entity is a SIBLING of the world (both children of sceneRoot), never",
        " * the world's child. VERIFY: compiles; the window + world are vision-verifiable on the",
        " * forward face; entity-crossing/PASSTHROUGH are headset-only.",
        " */",
        "object ScenePortal {",
        '    private const val TAG = "ScenePortal"',
        "",
        "    /** quadMesh = e.g. MeshResource.createPlane(w, h). populateWorld receives the world root to fill. */",
        "    fun build(sceneRoot: Entity, quadMesh: MeshResource, populateWorld: (Entity) -> Unit): Entity? = runCatching {",
        '        val world = Entity().also { it.setName("PortalWorld") }',
        "        world.components.set(PortalWorldComponent())",
        "        populateWorld(world)",
        "        sceneRoot.addChild(world)",
        "",
        '        val portal = Entity().also { it.setName("Portal") }',
        `        portal.components.set(TransformComponent(Vector3(${p[0]}f, ${p[1]}f, ${p[2]}f), Quat.identity(), Vector3(1f, 1f, 1f)))`,
        "        portal.components.set(ModelComponent(quadMesh, PortalMaterial()))",
        "        portal.components.set(",
        "            PortalComponent(",
        "                targetEntity = world,",
        "                enable = true,",
        `                doubleSide = ${ds},`,
        "                allowClipping = true,",
        "                allowEntityCrossing = false, // crossing is headset-only",
        "            )",
        "        )",
        "        sceneRoot.addChild(portal) // SIBLING of world, NOT its child",
        '        Log.i(TAG, "portal built")',
        "        portal",
        "    }.onFailure { Log.e(TAG, \"portal build failed: ${it.message}\") }.getOrNull()",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
