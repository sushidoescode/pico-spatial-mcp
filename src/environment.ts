import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok, fail } from "./util.js";

/**
 * environment.ts — RICH ENVIRONMENT generator (verified on the PICO 0.13 device emulator 2026-06-13).
 *
 * Replaces the flat 360-pano-on-a-sky-sphere workaround with real 3D worlds:
 *   - Gaussian SPLAT (.spz / .ply): PICO 0.13 loads these NATIVELY. This is the photoreal,
 *     full-3D path (e.g. a World Labs Marble export). VERIFIED rendering the real "Decayed
 *     Apartment" (SPZ v2, 1.92M points) in the emulator.
 *   - Textured MESH (GLB): runtime TextureResource + PhysicallyBasedMaterial + ModelComponent.
 *     Beats the "GLB textures render black" gap, which is caused by the bundle/USD pack path not
 *     driving gltfio's async texture loader — runtime TextureResource binds the Filament sampler
 *     synchronously instead.
 *
 * Both mirror the runtime-attach pattern that solved the collider: load the Resource off-main,
 * attach the Component via entity.components.set(...) on Dispatchers.Main, then content.addEntity.
 *
 * KEY GOTCHAS baked in:
 *   - spatialbundle CANNOT pack splats → ship the .spz raw (FROM_STORAGE via adb push, or
 *     FROM_ASSETS in app/src/main/assets to ride in the APK).
 *   - Splats have NO collision → keep a separate primitive-box collider rig for Scene.rayCast.
 *   - Marble's coordinate frame differs from PICO Y-up: the room interior is toward -Z, so rotate
 *     ~180° about Y (decode the .spz bbox to confirm); tune live before baking the default.
 *   - GaussianSplattingComponent has ONLY a no-arg ctor + a `gaussianSplattingResource` setter
 *     (construct-then-set), unlike CollisionComponent which takes ctor args.
 *   - Non-base-color textures (normal/metallic-roughness/AO) need TextureCreateOption
 *     colorSpace=RAW / encoding=LINEAR or they gamma-decode wrong; base color is fine by default.
 */

const vec3 = z.object({ x: z.number(), y: z.number(), z: z.number() });
const eulerDeg = z.object({ x: z.number(), y: z.number(), z: z.number() });

function f(n: number): string {
  return `${n}f`;
}

function header(pkg: string): string[] {
  return [
    `package ${pkg}`,
    "",
    "import android.util.Log",
    "import com.pico.spatial.core.ecs.Entity",
    "import com.pico.spatial.core.ecs.LoadType",
    "import com.pico.spatial.core.ecs.TransformComponent",
    "import com.pico.spatial.core.math.EulerAngles",
    "import com.pico.spatial.core.math.Vector3",
  ];
}

function splatKotlin(pkg: string, fileName: string, delivery: string, t: any): string {
  const L = header(pkg);
  L.push("import com.pico.spatial.core.ecs.GaussianSplattingComponent");
  L.push("import com.pico.spatial.core.ecs.resource.GaussianSplattingResource");
  L.push("import kotlinx.coroutines.Dispatchers");
  L.push("import kotlinx.coroutines.withContext");
  L.push("");
  L.push("/**");
  L.push(" * Generated by pico-spatial-mcp generate_environment_kotlin — VERIFIED Gaussian-splat environment.");
  L.push(" * Call from SpatialView.initial (a coroutine):  SplatEnvironment.load(externalFilesPath) { content.addEntity(it) }");
  L.push(` * Deliver the asset (${delivery}): ${delivery === "storage"
    ? `adb push your.spz /sdcard/Android/data/<pkg>/files/${fileName}`
    : `place your.spz at app/src/main/assets/${fileName}`}`);
  L.push(" * Splats have NO collision — keep a primitive box-collider rig for Scene.rayCast pin placement.");
  L.push(" */");
  L.push("object SplatEnvironment {");
  L.push('    private const val TAG = "SplatEnvironment"');
  L.push(`    private const val FILE = ${JSON.stringify(fileName)}`);
  L.push("");
  L.push("    /** externalFilesPath: pass context.getExternalFilesDir(null)?.absolutePath (capture it where a Context exists). */");
  L.push("    suspend fun load(externalFilesPath: String?, add: (Entity) -> Unit) {");
  if (delivery === "storage") {
    L.push("        val path = externalFilesPath?.let { \"$it/$FILE\" }");
    L.push("        if (path == null || !java.io.File(path).exists()) { Log.w(TAG, \"splat not found at $path\"); return }");
    L.push("        val loadType = LoadType.FROM_STORAGE");
  } else {
    L.push("        val path = FILE   // relative to app/src/main/assets");
    L.push("        val loadType = LoadType.FROM_ASSETS");
  }
  L.push("        runCatching {");
  L.push("            val splat = withContext(Dispatchers.IO) { GaussianSplattingResource.load(path, loadType) }");
  L.push("            withContext(Dispatchers.Main) {");
  L.push("                val e = Entity()");
  L.push('                e.setName("SplatEnvironment")');
  L.push(`                e.components.set(TransformComponent(Vector3(${f(t.translate.x)}, ${f(t.translate.y)}, ${f(t.translate.z)}), EulerAngles(${f(t.rotationEuler.x)}, ${f(t.rotationEuler.y)}, ${f(t.rotationEuler.z)}), Vector3(${f(t.scale)}, ${f(t.scale)}, ${f(t.scale)})))`);
  L.push("                val gc = GaussianSplattingComponent()");
  L.push("                gc.gaussianSplattingResource = splat   // construct-then-set (no resource ctor)");
  L.push("                e.components.set(gc)");
  L.push("                add(e)");
  L.push('                Log.i(TAG, "splat environment attached")');
  L.push("            }");
  L.push('        }.onFailure { Log.e(TAG, "splat load failed: ${it.message}", it) }');
  L.push("    }");
  L.push("}");
  L.push("");
  return L.join("\n");
}

function texturedMeshKotlin(pkg: string, glb: string, _baseColor: string, _delivery: string, t: any): string {
  // The model is delivered as a BAKED bundle (bake it first with the bake_textured_model tool):
  //   raw GLB renders BLACK at runtime; the spatialbundle-baked model renders textured. (VERIFIED on device.)
  const stem = glb.replace(/\.(glb|gltf|usd|usda|usdc|usdz)$/i, "");
  const bundle = `${stem}.bundle`;
  const L = header(pkg);
  L.push("import com.pico.spatial.core.ecs.resource.AssetBundle");
  L.push("import kotlinx.coroutines.Dispatchers");
  L.push("import kotlinx.coroutines.withContext");
  L.push("");
  L.push("/**");
  L.push(" * Generated by pico-spatial-mcp generate_environment_kotlin — BAKED textured-mesh environment.");
  L.push(" * Renders the texture (sharp, any scale, real geometry) by loading a spatialbundle-BAKED model.");
  L.push(` * FIRST bake it:  bake_textured_model(modelPath=<your ${glb}>, outBundle=app/src/main/assets/${bundle})`);
  L.push(" * (Do NOT runtime-load the raw GLB — it renders black; and never `references=@x.glb@` in a USDA.)");
  L.push(" */");
  L.push("object MeshEnvironment {");
  L.push('    private const val TAG = "MeshEnvironment"');
  L.push(`    private const val BUNDLE = "asset://${bundle}"`);
  L.push(`    private const val MODEL = ${JSON.stringify(stem)}   // model name inside the baked bundle (the file stem)`);
  L.push("");
  L.push("    /** Call from SpatialView.initial (a coroutine):  MeshEnvironment.load { content.addEntity(it) }");
  L.push("     *  Mesh colliders don't register on-device, so pair this with a box-collider rig for Scene.rayCast. */");
  L.push("    suspend fun load(add: (Entity) -> Unit) {");
  L.push("        runCatching {");
  L.push("            val bundle = withContext(Dispatchers.IO) { AssetBundle.load(BUNDLE) }");
  L.push("            val e = Entity.loadSuspend(MODEL, bundle)   // the BAKED model -> renders textured");
  L.push("            withContext(Dispatchers.Main) {");
  L.push("                e.setName(\"MeshEnvironment\")");
  L.push(`                e.components.get(TransformComponent::class.java)?.setPosition(Vector3(${f(t.translate.x)}, ${f(t.translate.y)}, ${f(t.translate.z)}))`);
  L.push("                add(e)");
  L.push('                Log.i(TAG, "baked textured mesh attached")');
  L.push("            }");
  L.push('        }.onFailure { Log.e(TAG, "mesh env load failed: ${it.message}", it) }');
  L.push("    }");
  L.push("}");
  L.push("");
  return L.join("\n");
}

export function registerEnvironmentTools(server: McpServer) {
  server.registerTool(
    "generate_environment_kotlin",
    {
      description:
        "Emit verified, drop-in Kotlin to load a RICH 3D environment into a native PICO app — replacing the flat 360-pano. kind='splat' loads a Gaussian splat (.spz/.ply, e.g. a World Labs Marble export) which PICO 0.13 supports NATIVELY (photoreal, full-3D; VERIFIED on emulator with a 1.92M-point Marble world). kind='texturedMesh' loads a spatialbundle-BAKED model (sharp at ANY scale, real geometry, walkable; VERIFIED on emulator). For texturedMesh, FIRST bake the model with the bake_textured_model tool (raw-GLB runtime loading renders BLACK; the baked model renders textured). Returns the Kotlin + integration notes. NOTE: mesh colliders don't register on-device, so pair either environment with a primitive box-collider rig (generate_collider_kotlin) for Scene.rayCast.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.claimsight.content"),
        kind: z.enum(["splat", "texturedMesh"]).default("splat"),
        assetFileName: z.string().describe("Splat: the .spz/.ply filename (e.g. marble_apartment.spz). Mesh: the .glb filename."),
        baseColorImage: z.string().optional().describe("texturedMesh only: the base-color PNG/JPG filename"),
        delivery: z.enum(["storage", "assets"]).default("storage").describe("storage = adb push to the app's external files dir (no rebuild to iterate); assets = ship in the APK (app/src/main/assets)"),
        translate: vec3.optional().describe("environment translation (default 0,0,0)"),
        rotationEuler: eulerDeg.optional().describe("environment euler degrees — Marble splats usually need y=180 (room faces -Z); default 0,180,0 for splat, 0,0,0 for mesh"),
        scale: z.number().optional().describe("uniform scale (default 1)"),
      },
    },
    async ({ packageName, kind, assetFileName, baseColorImage, delivery, translate, rotationEuler, scale }) => {
      const t = {
        translate: translate ?? { x: 0, y: 0, z: 0 },
        rotationEuler: rotationEuler ?? { x: 0, y: kind === "splat" ? 180 : 0, z: 0 },
        scale: scale ?? 1,
      };
      if (kind === "texturedMesh" && !baseColorImage) {
        return fail("texturedMesh requires baseColorImage (the base-color PNG/JPG filename).");
      }
      const kotlin = kind === "splat"
        ? splatKotlin(packageName, assetFileName, delivery, t)
        : texturedMeshKotlin(packageName, assetFileName, baseColorImage!, delivery, t);
      const deliveryCmd = delivery === "storage"
        ? `// DELIVER: adb -s <serial> push <local-asset> /sdcard/Android/data/<package>/files/${assetFileName}` +
          (kind === "texturedMesh" ? `\n//          adb push <base-color> /sdcard/Android/data/<package>/files/${baseColorImage}` : "")
        : `// DELIVER: copy the asset(s) into app/src/main/assets/ (rides in the APK; needs a rebuild)`;
      const notes = [
        "// ---- INTEGRATION ----",
        `// 1. Save this file in the package above.`,
        deliveryCmd,
        `// 2. Capture the files dir where a Context exists (e.g. Application.onCreate):`,
        `//      externalFilesPath = getExternalFilesDir(null)?.absolutePath`,
        `// 3. In SpatialView.initial (a coroutine), after the scene loads:`,
        kind === "splat"
          ? `//      SplatEnvironment.load(externalFilesPath) { content.addEntity(it) }`
          : `//      MeshEnvironment.load { content.addEntity(it) } (bake first with bake_textured_model)`,
        kind === "splat"
          ? `// 4. Splats have NO collision: also attach a primitive box-collider rig (generate_collider_kotlin) for Scene.rayCast.`
          : `// 4. Tune translate/rotation/scale so the camera sits inside; decode a splat .spz bbox or eyeball the GLB.`,
        `// VERIFY: assert_logcat for the 'attached' line; window-capture (gui_capture) to see it render.`,
      ].join("\n");
      return ok(`${kotlin}\n${notes}`);
    },
  );
}
