import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * databinding.ts — v5.0 DATA-BINDING primitive (third of the three brief-to-app compiler prerequisites).
 *
 * LOAD-BEARING SDK CONSTRAINT (source-verified): there is NO public TextComponent in SDK 0.13.3 — runtime
 * text cannot be drawn. So a data-bound card's per-item VISUAL is a TINTED QUAD (UnlitMaterial baseColor
 * from the item's color) and/or a BAKED per-item texture selected by name (bake_textured_model →
 * setBaseColorTexture). Dynamic text labels are therefore a bake-time concern, NOT runtime. This primitive
 * honestly wires: JSON parse → DataItem list → a tinted-quad card factory + a data lookup, and composes
 * with SceneLayout (place the cards) and SceneInteraction (select → detail lookup).
 *
 * Verified signatures used:
 *  - JSON via Android's built-in org.json (JSONArray/JSONObject) — no extra Gradle dependency.
 *  - context.assets.open(path) for bundled JSON.
 *  - MeshResource.createPlane(width, height, cornerRadius) ; UnlitMaterial.create().setBaseColor(Color4)
 *  - Color4(r,g,b,a) ; ModelComponent(mesh, material) ; Entity()/setName/components.set.
 *
 * VERIFY: compiles; "N JSON items → N tinted cards" is vision-verifiable (LOOK at the laid-out row); a
 * detail-card lookup after select(id) is vision + structural. Baked-texture labels are asset-gated.
 */
export function registerDataBindingTools(server: McpServer) {
  server.registerTool(
    "generate_data_binding_kotlin",
    {
      description:
        "Emit SceneDataBinding.kt — bind a bundled JSON catalog to N spatial cards. Parses an assets JSON array (org.json, no extra deps) into DataItems, exposes byId/byIndex/all lookups, and provides makeCard(item) — a tinted-quad Entity factory you hand to SceneLayout.place. KEY CONSTRAINT baked in: SDK 0.13.3 has NO TextComponent, so per-item visuals are UnlitMaterial baseColor (from item.color / #hex) and/or a BAKED per-item texture selected by name — dynamic text labels are a bake-time concern, not runtime. Composes with generate_layout_kotlin (placement) + generate_interaction_kotlin (select→detail lookup). Compiles against SDK 0.13.3; 'N items → N tinted cards' is vision-verifiable, baked-texture labels are asset-gated.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        cardWidth: z.number().optional().describe("Card quad width in meters (default 0.5)."),
        cardHeight: z.number().optional().describe("Card quad height in meters (default 0.7)."),
        defaultColor: z.array(z.number()).optional().describe("Fallback card color [r,g,b] 0..1 when an item has none (default [0.8,0.8,0.85])."),
      },
    },
    async ({ packageName, cardWidth, cardHeight, defaultColor }) => {
      const w = cardWidth ?? 0.5;
      const h = cardHeight ?? 0.7;
      const dc = (defaultColor && defaultColor.length === 3 ? defaultColor : [0.8, 0.8, 0.85]) as number[];
      const kt = [
        `package ${packageName}`,
        "",
        "import android.content.Context",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.ModelComponent",
        "import com.pico.spatial.core.ecs.resource.MeshResource",
        "import com.pico.spatial.core.ecs.resource.UnlitMaterial",
        "import com.pico.spatial.core.math.Color4",
        "import org.json.JSONArray",
        "import org.json.JSONObject",
        "",
        "/**",
        " * Generated by generate_data_binding_kotlin. Binds a bundled JSON catalog to N spatial cards.",
        " * NO TextComponent in the SDK → per-item visual is a TINTED QUAD (item color) and/or a baked",
        " * texture selected by name; dynamic text is a bake-time concern. Compose with SceneLayout +",
        " * SceneInteraction:",
        " *   val items = SceneDataBinding.loadItems(context, \"data/items.json\")",
        " *   SceneLayout.place(root, items.size) { i -> SceneDataBinding.makeCard(items[i]) }",
        " *   // on select: SceneDataBinding.byId(id)?.let { showDetail(it) }",
        " * items.json = array of { id, label, color:[r,g,b]? | colorHex:\"#RRGGBB\"?, texture:\"name.png\"? }.",
        " */",
        "object SceneDataBinding {",
        '    private const val TAG = "SceneDataBinding"',
        "",
        "    /** One catalog row. `raw` keeps the full JSON object for any extra brief-specific fields. */",
        "    data class DataItem(",
        "        val id: String,",
        "        val label: String,",
        "        val color: Color4?,",
        "        val texture: String?,",
        "        val raw: JSONObject,",
        "    )",
        "",
        `    var cardWidth: Float = ${w}f`,
        `    var cardHeight: Float = ${h}f`,
        "    private var items: List<DataItem> = emptyList()",
        "",
        "    /** Parse a JSON array asset (e.g. \"data/items.json\") from app assets into DataItems. */",
        "    fun loadItems(context: Context, assetPath: String): List<DataItem> {",
        "        val parsed = runCatching {",
        "            val text = context.assets.open(assetPath).bufferedReader().use { it.readText() }",
        "            parse(text)",
        "        }.onFailure { Log.e(TAG, \"loadItems('$assetPath') failed: ${it.message}\") }.getOrDefault(emptyList())",
        "        Log.i(TAG, \"loaded ${parsed.size} items from $assetPath\")",
        "        return parsed",
        "    }",
        "",
        "    /** Parse a JSON array string into DataItems (use when the JSON is already in memory). */",
        "    fun parse(json: String): List<DataItem> {",
        "        val arr = JSONArray(json)",
        "        val out = ArrayList<DataItem>(arr.length())",
        "        for (i in 0 until arr.length()) {",
        "            val o = arr.optJSONObject(i) ?: continue",
        "            val id = o.optString(\"id\", \"item$i\")",
        "            val label = o.optString(\"label\", id)",
        "            val texture = if (o.has(\"texture\")) o.optString(\"texture\") else null",
        "            out.add(DataItem(id, label, colorOf(o), texture, o))",
        "        }",
        "        items = out",
        "        return out",
        "    }",
        "",
        "    fun all(): List<DataItem> = items",
        "    fun byId(id: String): DataItem? = items.firstOrNull { it.id == id }",
        "    fun byIndex(i: Int): DataItem? = items.getOrNull(i)",
        "",
        "    /** Build a tinted-quad Entity for [item] — hand this to SceneLayout.place as the factory. */",
        "    fun makeCard(item: DataItem): Entity {",
        "        val e = Entity()",
        "        e.setName(\"card_${'$'}{item.id}\")",
        "        runCatching {",
        "            val mesh = MeshResource.createPlane(cardWidth, cardHeight, 0.02f)",
        "            val mat = UnlitMaterial.create()",
        `            mat.setBaseColor(item.color ?: Color4(${dc[0]}f, ${dc[1]}f, ${dc[2]}f, 1f))`,
        "            e.components.set(ModelComponent(mesh, mat))",
        "        }.onFailure { Log.e(TAG, \"makeCard '${'$'}{item.id}' failed: ${it.message}\") }",
        "        return e",
        "    }",
        "",
        "    private fun colorOf(o: JSONObject): Color4? {",
        "        o.optJSONArray(\"color\")?.let { c ->",
        "            if (c.length() >= 3) return Color4(",
        "                c.optDouble(0, 1.0).toFloat(),",
        "                c.optDouble(1, 1.0).toFloat(),",
        "                c.optDouble(2, 1.0).toFloat(),",
        "                if (c.length() >= 4) c.optDouble(3, 1.0).toFloat() else 1f,",
        "            )",
        "        }",
        "        val hex = o.optString(\"colorHex\", \"\")",
        "        if (hex.startsWith(\"#\") && hex.length >= 7) {",
        "            return runCatching {",
        "                Color4(",
        "                    hex.substring(1, 3).toInt(16) / 255f,",
        "                    hex.substring(3, 5).toInt(16) / 255f,",
        "                    hex.substring(5, 7).toInt(16) / 255f,",
        "                    1f,",
        "                )",
        "            }.getOrNull()",
        "        }",
        "        return null",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
