import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * databinding.ts — v5.0 DATA-BINDING primitive (third of the three brief-to-app compiler prerequisites).
 *
 * LOAD-BEARING SDK CONSTRAINT (source-verified): there is NO public TextComponent in SDK 0.13.3 — runtime
 * text cannot be drawn. So a data-bound card's per-item VISUAL is a TINTED QUAD (UnlitMaterial baseColor
 * from the item's color) and/or a BAKED per-item texture selected by name (bake_textured_model →
 * setBaseColorTexture). Dynamic text labels are therefore a bake-time concern, NOT runtime. This primitive
 * honestly wires: JSON parse → DataItem list → a tinted-quad card factory + a data lookup, and composes
 * with SceneLayout (place the cards) and SceneInteraction (select → detail lookup).
 *
 * Verified signatures used:
 *  - JSON via Android's built-in org.json (JSONArray/JSONObject) — no extra Gradle dependency.
 *  - context.assets.open(path) for bundled JSON.
 *  - MeshResource.createPlane(width, height, cornerRadius) ; UnlitMaterial.create().setBaseColor(Color4)
 *  - Color4(r,g,b,a) ; ModelComponent(mesh, material) ; Entity()/setName/components.set.
 *
 * VERIFY: compiles; "N JSON items → N tinted cards" is vision-verifiable (LOOK at the laid-out row); a
 * detail-card lookup after select(id) is vision + structural. Baked-texture labels are asset-gated.
 */
export function registerDataBindingTools(server: McpServer) {
  server.registerTool(
    "generate_data_binding_kotlin",
    {
      description:
        "Emit SceneDataBinding.kt — bind a bundled JSON catalog to N spatial cards OR N real textured 3D models. Parses an assets JSON array (org.json, no extra deps) into DataItems (id/label/color/texture/model), exposes byId/byIndex/all lookups, and provides TWO factories you hand to SceneLayout.place: makeCard(item) → a tinted-quad Entity, and makeModelCard(item) → a container that ASYNC-loads item.model (a baked .bundle from import_model_catalog) as a real textured model via AssetBundle.load + Entity.loadSuspend (off-main load, Main attach — the proven runtime-attach pattern), showing a tinted placeholder quad until it arrives. KEY CONSTRAINT: SDK 0.13.3 has NO TextComponent for IN-SCENE 3D, so per-item 3D-card text is a bake-time concern (for LIVE/dynamic text — HUD, scoreboards, detail — use generate_panel_compose_kotlin, a 2D panel activity: the no-TextComponent limit is in-scene-3D only, v9.4); raw-GLB runtime loads render BLACK, so models MUST be baked first (bake_textured_model / import_model_catalog). Composes with generate_layout_kotlin (placement) + generate_interaction_kotlin (select→detail). Compiles against SDK 0.13.3; 'N items → N tinted cards' and 'N items → N textured models' are both vision-verifiable. RETURNS: raw Kotlin text (write it to the targetPath yourself).",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        cardWidth: z.number().optional().describe("Card quad width in meters (default 0.5)."),
        cardHeight: z.number().optional().describe("Card quad height in meters (default 0.7)."),
        defaultColor: z.array(z.number()).optional().describe("Fallback card color [r,g,b] 0..1 when an item has none (default [0.8,0.8,0.85])."),
      },
    },
    async ({ packageName, cardWidth, cardHeight, defaultColor }) => {
      const w = cardWidth ?? 0.5;
      const h = cardHeight ?? 0.7;
      const dc = (defaultColor && defaultColor.length === 3 ? defaultColor : [0.8, 0.8, 0.85]) as number[];
      const kt = [
        `package ${packageName}`,
        "",
        "import android.content.Context",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.LoadType",
        "import com.pico.spatial.core.ecs.ModelComponent",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.ecs.resource.AssetBundle",
        "import com.pico.spatial.core.ecs.resource.MaterialCullingMode",
        "import com.pico.spatial.core.ecs.resource.MeshResource",
        "import com.pico.spatial.core.ecs.resource.PhysicallyBasedMaterial",
        "import com.pico.spatial.core.ecs.resource.TextureResource",
        "import com.pico.spatial.core.ecs.resource.UnlitMaterial",
        "import com.pico.spatial.core.math.Color4",
        "import com.pico.spatial.core.math.EulerAngles",
        "import com.pico.spatial.core.math.Vector3",
        "import kotlinx.coroutines.CoroutineScope",
        "import kotlinx.coroutines.Dispatchers",
        "import kotlinx.coroutines.SupervisorJob",
        "import kotlinx.coroutines.cancelChildren",
        "import kotlinx.coroutines.launch",
        "import kotlinx.coroutines.withContext",
        "import org.json.JSONArray",
        "import org.json.JSONObject",
        "",
        "/**",
        " * Generated by generate_data_binding_kotlin. Binds a bundled JSON catalog to N spatial cards.",
        " * NO TextComponent in the SDK → per-item visual is a TINTED QUAD (item color) and/or a baked",
        " * texture selected by name; dynamic text is a bake-time concern. Compose with SceneLayout +",
        " * SceneInteraction:",
        " *   val items = SceneDataBinding.loadItems(context, \"data/items.json\")",
        " *   SceneLayout.place(root, items.size) { i -> SceneDataBinding.makeCard(items[i]) }",
        " *   // on select: SceneDataBinding.byId(id)?.let { showDetail(it) }",
        " * items.json = array of { id, label, color:[r,g,b]? | colorHex:\"#RRGGBB\"?, texture:\"name.png\"? }.",
        " */",
        "object SceneDataBinding {",
        '    private const val TAG = "SceneDataBinding"',
        "",
        "    /** One catalog row. `raw` keeps the full JSON object for any extra brief-specific fields. */",
        "    data class DataItem(",
        "        val id: String,",
        "        val label: String,",
        "        val color: Color4?,",
        "        val texture: String?,",
        "        val model: String?,       // a baked .bundle filename (from import_model_catalog) → makeModelCard",
        "        val modelName: String?,   // the model NAME inside the bundle (≠ filename); import_model_catalog emits it",
        "        val raw: JSONObject,",
        "    )",
        "",
        `    var cardWidth: Float = ${w}f`,
        `    var cardHeight: Float = ${h}f`,
        "    var modelScale: Float = 1f   // uniform scale applied to each loaded model (rooms/props differ)",
        "    // v28.3: invoked with the active renderable: the loaded model on success, or the placeholder",
        "    // when no model is declared / loading fails. Lighting and animation must never target the empty container.",
        "    // NOTE: the SDK's animation does NOT propagate through a loaded model's node hierarchy, so rotating",
        "    // a model via a tween is BEST-EFFORT (nested geometry may not move) — quad/primitive animation works.",
        "    var onModelLoaded: ((Entity) -> Unit)? = null",
        "    // v6.6 material system: \"unlit\" (flat tint, no lighting needed) or \"pbr\" (lit by the scene rig,",
        "    // metallic/roughness). A per-item texture (item.texture) forces pbr so the image is lit, and is",
        "    // loaded at RUNTIME via TextureResource (the path that binds the Filament sampler synchronously —",
        "    // beats the bundle-pack 'textures render black' gap). Cards are double-sided (free-cam friendly).",
        "    var materialMode: String = \"unlit\"",
        "    var roughness: Float = 0.6f",
        "    var metallic: Float = 0f",
        "    private var items: List<DataItem> = emptyList()",
        "    // Models load asynchronously (AssetBundle.load off-main, attach on Main) — the proven runtime-attach",
        "    // pattern. A per-item placeholder quad shows until the model arrives, so layout/placement never blocks.",
        "    private val loadScope = CoroutineScope(Dispatchers.Main + SupervisorJob())",
        "",
        "    // v35.5: bundles are CACHED by path and CLOSED in dispose(). Before this, makeModelCard",
        "    // called AssetBundle.load per item and dropped the handle — a 50-item catalog loaded the",
        "    // same bundle up to 50 times and released none. AssetBundle is Closeable (AssetBundle.kt",
        "    // :76-77, close() at :235). WelcomeSpace refcounts by owner because the same model is live",
        "    // in three places at once; here SceneDataBinding is the only owner, so a keyed cache plus",
        "    // one dispose() is the whole requirement.",
        "    private val bundles = mutableMapOf<String, AssetBundle>()",
        "    private val placeholders = mutableListOf<Entity>()",
        "",
        "    private suspend fun bundleFor(path: String): AssetBundle {",
        "        bundles[path]?.let { if (it.valid) return it else bundles.remove(path) }",
        "        val loaded = withContext(Dispatchers.IO) { AssetBundle.load(path) }",
        "        bundles[path] = loaded",
        "        return loaded",
        "    }",
        "",
        "    /**",
        "     * Release everything this object acquired. Call from onDispose / onCleared / ON_PAUSE.",
        "     * Cancels in-flight loads FIRST so a load cannot resurrect a bundle we are closing, then",
        "     * destroys orphaned placeholder quads (a placeholder whose model arrived was removed from",
        "     * the container but never destroyed), then closes the bundles.",
        "     */",
        "    fun dispose() {",
        "        loadScope.coroutineContext.cancelChildren()",
        "        placeholders.forEach { runCatching { it.destroy() } }",
        "        placeholders.clear()",
        "        bundles.values.forEach { runCatching { it.close() } }",
        "        bundles.clear()",
        "        Log.i(TAG, \"SceneDataBinding disposed\")",
        "    }",
        "",
        "    /** Parse a JSON array asset (e.g. \"data/items.json\") from app assets into DataItems. */",
        "    fun loadItems(context: Context, assetPath: String): List<DataItem> {",
        "        val parsed = runCatching {",
        "            val text = context.assets.open(assetPath).bufferedReader().use { it.readText() }",
        "            parse(text)",
        "        }.onFailure { Log.e(TAG, \"loadItems('$assetPath') failed: ${it.message}\") }.getOrDefault(emptyList())",
        "        Log.i(TAG, \"loaded ${parsed.size} items from $assetPath\")",
        "        return parsed",
        "    }",
        "",
        "    /** Parse a JSON array string into DataItems (use when the JSON is already in memory). */",
        "    fun parse(json: String): List<DataItem> {",
        "        val arr = JSONArray(json)",
        "        val out = ArrayList<DataItem>(arr.length())",
        "        for (i in 0 until arr.length()) {",
        "            val o = arr.optJSONObject(i) ?: continue",
        "            val id = o.optString(\"id\", \"item$i\")",
        "            val label = o.optString(\"label\", id)",
        "            val texture = if (o.has(\"texture\")) o.optString(\"texture\") else null",
        "            val model = if (o.has(\"model\")) o.optString(\"model\") else null",
        "            val modelName = if (o.has(\"modelName\")) o.optString(\"modelName\") else null",
        "            out.add(DataItem(id, label, colorOf(o), texture, model, modelName, o))",
        "        }",
        "        items = out",
        "        return out",
        "    }",
        "",
        "    /** Fetch a JSON catalog from a GATED API endpoint on a background thread, parse, call back on main.",
        "     *  NETWORK-GATED: needs <uses-permission android:name=\"android.permission.INTERNET\"/> + a reachable",
        "     *  endpoint. Verify with ONE live call + logcat; flag it network-gated (don't fake). */",
        "    fun loadItemsFromApi(url: String, onLoaded: (List<DataItem>) -> Unit) {",
        "        Thread {",
        "            val json = runCatching {",
        "                val c = (java.net.URL(url).openConnection() as java.net.HttpURLConnection)",
        "                c.connectTimeout = 5000; c.readTimeout = 5000",
        "                c.inputStream.bufferedReader().use { it.readText() }",
        "            }.onFailure { Log.e(TAG, \"api fetch '\" + url + \"' failed: \" + it.message) }.getOrNull()",
        "            val parsed = if (json != null) runCatching { parse(json) }.getOrDefault(emptyList()) else emptyList()",
        "            Log.i(TAG, \"api loaded \" + parsed.size + \" items from \" + url)",
        "            android.os.Handler(android.os.Looper.getMainLooper()).post { onLoaded(parsed) }",
        "        }.start()",
        "    }",
        "",
        "    fun all(): List<DataItem> = items",
        "    fun byId(id: String): DataItem? = items.firstOrNull { it.id == id }",
        "    fun byIndex(i: Int): DataItem? = items.getOrNull(i)",
        "    fun size(): Int = items.size",
        "",
        "    /** Build a card Entity for [item] — hand this to SceneLayout.place as the factory. Unlit tint by",
        "     *  default; pbr (lit) when materialMode=\"pbr\"; a per-item texture (item.texture) is loaded at",
        "     *  runtime onto a lit PBR material so the image shows. Double-sided so the free cam can orbit it. */",
        "    fun makeCard(item: DataItem): Entity {",
        "        val e = Entity()",
        "        e.setName(\"card_\" + item.id)",
        "        runCatching {",
        "            val mesh = MeshResource.createPlane(cardWidth, cardHeight, 0.02f)",
        `            val color = item.color ?: Color4(${dc[0]}f, ${dc[1]}f, ${dc[2]}f, 1f)`,
        "            val usePbr = materialMode == \"pbr\" || item.texture != null   // textures must be lit → pbr",
        "            if (usePbr) {",
        "                val mat = PhysicallyBasedMaterial.create()",
        "                mat.setBaseColor(color)",
        "                mat.setRoughness(roughness)",
        "                mat.setMetallic(metallic)",
        "                mat.setCullingMode(MaterialCullingMode.NONE)",
        "                item.texture?.let { tex ->",
        "                    runCatching { mat.setBaseColorTexture(TextureResource.load(tex, LoadType.FROM_ASSETS)) }",
        "                        .onFailure { Log.w(TAG, \"texture '\" + tex + \"' load failed: \" + it.message) }",
        "                }",
        "                e.components.set(ModelComponent(mesh, mat))",
        "            } else {",
        "                val mat = UnlitMaterial.create()",
        "                mat.setBaseColor(color)",
        "                mat.setCullingMode(MaterialCullingMode.NONE)",
        "                e.components.set(ModelComponent(mesh, mat))",
        "            }",
        "        }.onFailure { Log.e(TAG, \"makeCard '\" + item.id + \"' failed: \" + it.message) }",
        "        return e",
        "    }",
        "",
        "    /** Build a container that ASYNC-loads item.model (a baked .bundle) as a real textured 3D model —",
        "     *  hand this to SceneLayout.place exactly like makeCard. Shows a tinted placeholder quad until the",
        "     *  model arrives (AssetBundle.load off-main → Entity.loadSuspend → attach on Main). If item.model is",
        "     *  null it stays a tinted quad. Bake the models with import_model_catalog (raw GLB renders black). */",
        "    fun makeModelCard(item: DataItem): Entity {",
        "        val container = Entity()",
        "        container.setName(\"model_\" + item.id)",
        "        val placeholder = makeCard(item)   // tinted quad shown until the model loads",
        "        container.addChild(placeholder)",
        "        placeholders.add(placeholder)",
        "        val bundleFile = item.model",
        "        if (bundleFile == null) { onModelLoaded?.invoke(placeholder); Log.w(TAG, \"makeModelCard '\" + item.id + \"' has no model; showing placeholder quad\"); return container }",
        "        // The model NAME inside the bundle (from the baked source's stem) is NOT the bundle filename —",
        "        // use item.modelName when import_model_catalog provides it, else fall back to the filename stem.",
        "        val stem = item.modelName ?: bundleFile.substringAfterLast('/').removeSuffix(\".bundle\")",
        "        val s = modelScale",
        "        loadScope.launch {",
        "            runCatching {",
        "                val bundle = bundleFor(\"asset://\" + bundleFile)   // cached + closed in dispose()",
        "                val model = Entity.loadSuspend(stem, bundle)   // the BAKED model → renders textured",
        "                withContext(Dispatchers.Main) {",
        "                    model.setName(\"mdl_\" + item.id)",
        "                    model.components.set(TransformComponent(Vector3(0f, 0f, 0f), EulerAngles(0f, 0f, 0f), Vector3(s, s, s)))",
        "                    container.removeChild(placeholder)",
        "                    // The placeholder is out of the tree but still a live Entity — destroy it",
        "                    // rather than stranding one per catalog item.",
        "                    runCatching { placeholder.destroy() }",
        "                    placeholders.remove(placeholder)",
        "                    container.addChild(model)",
        "                    onModelLoaded?.invoke(model)   // v7.3: animate/interact the real geometry, not the container",
        "                    Log.i(TAG, \"loaded model \" + item.id + \" (\" + stem + \")\")",
        "                }",
        "            }.onFailure { onModelLoaded?.invoke(placeholder); Log.e(TAG, \"model load '\" + item.id + \"' failed; keeping placeholder: \" + it.message) }",
        "        }",
        "        return container",
        "    }",
        "",
        "    private fun colorOf(o: JSONObject): Color4? {",
        "        o.optJSONArray(\"color\")?.let { c ->",
        "            if (c.length() >= 3) return Color4(",
        "                c.optDouble(0, 1.0).toFloat(),",
        "                c.optDouble(1, 1.0).toFloat(),",
        "                c.optDouble(2, 1.0).toFloat(),",
        "                if (c.length() >= 4) c.optDouble(3, 1.0).toFloat() else 1f,",
        "            )",
        "        }",
        "        val hex = o.optString(\"colorHex\", \"\")",
        "        if (hex.startsWith(\"#\") && hex.length >= 7) {",
        "            return runCatching {",
        "                Color4(",
        "                    hex.substring(1, 3).toInt(16) / 255f,",
        "                    hex.substring(3, 5).toInt(16) / 255f,",
        "                    hex.substring(5, 7).toInt(16) / 255f,",
        "                    1f,",
        "                )",
        "            }.getOrNull()",
        "        }",
        "        return null",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
