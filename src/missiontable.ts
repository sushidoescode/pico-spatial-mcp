  const phaseField = panelField("phase");
  const anchorField = panelField("anchor");
  const surfaceField = panelField("surface");
  const controlLabel = (action: string, fallback: string): string => {
    const interaction = spec.interactions.find((candidate) => candidate.action === action);
    return typeof interaction?.params?.label === "string" && interaction.params.label.trim()
      ? interaction.params.label.trim()
      : fallback;
  };
  // JSON escaping covers quotes/control characters, but Kotlin also interpolates '$' inside a
  // quoted string. Escape that marker after serialization so arbitrary authored copy stays data.
  const ktString = (value: string): string => JSON.stringify(value).replace(/\$/g, "\\$");
  const contentPkg = `${pkg}.content`;
  const cdir = `app/src/main/java/${pkg.replace(/\./g, "/")}/content`;
  const [targetWidth, targetDepth] = profile.targetFootprintM;
  const [tableMinWidth, tableMinDepth] = profile.tableExtentRangeM.min;
  const [tableMaxWidth, tableMaxDepth] = profile.tableExtentRangeM.max;
  const [artMinWidth, artMinHeight] = profile.wallArtExtentRangeM.min;
