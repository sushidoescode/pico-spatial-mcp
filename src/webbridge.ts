import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * webbridge.ts — v10.13 (P11): the WEB ↔ 3D bridge.
 *
 * Fuses the two lanes: an HTML control panel (real buttons/text/CSS — a WebView activity) whose
 * JavaScript drives the NATIVE Filament 3D scene. addJavascriptInterface exposes a `Native` object
 * to the page; `Native.send(cmd)` routes on the main thread to the scene's dispatchDebugCommand
 * (the same channel the GameMenu/broadcasts use), so a web button can throw the physics ball,
 * re-rack, recolor, spawn — anything the scene handles. Same process = a direct call, no IPC.
 */
export function registerWebBridgeTools(server: McpServer) {
  server.registerTool(
    "generate_web_bridge_kotlin",
    {
      description:
        "Emit WebControlPanel.kt (P11) — an HTML CONTROL PANEL whose buttons drive the NATIVE 3D scene. A WebView activity exposes `Native.send(cmd)` (addJavascriptInterface) that routes on the main thread to the scene's dispatchDebugCommand — so a real HTML button throws the physics ball / re-racks / recolors, fusing the web + Filament lanes. Provide controls [{label, cmd}] (cmd = whatever dispatchDebugCommand handles, e.g. 'start','reset','bowl'). WebView debugging is enabled so the panel is CDP-drivable for verification. RETURNS: JSON {kotlin, manifestEntry} — write to content/WebControlPanel.kt, merge manifestEntry; open with `am start -n <pkg>/<contentPkg>.WebControlPanelActivity`.",
      inputSchema: {
        packageName: z.string().describe("Content package, e.g. com.example.app.content (must contain dispatchDebugCommand)."),
        title: z.string().optional().describe("Panel title (default 'CONTROLS')."),
        controls: z.array(z.object({ label: z.string(), cmd: z.string() })).min(1).describe("Buttons: label + the scene command each sends."),
      },
    },
    async ({ packageName, title, controls }) => {
      const appPkg = packageName.replace(/\.content$/, "");
      const t = title ?? "CONTROLS";
      const buttons = controls.map((c) =>
        `<button data-cmd="${c.cmd}" onclick="Native.send('${c.cmd}')">${c.label.replace(/</g, "")}</button>`).join("");
      const html = `<!doctype html><html><head><meta charset=utf-8><style>
html,body{margin:0;height:100%;background:#0b1020;color:#eaf0ff;font-family:-apple-system,Roboto,sans-serif;display:flex;flex-direction:column;justify-content:center;gap:3vh;padding:6vw}
h1{color:#7fd7ff;font-size:8vw;margin:0}
button{font-size:6vw;font-weight:800;padding:5vw;border:none;border-radius:4vw;background:linear-gradient(160deg,#1b8f4a,#0f6a34);color:#fff;box-shadow:0 1vw 3vw rgba(0,0,0,.5)}
button:active{transform:scale(.97)}
button[data-cmd=reset]{background:linear-gradient(160deg,#b53a3a,#7a2222)}
</style></head><body><h1>${t}</h1>${buttons}</body></html>`;
      const kt = [
        `package ${packageName}`,
        ``,
        `import android.annotation.SuppressLint`,
        `import android.os.Bundle`,
        `import android.webkit.JavascriptInterface`,
        `import android.webkit.WebView`,
        `import androidx.activity.ComponentActivity`,
        ``,
        `/**`,
        ` * Generated by generate_web_bridge_kotlin — an HTML control panel that drives the native 3D`,
        ` * scene. Native.send(cmd) routes to dispatchDebugCommand on the UI thread. Open:`,
        ` * am start -n ${appPkg}/${packageName}.WebControlPanelActivity`,
        ` */`,
        `class WebControlPanelActivity : ComponentActivity() {`,
        `    inner class Native {`,
        `        @JavascriptInterface`,
        `        fun send(cmd: String) { runOnUiThread { dispatchDebugCommand(cmd) } }`,
        `    }`,
        `    @SuppressLint("SetJavaScriptEnabled", "JavascriptInterface")`,
        `    override fun onCreate(savedInstanceState: Bundle?) {`,
        `        super.onCreate(savedInstanceState)`,
        `        WebView.setWebContentsDebuggingEnabled(true)`,
        `        val wv = WebView(this)`,
        `        wv.settings.javaScriptEnabled = true`,
        `        wv.addJavascriptInterface(Native(), "Native")`,
        `        wv.loadDataWithBaseURL(null, HTML, "text/html", "utf-8", null)`,
        `        setContentView(wv)`,
        `    }`,
        `    companion object {`,
        `        private val HTML = ${JSON.stringify(html)}`,
        `    }`,
        `}`,
        ``,
      ].join("\n");
      const manifestEntry = `<activity android:name="${packageName}.WebControlPanelActivity" android:exported="true" android:taskAffinity="${appPkg}.controls" android:launchMode="singleTask" />`;
      return ok(JSON.stringify({ kotlin: kt, manifestEntry, note: "Write to content/WebControlPanel.kt; merge manifestEntry; open with am start -n <pkg>/" + packageName + ".WebControlPanelActivity. Buttons call dispatchDebugCommand via the Native JS bridge." }, null, 2));
    },
  );
}
