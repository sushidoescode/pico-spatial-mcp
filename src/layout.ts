import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * layout.ts — v5.0 spatial LAYOUT primitive (the first of the three brief-to-app compiler prerequisites).
 *
 * Source-verified facts (SDK 0.13.3 — read from core/foundation sources, NOT invented):
 *  - `Entity()` no-arg ctor; `entity.setName(s)`; `parent.addChild(entity)`; `entity.components.set(c)`.
 *  - `TransformComponent(position: Vector3, rotation: EulerAngles, scale: Vector3)` IS a real ctor
 *    (also (position, Quat, scale) and (Transform)). EulerAngles(pitch, yaw, roll) is in DEGREES
 *    (its toQuat multiplies by PI/180; extrinsic ZXY). We use the EulerAngles ctor for a clean yaw.
 *  - -Z is forward (the viewer looks down -Z), matching every existing generator + the collider recipe.
 *
 * Positions are computed ANALYTICALLY from geometry (the retained lesson: never eyeball a layout — the
 * game-menu rows were computed, not tuned). The tool bakes the chosen pattern + geometry as defaults;
 * everything is a mutable `var` so a data-driven count (databinding) or a vision-calibration pass can
 * override at runtime without regenerating. VERIFY: compiles; the arrangement is vision-verifiable — aim
 * the free cam at centerZ and LOOK (C2). faceUser yaw sign is vision-calibrated next (yawOffsetDeg knob).
 */
export function registerLayoutTools(server: McpServer) {
  server.registerTool(
    "generate_layout_kotlin",
    {
      description:
        "Emit SceneLayout.kt — an ANALYTICAL spatial layout engine that positions N content entities in a pattern (WALL row / GRID / ARC facing the viewer / SHELF stacked rows). You supply a factory `(index) -> Entity` that returns the content (a baked card/model/quad); SceneLayout computes each slot's position + facing yaw and parents it under the scene root. Positions are derived from geometry (never eyeballed — the retained game-menu lesson). All params are runtime-mutable vars (defaults baked from these inputs) so a data-driven count or a vision-calibration pass can override without regen. Compiles against SDK 0.13.3; the arrangement is vision-verifiable (aim the cam at centerZ and LOOK — C2). RETURNS: raw Kotlin text (write it to the targetPath yourself).",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        pattern: z.enum(["wall", "grid", "arc", "shelf"]).optional().describe("Default layout pattern (default 'arc'). Runtime-overridable per place() call."),
        count: z.number().int().optional().describe("Default item count used by convenience helpers (default 6). place() takes an explicit count."),
        radius: z.number().optional().describe("ARC radius in meters from the viewer (default 2.5)."),
        spacing: z.number().optional().describe("Gap between items in meters for WALL/GRID/SHELF (default 0.6)."),
        columns: z.number().int().optional().describe("GRID columns (default 3)."),
        shelves: z.number().int().optional().describe("SHELF row count (default 2)."),
        centerY: z.number().optional().describe("Vertical center / eye height in meters (default 1.4)."),
        centerZ: z.number().optional().describe("Forward distance in meters for WALL/GRID/SHELF, negative = in front (default -2.5)."),
        arcSpanDeg: z.number().optional().describe("Total angular span of the ARC in degrees (default 90)."),
        faceUser: z.boolean().optional().describe("If true (default), each ARC item is yawed to face the viewer at the origin."),
        yawOffsetDeg: z.number().optional().describe("Extra yaw added to every faced item (default 0) — the vision-calibration knob for the plane-facing convention."),
      },
    },
    async ({ packageName, pattern, count, radius, spacing, columns, shelves, centerY, centerZ, arcSpanDeg, faceUser, yawOffsetDeg }) => {
      const pat = (pattern ?? "arc").toUpperCase();
      const n = count ?? 6;
      const rad = radius ?? 2.5;
      const sp = spacing ?? 0.6;
      const cols = columns ?? 3;
      const shv = shelves ?? 2;
      const cy = centerY ?? 1.4;
      const cz = centerZ ?? -2.5;
      const span = arcSpanDeg ?? 90;
      const face = faceUser ?? true;
      const yawOff = yawOffsetDeg ?? 0;
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.math.EulerAngles",
        "import com.pico.spatial.core.math.Vector3",
        "import kotlin.math.atan2",
        "import kotlin.math.cos",
        "import kotlin.math.sin",
        "",
        "/**",
        " * Generated by generate_layout_kotlin. ANALYTICAL spatial layout — positions are computed from",
        " * geometry, never eyeballed. Patterns: WALL (row), GRID (rows×cols on a plane), ARC (curved row",
        " * facing the viewer), SHELF (stacked rows). Usage:",
        " *   SceneLayout.place(root, items.size) { i -> makeCard(items[i]) }",
        " * where your factory returns the content Entity; SceneLayout positions + (faceUser) yaws it.",
        " * All tunables are vars (defaults baked in) — override before place() for data-driven counts or",
        " * a vision-calibration pass. VERIFY: compiles; arrangement is vision-verifiable (aim cam at centerZ).",
        " */",
        "object SceneLayout {",
        '    private const val TAG = "SceneLayout"',
        "",
        "    enum class Pattern { WALL, GRID, ARC, SHELF }",
        "",
        "    /** A computed placement: where to put an item and how far to yaw it (degrees, about world Y). */",
        "    data class Slot(val position: Vector3, val yawDeg: Float)",
        "",
        "    // Defaults baked from generate_layout_kotlin inputs; mutate before place() to override.",
        `    var pattern: Pattern = Pattern.${pat}`,
        `    var radius: Float = ${rad}f`,
        `    var spacing: Float = ${sp}f`,
        `    var columns: Int = ${cols}`,
        `    var shelves: Int = ${shv}`,
        `    var centerY: Float = ${cy}f`,
        `    var centerZ: Float = ${cz}f`,
        `    var arcSpanDeg: Float = ${span}f`,
        `    var faceUser: Boolean = ${face}`,
        `    var yawOffsetDeg: Float = ${yawOff}f`,
        `    var defaultCount: Int = ${n}`,
        "",
        "    /** Pure math: compute [count] slots in [pattern]. No entities created — safe to inspect/log. */",
        "    fun slots(count: Int, pattern: Pattern = this.pattern): List<Slot> {",
        "        if (count <= 0) return emptyList()",
        "        return when (pattern) {",
        "            Pattern.WALL -> row(count)",
        "            Pattern.GRID -> grid(count)",
        "            Pattern.ARC -> arc(count)",
        "            Pattern.SHELF -> shelf(count)",
        "        }",
        "    }",
        "",
        "    /** Create + position [count] items via [makeItem], parenting each under [root]. Returns placed entities. */",
        "    fun place(",
        "        root: Entity,",
        "        count: Int = defaultCount,",
        "        pattern: Pattern = this.pattern,",
        "        makeItem: (Int) -> Entity,",
        "    ): List<Entity> {",
        "        val out = ArrayList<Entity>(count)",
        "        val computed = slots(count, pattern)",
        "        for (i in 0 until count) {",
        "            val slot = computed[i]",
        "            val e = runCatching { makeItem(i) }.onFailure { Log.e(TAG, \"makeItem $i threw: $it\") }.getOrNull() ?: continue",
        "            runCatching {",
        "                e.components.set(",
        "                    TransformComponent(slot.position, EulerAngles(0f, slot.yawDeg, 0f), Vector3(1f, 1f, 1f)),",
        "                )",
        "                root.addChild(e)",
        "                out.add(e)",
        "            }.onFailure { Log.e(TAG, \"place item $i failed: ${it.message}\") }",
        "        }",
        "        Log.i(TAG, \"placed ${out.size}/$count items in $pattern\")",
        "        return out",
        "    }",
        "",
        "    private fun row(count: Int): List<Slot> {",
        "        val startX = -(count - 1) * spacing / 2f",
        "        return (0 until count).map { i -> Slot(Vector3(startX + i * spacing, centerY, centerZ), 0f) }",
        "    }",
        "",
        "    private fun grid(count: Int): List<Slot> {",
        "        val c = maxOf(1, columns)",
        "        val rows = (count + c - 1) / c",
        "        val startX = -(c - 1) * spacing / 2f",
        "        val startY = centerY + (rows - 1) * spacing / 2f",
        "        return (0 until count).map { i ->",
        "            val col = i % c; val r = i / c",
        "            Slot(Vector3(startX + col * spacing, startY - r * spacing, centerZ), 0f)",
        "        }",
        "    }",
        "",
        "    private fun arc(count: Int): List<Slot> {",
        "        val step = if (count > 1) arcSpanDeg / (count - 1) else 0f",
        "        val start = -arcSpanDeg / 2f",
        "        val deg2rad = (Math.PI / 180.0).toFloat()",
        "        return (0 until count).map { i ->",
        "            val deg = start + i * step",
        "            val a = deg * deg2rad",
        "            val x = radius * sin(a)",
        "            val z = -radius * cos(a) // -Z is forward",
        "            // Yaw so the item turns toward the viewer at the origin (atan2 of the item->origin dir).",
        "            val faceDeg = if (faceUser) atan2(-x, -z) / deg2rad + yawOffsetDeg else 0f",
        "            Slot(Vector3(x, centerY, z), faceDeg)",
        "        }",
        "    }",
        "",
        "    private fun shelf(count: Int): List<Slot> {",
        "        val rows = maxOf(1, shelves)",
        "        val perRow = (count + rows - 1) / rows",
        "        val startX = -(perRow - 1) * spacing / 2f",
        "        val startY = centerY + (rows - 1) * spacing / 2f",
        "        return (0 until count).map { i ->",
        "            val r = i / perRow; val col = i % perRow",
        "            Slot(Vector3(startX + col * spacing, startY - r * spacing, centerZ), 0f)",
        "        }",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
