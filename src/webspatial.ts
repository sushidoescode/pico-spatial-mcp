import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import * as fs from "node:fs";
import * as path from "node:path";
import { okJson } from "./util.js";

/**
 * webspatial.ts — v10.12 (P10): the WebSpatial React compile target.
 *
 * A second, web-native compile lane. Emits a real React + @webspatial/react-sdk project
 * (enable-xr attribute, --xr-back depth CSS var, xr_spatial_scene manifest) that on PICO OS 6 (Swan)
 * activates spatially with ZERO packaging (the OS Web App runtime has WebSpatial built in), and
 * degrades to a plain website everywhere else. Because it degrades, the 2D PROJECTION is
 * verifiable NOW (headless Chrome / the emulator browser); the spatial depth is `built_for_os6`
 * (a new evidence class, mirroring awaiting_swan). Runtime TEXT is free (real HTML/CSS) — this
 * sidesteps the native SDK's no-TextComponent limit entirely.
 */

const esc = (s: string) => s.replace(/</g, "&lt;").replace(/>/g, "&gt;");

type Panel = { title: string; rows?: { label: string; value: string }[]; body?: string; depth?: number; accent?: string };

function previewHtml(title: string, panels: Panel[]): string {
  // The 2D projection: the exact content a non-spatial browser shows. --xr-back depth is hinted as a
  // subtle stacked shadow/offset so the layering is legible in 2D (spatially it's real Z on OS 6).
  const cards = panels.map((p, i) => {
    const depth = p.depth ?? (i + 1) * 20;
    const accent = p.accent ?? ["#7fd7ff", "#7dff9b", "#ff9bce", "#ffd24d"][i % 4];
    const rows = (p.rows ?? []).map((r) => `<div class=row><span class=lbl>${esc(r.label)}</span><span class=val>${esc(r.value)}</span></div>`).join("");
    const body = p.body ? `<div class=body>${p.body}</div>` : "";
    return `<div class="panel" style="--xr-back:${depth}px; box-shadow: 0 ${depth / 2}px ${depth}px rgba(0,0,0,.5), 0 0 0 1px #2a3a6a; transform: translateY(-${i * 6}px);">
      <h2 style="color:${accent}">${esc(p.title)}</h2>${rows}${body}</div>`;
  }).join("\n");
  return `<!doctype html><html><head><meta charset=utf-8><meta name=viewport content="width=device-width,initial-scale=1"><style>
    :root{color-scheme:dark} *{box-sizing:border-box}
    body{margin:0;min-height:100vh;background:radial-gradient(1200px 800px at 50% -10%, #10204a, #05070f);color:#eaf0ff;font-family:-apple-system,'Segoe UI',Roboto,sans-serif;padding:6vh 6vw;display:flex;flex-direction:column;gap:3vh}
    h1{font-size:5vh;margin:0 0 2vh;color:#cfe0ff;letter-spacing:.5px}
    .grid{display:flex;flex-wrap:wrap;gap:3vh}
    .panel{flex:1 1 320px;min-width:280px;background:linear-gradient(160deg,#141d40,#0d1430);border-radius:22px;padding:28px}
    .panel h2{font-size:3.2vh;margin:0 0 16px}
    .row{display:flex;justify-content:space-between;padding:10px 0;border-bottom:1px solid #22305e;font-size:2.4vh}
    .lbl{color:#9aa4bf} .val{color:#fff;font-weight:700} .body{font-size:2.2vh;line-height:1.5;color:#c8d2ee}
  </style></head><body><h1>${esc(title)}</h1><div class=grid>${cards}</div>
  <!-- 2D projection of a WebSpatial app; on PICO OS 6 the .panel elements gain real Z via --xr-back + enable-xr --></body></html>`;
}

function appJsx(title: string, panels: Panel[]): string {
  const panelJsx = panels.map((p, i) => {
    const depth = p.depth ?? (i + 1) * 20;
    const rows = (p.rows ?? []).map((r) => `        <div className="row"><span className="lbl">${esc(r.label)}</span><span className="val">${esc(r.value)}</span></div>`).join("\n");
    return `      <div enable-xr className="panel" style={{ '--xr-back': '${depth}px', '--xr-background-material': 'translucent' }}>
        <h2>${esc(p.title)}</h2>
${rows}
      </div>`;
  }).join("\n");
  return `import './App.css'

// Generated by generate_webspatial_app. The 'enable-xr' attribute + '--xr-back' CSS var give each
// panel real depth on PICO OS 6 (the OS Web App runtime activates WebSpatial automatically);
// elsewhere this renders as a normal responsive website (the verifiable 2D projection).
export default function App() {
  return (
    <main>
      <h1>${esc(title)}</h1>
      <div className="grid">
${panelJsx}
      </div>
    </main>
  )
}
`;
}

export function registerWebSpatialTools(server: McpServer) {
  server.registerTool(
    "generate_webspatial_app",
    {
      description:
        "Generate a WebSpatial React app (P10) — the web-native compile target. Emits a real, buildable React + @webspatial/react-sdk project (enable-xr panels, --xr-back depth, xr_spatial_scene manifest) into projectDir, PLUS a self-contained preview.html (the 2D projection). On PICO OS 6 (Swan) the panels activate spatially with no packaging; elsewhere it's a normal website. Runtime TEXT is FREE (real HTML/CSS — no baked-texture workaround). VERIFY NOW: render preview.html with headless Chrome or the emulator browser (the 2D projection is C0-verifiable); the spatial depth is `built_for_os6` (deferred honestly, like awaiting_swan). Returns the file list + the preview path + the build/run commands.",
      inputSchema: {
        projectDir: z.string().describe("Directory to write the React project into (created if absent)."),
        title: z.string().describe("App title, e.g. 'Ops Console'."),
        panels: z
          .array(z.object({
            title: z.string(),
            rows: z.array(z.object({ label: z.string(), value: z.string() })).optional(),
            body: z.string().optional().describe("Inline HTML body (for the preview)."),
            depth: z.number().optional().describe("--xr-back depth in px (spatial Z on OS 6; default (index+1)*20)."),
            accent: z.string().optional().describe("Accent hex color for the heading."),
          }))
          .min(1)
          .describe("The spatial panels (each an enable-xr element)."),
      },
    },
    async ({ projectDir, title, panels }) => {
      fs.mkdirSync(path.join(projectDir, "src"), { recursive: true });
      fs.mkdirSync(path.join(projectDir, "public"), { recursive: true });
      const write = (rel: string, content: string) => { const fp = path.join(projectDir, rel); fs.mkdirSync(path.dirname(fp), { recursive: true }); fs.writeFileSync(fp, content); return rel; };
      const files: string[] = [];

      files.push(write("package.json", JSON.stringify({
        name: title.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
        private: true, type: "module",
        scripts: { dev: "vite", build: "vite build", preview: "vite preview" },
        dependencies: { react: "^18.3.1", "react-dom": "^18.3.1", "@webspatial/react-sdk": "^1.7.0" },
        devDependencies: { vite: "^5.4.0", "@vitejs/plugin-react": "^4.3.0", "@webspatial/vite-plugin": "^1.7.0" },
      }, null, 2)));
      files.push(write("vite.config.js", `import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
// import webSpatial from '@webspatial/vite-plugin' // enable when building the spatial bundle for OS 6
export default defineConfig({ plugins: [react()] })
`));
      files.push(write("index.html", `<!doctype html><html lang=en><head><meta charset=utf-8>
<meta name=viewport content="width=device-width,initial-scale=1">
<link rel=manifest href="/manifest.webmanifest"><title>${esc(title)}</title></head>
<body><div id=root></div><script type=module src="/src/main.jsx"></script></body></html>
`));
      files.push(write("src/main.jsx", `import React from 'react'
import ReactDOM from 'react-dom/client'
import App from './App.jsx'
// import { initScene } from '@webspatial/react-sdk' // OS 6: multi-scene management
ReactDOM.createRoot(document.getElementById('root')).render(<App />)
`));
      files.push(write("src/App.jsx", appJsx(title, panels)));
      files.push(write("src/App.css", `main{min-height:100vh;background:radial-gradient(1200px 800px at 50% -10%,#10204a,#05070f);color:#eaf0ff;font-family:-apple-system,Roboto,sans-serif;padding:6vh 6vw}
h1{font-size:5vh;color:#cfe0ff;margin:0 0 3vh}
.grid{display:flex;flex-wrap:wrap;gap:3vh}
.panel{flex:1 1 320px;min-width:280px;background:linear-gradient(160deg,#141d40,#0d1430);border-radius:22px;padding:28px;box-shadow:0 14px 40px rgba(0,0,0,.5)}
.panel h2{font-size:3.2vh;margin:0 0 16px;color:#7fd7ff}
.row{display:flex;justify-content:space-between;padding:10px 0;border-bottom:1px solid #22305e;font-size:2.4vh}
.lbl{color:#9aa4bf}.val{color:#fff;font-weight:700}
`));
      files.push(write("public/manifest.webmanifest", JSON.stringify({
        name: title, short_name: title.slice(0, 12), display: "standalone", start_url: "/",
        // WebSpatial xr_spatial_scene (verified key from the @webspatial SDK source, 2026-07-08)
        xr_spatial_scene: { default_size: { width: "1280px", height: "720px" }, worldScaling: "automatic", worldAlignment: "automatic" },
      }, null, 2)));
      const preview = write("preview.html", previewHtml(title, panels));

      return okJson({
        status: "ok",
        projectDir,
        files,
        preview: path.join(projectDir, preview),
        evidence: "The 2D projection (preview.html / the built site) is C0-verifiable now (render it). The spatial-depth behavior is built_for_os6 — activates on PICO OS 6 / Swan.",
        build: "cd " + projectDir + " && npm install && npm run build   # the OS-6 deliverable (Node 22+)",
        verifyNow: "Render the returned preview path with headless Chrome ('Google Chrome' --headless --screenshot=out.png --window-size=1280,900 file://<preview>) or the emulator browser (drive_browser url=...), then LOOK / visual_judge.",
      });
    },
  );
}
