import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok, fail } from "./util.js";

/**
 * generate_lighting_kotlin — emit SceneLighting.kt that lights a scene the CORRECT way (a directional
 * "sun" + an IBL intensity scale) so baked PBR meshes render lit instead of dim — vs the emissive
 * hacks. Uses sources-confirmed APIs: DirectionalLightComponent (color: Color4, intensity: lux),
 * EnvironmentLightingSettingsComponent(scale: Float).
 *
 * Verify: COMPILES against the SDK; the lit-vs-unlit delta is visible in a capture on a BAKED-MESH
 * scene (the PICO home-env is system-lit and won't change — flag that honestly).
 */
export function registerLightingTools(server: McpServer) {
  server.registerTool(
    "generate_lighting_kotlin",
    {
      description:
        "Emit SceneLighting.kt (a directional 'sun' DirectionalLightComponent + an EnvironmentLightingSettingsComponent IBL scale) so baked PBR meshes are LIT (not dim) — the editor-grade fix vs emissive hacks. Call SceneLighting.apply(content) after building the scene root. Compiles against the SDK; the brightening is vision-verifiable on a baked-mesh scene (the system-lit home-env won't change).",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        sunLux: z.number().optional().describe("Directional light intensity in lux (default 1500)."),
        iblScale: z.number().optional().describe("Environment IBL intensity scale (default 1.5; 0 disables IBL)."),
        color: z.array(z.number()).optional().describe("Sun color RGBA [r,g,b,a] 0..1 (default warm white)."),
      },
    },
    async ({ packageName, sunLux, iblScale, color }) => {
      if (color && color.length !== 4) return fail("color must be [r,g,b,a] (4 numbers).");
      const c = (color ?? [1, 0.96, 0.9, 1]) as number[];
      const lux = sunLux ?? 1500;
      const ibl = iblScale ?? 1.5;
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.DirectionalLightComponent",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.EnvironmentLightingSettingsComponent",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.math.Color4",
        "import com.pico.spatial.core.math.EulerAngles",
        "import com.pico.spatial.core.math.Quat",
        "import com.pico.spatial.core.math.Vector3",
        "",
        "/**",
        " * Generated by generate_lighting_kotlin. Lights the scene the correct way (sun + IBL) so baked",
        " * PBR meshes render LIT, not dim. Call SceneLighting.apply(content) after the scene root exists.",
        " * VERIFY: compiles; the lit-vs-unlit delta is visible in a capture on a BAKED-MESH scene (the PICO",
        " * home-env is system-lit and will NOT change).",
        " */",
        "object SceneLighting {",
        '    private const val TAG = "SceneLighting"',
        `    private const val SUN_LUX = ${lux}f`,
        `    private const val IBL_SCALE = ${ibl}f`,
        "",
        "    fun apply(content: Entity) {",
        "        runCatching {",
        "            content.components.set(EnvironmentLightingSettingsComponent(IBL_SCALE))",
        "            val sun = Entity()",
        '            sun.setName("SceneSun")',
        "            sun.components.set(",
        "                TransformComponent(Vector3(0f, 3f, 0f), Quat.identity(), Vector3(1f, 1f, 1f))",
        "                    .setEulerAngles(EulerAngles(-50f, -30f, 0f))",
        "            )",
        `            sun.components.set(DirectionalLightComponent(Color4(${c[0]}f, ${c[1]}f, ${c[2]}f, ${c[3]}f), SUN_LUX))`,
        "            content.addChild(sun)",
        '            Log.i(TAG, "scene lighting applied (sun=${SUN_LUX}lux, ibl=${IBL_SCALE})")',
        "        }.onFailure { Log.e(TAG, \"lighting failed: ${it.message}\") }",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );

  server.registerTool(
    "generate_full_lighting_rig_kotlin",
    {
      description:
        "Emit SceneLightingRig.kt — a FULL lighting rig (closes the 2-of-7 lighting gap): a directional sun + PointLightComponent (falloff) + SpotLightComponent (cone) + GroundShadowComponent (contact shadow) + EnvironmentLightingSettingsComponent (IBL). Call SceneLightingRig.apply(content) after the scene root. Compiles against the SDK; point falloff / spot cone / ground shadow are vision-verifiable on a baked-mesh scene via capture_frame.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        sunLux: z.number().optional().describe("Directional sun intensity (default 1400)."),
        pointLux: z.number().optional().describe("Point light intensity (default 900)."),
        spotLux: z.number().optional().describe("Spot light intensity (default 1300)."),
        iblScale: z.number().optional().describe("Environment IBL scale (default 1.4)."),
      },
    },
    async ({ packageName, sunLux, pointLux, spotLux, iblScale }) => {
      const sun = sunLux ?? 1400, pt = pointLux ?? 900, sp = spotLux ?? 1300, ibl = iblScale ?? 1.4;
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.DirectionalLightComponent",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.EnvironmentLightingSettingsComponent",
        "import com.pico.spatial.core.ecs.GroundShadowComponent",
        "import com.pico.spatial.core.ecs.PointLightComponent",
        "import com.pico.spatial.core.ecs.SpotLightComponent",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.math.Color4",
        "import com.pico.spatial.core.math.EulerAngles",
        "import com.pico.spatial.core.math.Quat",
        "import com.pico.spatial.core.math.Vector3",
        "",
        "/**",
        " * Generated by generate_full_lighting_rig_kotlin. A complete lighting rig: directional sun +",
        " * point (falloff) + spot (cone) + ground/contact shadow + IBL. Call SceneLightingRig.apply(content).",
        " * VERIFY: compiles; point falloff / spot cone / contact shadow are vision-verifiable on a BAKED-MESH",
        " * scene via capture_frame (the system-lit home env will not change).",
        " */",
        "object SceneLightingRig {",
        '    private const val TAG = "SceneLightingRig"',
        "",
        "    fun apply(content: Entity) {",
        "        runCatching {",
        `            content.components.set(EnvironmentLightingSettingsComponent(${ibl}f))`,
        "            content.components.set(GroundShadowComponent(true, true)) // contact/ground shadows",
        "",
        '            val sun = Entity().also { it.setName("RigSun") }',
        "            sun.components.set(TransformComponent(Vector3(0f, 3f, 0f), Quat.identity(), Vector3(1f, 1f, 1f)).setEulerAngles(EulerAngles(-50f, -30f, 0f)))",
        `            sun.components.set(DirectionalLightComponent(Color4(1f, 0.96f, 0.9f, 1f), ${sun}f))`,
        "            content.addChild(sun)",
        "",
        '            val point = Entity().also { it.setName("RigPoint") }',
        "            point.components.set(TransformComponent(Vector3(1.2f, 1.6f, -1.4f), Quat.identity(), Vector3(1f, 1f, 1f)))",
        `            point.components.set(PointLightComponent(Color4(1f, 0.82f, 0.55f, 1f), ${pt}f, 4f)) // warm lamp, 4m falloff`,
        "            content.addChild(point)",
        "",
        '            val spot = Entity().also { it.setName("RigSpot") }',
        "            spot.components.set(TransformComponent(Vector3(-1.1f, 2.3f, -1.2f), Quat.identity(), Vector3(1f, 1f, 1f)).setEulerAngles(EulerAngles(-70f, 18f, 0f)))",
        `            spot.components.set(SpotLightComponent(Color4(0.9f, 0.95f, 1f, 1f), ${sp}f, 6f, 0.45f, 0.7f)) // cone inner 0.45 / outer 0.7 rad`,
        "            content.addChild(spot)",
        '            Log.i(TAG, "full lighting rig applied (sun+point+spot+groundShadow+ibl)")',
        "        }.onFailure { Log.e(TAG, \"lighting rig failed: ${it.message}\") }",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );

  server.registerTool(
    "generate_ibl_kotlin",
    {
      description:
        "Emit SceneIBL.kt — image-based lighting (IBL) from an HDR .ktx cubemap. Two modes: 'stage' = scene-wide StageEnvironmentLightingComponent (lights ALL PBR meshes; ACTIVE only in FULL/PROGRESSIVE stage, INACTIVE in MIXED where the system real-world IBL wins) and 'local' = an ImageBasedLightComponent source entity + ImageBasedLightReceiverComponent on tagged receivers (localized reflections/lighting on chosen meshes). Compiles against the SDK; the IBL effect (reflections/ambient) is vision-verifiable on a baked-PBR/metallic mesh. ASSET-GATED: needs an HDR cubemap .ktx in app assets (only .ktx is supported); the system-lit home env will not change.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        ktxAssetPath: z.string().describe("Path to the HDR cubemap .ktx under app assets (loaded FROM_ASSETS), e.g. 'ibl/studio.ktx'. Only .ktx cubemaps are supported by the SDK."),
        mode: z.enum(["stage", "local", "both"]).optional().describe("stage = scene-wide (FULL/PROGRESSIVE stage only). local = source+receiver on tagged meshes. both = emit both. Default 'stage'."),
        intensityExponent: z.number().optional().describe("IBL intensity exponent; actual intensity = 2^exp (range -24..24). Default 0 (= 1.0x)."),
      },
    },
    async ({ packageName, ktxAssetPath, mode, intensityExponent }) => {
      const exp = intensityExponent ?? 0;
      if (exp < -24 || exp > 24) return fail("intensityExponent must be in [-24, 24] (intensity = 2^exp).");
      const m = mode ?? "stage";
      const doStage = m === "stage" || m === "both";
      const doLocal = m === "local" || m === "both";
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.EnvironmentLightingSettingsComponent",
        "import com.pico.spatial.core.ecs.ImageBasedLightComponent",
        "import com.pico.spatial.core.ecs.ImageBasedLightReceiverComponent",
        "import com.pico.spatial.core.ecs.ImageBasedLightSource",
        "import com.pico.spatial.core.ecs.StageEnvironmentLightingComponent",
        "import com.pico.spatial.core.ecs.resource.TextureResource",
        "",
        "/**",
        " * Generated by generate_ibl_kotlin. Image-based lighting from an HDR .ktx cubemap.",
        " *  - applyStage(content): scene-wide IBL (StageEnvironmentLightingComponent). Lights every PBR mesh,",
        " *    but is ACTIVE ONLY in FULL / PROGRESSIVE stage. In MIXED stage it is INACTIVE (the system's",
        " *    real-world IBL takes precedence) — call this only when you own a FULL/PROGRESSIVE stage.",
        " *  - applyLocal(content, receivers): localized IBL. An ImageBasedLightComponent SOURCE entity lights",
        " *    only the entities you tag with ImageBasedLightReceiverComponent — works in any stage.",
        " * VERIFY: compiles; the IBL reflections/ambient are vision-verifiable on a baked-PBR/metallic mesh via",
        " * capture_frame. ASSET-GATED: place an HDR cubemap .ktx in assets (only .ktx is supported).",
        " */",
        "object SceneIBL {",
        '    private const val TAG = "SceneIBL"',
        `    private const val KTX = "${ktxAssetPath}"`,
        `    private const val EXP = ${exp}f // intensity = 2^EXP`,
        "",
        ...(doStage ? [
          "    /** Scene-wide IBL. ACTIVE only in FULL/PROGRESSIVE stage; INACTIVE in MIXED (system IBL wins). */",
          "    fun applyStage(content: Entity) {",
          "        runCatching {",
          "            val tex = TextureResource.load(KTX)",
          "            content.components.set(StageEnvironmentLightingComponent(ImageBasedLightSource.Single(tex), EXP))",
          "            content.components.set(EnvironmentLightingSettingsComponent(1f)) // global IBL intensity scale",
          '            Log.i(TAG, "stage IBL applied from $KTX (exp=$EXP)")',
          "        }.onFailure { Log.e(TAG, \"stage IBL failed (is $KTX a valid .ktx cubemap in assets?): ${it.message}\") }",
          "    }",
          "",
        ] : []),
        ...(doLocal ? [
          "    /** Localized IBL: only [receivers] are lit by the cubemap. Returns the source entity (keep it to retune). */",
          "    fun applyLocal(content: Entity, receivers: List<Entity>): Entity? = runCatching {",
          "        val tex = TextureResource.load(KTX)",
          '        val source = Entity().also { it.setName("IBLSource") }',
          "        source.components.set(ImageBasedLightComponent(ImageBasedLightSource.Single(tex), EXP))",
          "        content.addChild(source)",
          "        receivers.forEach { it.components.set(ImageBasedLightReceiverComponent(source)) }",
          '        Log.i(TAG, "local IBL applied to ${receivers.size} receivers from $KTX")',
          "        source",
          "    }.onFailure { Log.e(TAG, \"local IBL failed: ${it.message}\") }.getOrNull()",
          "",
        ] : []),
        "    /** Convenience dispatch. Pass the scene root as [content]; [receivers] used only for local IBL. */",
        "    fun apply(content: Entity, receivers: List<Entity> = emptyList()) {",
        ...(doStage ? ["        applyStage(content)"] : []),
        ...(doLocal ? ["        if (receivers.isNotEmpty()) applyLocal(content, receivers)"] : []),
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
