import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * router.ts — v5.7 `generate_scene_router_kotlin`: a scene-graph state machine for multi-scene apps.
 *
 * Source-verified (SDK 0.13.3): scene teardown uses `Entity.destroy(recursively=true)` (verified in
 * Entity.kt) — each scene lives under its own container entity that is destroyed on transition and rebuilt
 * fresh (this also resets per-scene state, e.g. an additive bob that would otherwise fight a moved
 * transform). Transitions are BROADCAST-driven (navigate:<id>) so they stay in the ECS world and the mouse
 * bridge keeps working (C4 — no in-front Compose panels). Portal/controller-gaze activation is Swan-only
 * (C3); broadcast traversal is emulator-verifiable. Scene mutation is marshaled to the MAIN thread (the
 * broadcast arrives on a binder thread — the retained lesson from SceneInteraction).
 */
export function registerRouterTools(server: McpServer) {
  server.registerTool(
    "generate_scene_router_kotlin",
    {
      description:
        "Emit SceneRouter.kt — a broadcast-driven scene-graph state machine for multi-scene apps. Register each scene as a builder lambda ((container: Entity) -> Unit); go(id) tears down the current scene (Entity.destroy) and builds the target fresh under its own container (resetting per-scene state). Drive transitions with a <pkg>.DEBUG_CMD 'navigate:<id>' broadcast (C4-safe, mouse-bridge-compatible); portal/gaze/controller activation is built-for-Swan (C3). Scene mutation is marshaled to the main thread (broadcasts arrive off-main). Compiles against SDK 0.13.3; a broadcast transition between scenes is vision-verifiable by capturing each scene individually (with ~3s settle).",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
      },
    },
    async ({ packageName }) => {
      const kt = [
        `package ${packageName}`,
        "",
        "import android.os.Handler",
        "import android.os.Looper",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.math.Quat",
        "import com.pico.spatial.core.math.Vector3",
        "",
        "/**",
        " * Generated by generate_scene_router_kotlin. A broadcast-driven scene-graph state machine.",
        " * Usage:",
        " *   SceneRouter.attach(sceneRoot)",
        " *   SceneRouter.register(\"lobby\") { c -> buildLobby(c) }",
        " *   SceneRouter.register(\"gallery\") { c -> buildGallery(c) }",
        " *   SceneRouter.start(\"lobby\")",
        " *   // transition: adb shell am broadcast -a <pkg>.DEBUG_CMD --es cmd navigate:gallery",
        " * go(id) destroys the current scene container and builds the target fresh (resets per-scene state).",
        " */",
        "object SceneRouter {",
        '    private const val TAG = "SceneRouter"',
        "",
        "    private val builders = LinkedHashMap<String, (Entity) -> Unit>()",
        "    private var root: Entity? = null",
        "    private var current: Entity? = null",
        "    var currentId: String? = null",
        "        private set",
        "    var onSceneChanged: ((String) -> Unit)? = null",
        "",
        "    private val mainHandler = Handler(Looper.getMainLooper())",
        "    private fun onMain(block: () -> Unit) {",
        "        if (Looper.myLooper() == Looper.getMainLooper()) block() else mainHandler.post(block)",
        "    }",
        "",
        "    /** Attach the router to a PERSISTENT scene root (survives transitions). Call once. */",
        "    fun attach(sceneRoot: Entity) { root = sceneRoot }",
        "",
        "    /** Register a scene builder: given the scene's own container entity, populate it. */",
        "    fun register(id: String, builder: (Entity) -> Unit) { builders[id] = builder }",
        "",
        "    /** Navigate to [id]: tear down the current scene container and build the target fresh. */",
        "    fun go(id: String) = onMain {",
        "        val r = root ?: run { Log.e(TAG, \"go('$id') before attach()\"); return@onMain }",
        "        val builder = builders[id] ?: run { Log.w(TAG, \"unknown scene '$id'\"); return@onMain }",
        "        runCatching {",
        "            current?.destroy(true)",
        "            val container = Entity()",
        "            container.setName(\"scene_\" + id)",
        "            container.components.set(TransformComponent(Vector3(0f, 0f, 0f), Quat.identity(), Vector3(1f, 1f, 1f)))",
        "            r.addChild(container)",
        "            current = container",
        "            currentId = id",
        "            builder(container)",
        "            Log.i(TAG, \"navigated to $id\")",
        "            onSceneChanged?.invoke(id)",
        "        }.onFailure { Log.e(TAG, \"go('$id') failed: \" + it.message) }",
        "    }",
        "",
        "    /** Load the initial scene. */",
        "    fun start(id: String) = go(id)",
        "",
        "    fun scenes(): List<String> = builders.keys.toList()",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
