import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok, fail } from "./util.js";

/**
 * media.ts — v4.6 particles + video.
 *
 * Source-verified facts (SDK 0.13.3, com.pico.spatial.core.ecs):
 *  - ParticleComponent has NO public constructor. The class doc: "you can modify the exposed
 *    properties of an existing ParticleComponent, but cannot create new instances." A particle
 *    node authored in the Spatial Editor and loaded from an AssetBundle AUTO-ATTACHES the
 *    component; you retrieve it via emitter.components.get<ParticleComponent>() and drive the
 *    runtime knobs: isEmitting, startColor (ParticleColorVaryingProperty), attractor/vortex.
 *    => generate_particle_kotlin emits a DRIVER (it does not — cannot — construct the component).
 *    The emitter geometry/rate/lifetime are editor-authored (ASSET-GATED).
 *  - VideoPlayerComponent(player: CypressMediaPlayer, mesh: MeshResource, mat: VideoMaterial).
 *    CypressMediaPlayer() is a public no-arg ctor; render goes through VideoPlayerComponent.
 *    ASSET + CODEC gated: needs a real .mp4 + a hardware decoder; on the emulator decode often
 *    fails (onError ERROR_DECODER). The reliable verification surface is the CypressMediaPlayer
 *    callbacks (onPrepared/onStarted) in logcat — structural, not pixel.
 */
export function registerMediaTools(server: McpServer) {
  // ── generate_particle_kotlin ───────────────────────────────────────────────
  server.registerTool(
    "generate_particle_kotlin",
    {
      description:
        "Emit SceneParticles.kt — a DRIVER for an editor-authored particle effect. ParticleComponent has NO public constructor (the emitter shape/rate/lifetime are authored in the Spatial Editor and baked into an AssetBundle/.glb, which auto-attaches the component); this code retrieves it via emitter.components.get<ParticleComponent>() and drives the runtime knobs: isEmitting (start/stop), startColor (constant or random range), and the attractor/vortex forces. Compiles against the SDK. ASSET-GATED: you must load an editor-authored particle node first; toggling emission/color is then vision-verifiable across captures (the forces are subtle/structural).",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        startColor: z.array(z.number()).optional().describe("Spawn color RGBA [r,g,b,a] 0..1 (default cyan [0,1,1,1])."),
        randomColor: z.boolean().optional().describe("If true, startColor varies per-particle between startColor and rangeColor (ParticleVaryingPropertyType.RANDOM); else CONSTANT. Default false."),
        rangeColor: z.array(z.number()).optional().describe("The second color bound for RANDOM spawn color (default magenta [1,0,1,1])."),
        attractorStrength: z.number().optional().describe("If > 0, enables the attractor force (pulls particles toward a point) with this strength. Must be >= 0."),
        vortexStrength: z.number().optional().describe("If > 0, enables the vortex force (rotates particles) with this strength. Must be >= 0."),
      },
    },
    async ({ packageName, startColor, randomColor, rangeColor, attractorStrength, vortexStrength }) => {
      if (startColor && startColor.length !== 4) return fail("startColor must be [r,g,b,a] (4 numbers).");
      if (rangeColor && rangeColor.length !== 4) return fail("rangeColor must be [r,g,b,a] (4 numbers).");
      if (attractorStrength !== undefined && attractorStrength < 0) return fail("attractorStrength must be >= 0.");
      if (vortexStrength !== undefined && vortexStrength < 0) return fail("vortexStrength must be >= 0.");
      const sc = (startColor ?? [0, 1, 1, 1]) as number[];
      const rc = (rangeColor ?? [1, 0, 1, 1]) as number[];
      const type = randomColor ? "RANDOM" : "CONSTANT";
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.ParticleComponent",
        "import com.pico.spatial.core.ecs.particle.ParticleColorVaryingProperty",
        "import com.pico.spatial.core.ecs.particle.ParticleVaryingPropertyType",
        "import com.pico.spatial.core.math.Color4",
        "",
        "/**",
        " * Generated by generate_particle_kotlin. DRIVES an editor-authored particle effect.",
        " * ParticleComponent cannot be constructed — load a particle node from an AssetBundle/.glb",
        " * (the Spatial Editor authors the emitter), then call SceneParticles.drive(emitter).",
        " * VERIFY: compiles; isEmitting/startColor changes are vision-verifiable once the asset is loaded.",
        " */",
        "object SceneParticles {",
        '    private const val TAG = "SceneParticles"',
        "",
        "    /** Drive the ParticleComponent already attached to [emitter] (from a loaded particle asset). */",
        "    fun drive(emitter: Entity, emitting: Boolean = true): ParticleComponent? {",
        "        val p = emitter.components.get<ParticleComponent>()",
        "        if (p == null) {",
        '            Log.w(TAG, "no ParticleComponent on emitter — load an editor-authored particle asset first")',
        "            return null",
        "        }",
        "        runCatching {",
        "            p.isEmitting = emitting",
        `            p.startColor = ParticleColorVaryingProperty(`,
        `                ParticleVaryingPropertyType.${type},`,
        `                Color4(${sc[0]}f, ${sc[1]}f, ${sc[2]}f, ${sc[3]}f),`,
        `                Color4(${rc[0]}f, ${rc[1]}f, ${rc[2]}f, ${rc[3]}f),`,
        "            )",
        ...(attractorStrength && attractorStrength > 0 ? [
          "            p.isAttractorEnabled = true",
          `            p.attractorStrength = ${attractorStrength}f`,
        ] : []),
        ...(vortexStrength && vortexStrength > 0 ? [
          "            p.isVortexEnabled = true",
          `            p.vortexStrength = ${vortexStrength}f`,
        ] : []),
        '            Log.i(TAG, "particles driven (emitting=$emitting)")',
        "        }.onFailure { Log.e(TAG, \"particle drive failed: ${it.message}\") }",
        "        return p",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );

  // ── generate_video_player_kotlin ───────────────────────────────────────────
  server.registerTool(
    "generate_video_player_kotlin",
    {
      description:
        "Emit SceneVideo.kt — render a video onto a quad via VideoPlayerComponent + the SDK's CypressMediaPlayer. Builds a plane MeshResource + a VideoMaterial, wires the player callbacks (play on onPrepared), and attaches the component. Compiles against the SDK. ASSET + CODEC gated: needs a real video file/URL reachable via setDataSource (storage path or URL — NOT android assets, use the AssetFileDescriptor overload for bundled assets) and a hardware decoder; on the native emulator decode often fails (onError ERROR_DECODER) — the reliable signal is the logcat callbacks (onPrepared/onStarted), which is STRUCTURAL not pixel.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        width: z.number().optional().describe("Quad width in m (default 0.9)."),
        height: z.number().optional().describe("Quad height in m (default 0.5)."),
        loop: z.boolean().optional().describe("Loop playback (default true)."),
        stereo: z.boolean().optional().describe("Treat the source as side-by-side stereo (VideoDimensionMode.SIDE_BY_SIDE + DisplayMode.STEREO). Default false (MONO)."),
      },
    },
    async ({ packageName, width, height, loop, stereo }) => {
      const w = width ?? 0.9, h = height ?? 0.5;
      const dim = stereo ? "SIDE_BY_SIDE" : "MONO";
      const disp = stereo ? "STEREO" : "MONO";
      const kt = [
        `package ${packageName}`,
        "",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.VideoPlayerComponent",
        "import com.pico.spatial.core.ecs.video.CypressMediaPlayer",
        "import com.pico.spatial.core.ecs.video.CypressMediaPlayerCallback",
        "import com.pico.spatial.core.ecs.video.CypressMediaPlayerErrorCode",
        "import com.pico.spatial.core.ecs.video.DisplayMode",
        "import com.pico.spatial.core.ecs.video.VideoDimensionMode",
        "import com.pico.spatial.core.ecs.resource.BlendingMode",
        "import com.pico.spatial.core.ecs.resource.MaterialCullingMode",
        "import com.pico.spatial.core.ecs.resource.MeshResource",
        "import com.pico.spatial.core.ecs.resource.VideoMaterial",
        "",
        "/**",
        " * Generated by generate_video_player_kotlin. Renders a video onto a quad via the SDK's",
        " * CypressMediaPlayer + VideoPlayerComponent. Call SceneVideo.attach(entity, dataSource).",
        " * VERIFY: compiles; playback is ASSET+CODEC gated — the reliable signal is the logcat",
        " * callbacks (onPrepared/onStarted), since the emulator decoder/Surface is unreliable.",
        " */",
        "object SceneVideo {",
        '    private const val TAG = "SceneVideo"',
        "",
        "    // Retained so release() can close it. CypressMediaPlayer is Closeable but is NOT a Resource,",
        "    // so it is never lifecycle-tied to the component it is handed to — the app owns it outright",
        "    // and a decoder + Surface stay alive until close(). PICO's SpatialVideo sample holds it the",
        "    // same way (PlaybackManager.kt:28) and tears it down in reset() from onCleared().",
        "    private var player: CypressMediaPlayer? = null",
        "",
        "    /** dataSource = a storage path (e.g. /sdcard/Movies/clip.mp4) or a URL (NOT an android assets path). */",
        "    fun attach(entity: Entity, dataSource: String): VideoPlayerComponent? = runCatching {",
        "        release()   // one player per SceneVideo; re-attaching must not strand the previous decoder",
        "        val player = CypressMediaPlayer()",
        "        this.player = player",
        "        player.registerCypressMediaPlayerCallback(object : CypressMediaPlayerCallback {",
        '            override fun onPrepared() { player.play(); Log.i(TAG, "video prepared -> play") }',
        "            override fun onStarted() {}",
        "            override fun onPaused() {}",
        "            override fun onStopped() {}",
        "            override fun onCompleted() {}",
        "            override fun onSeekToCompleted() {}",
        '            override fun onError(error: CypressMediaPlayerErrorCode) { Log.e(TAG, "video error: $error") }',
        "            override fun onVideoSizeChanged(width: Int, height: Int) {}",
        "        })",
        `        player.setLoop(${loop === false ? "false" : "true"})`,
        "        player.setDataSource(dataSource)",
        `        val mesh = MeshResource.createPlane(${w}f, ${h}f, 0f)`,
        `        val mat = VideoMaterial(BlendingMode.OPAQUE, VideoDimensionMode.${dim}, MaterialCullingMode.BACK)`,
        "        val comp = VideoPlayerComponent(player, mesh, mat)",
        `        comp.setDisplayMode(DisplayMode.${disp})`,
        "        entity.components.set(comp)",
        "        player.prepareAsync() // async; play() fires from onPrepared()",
        '        Log.i(TAG, "video attached from $dataSource")',
        "        comp",
        "    }.onFailure { Log.e(TAG, \"video attach failed: ${it.message}\") }.getOrNull()",
        "",
        "    /**",
        "     * MANDATORY teardown — onCleared / DisposableEffect { onDispose { SceneVideo.release() } }.",
        "     * UNREGISTER BEFORE CLOSE, the order PICO's own PlaybackManager.reset() uses: the callback",
        "     * holds this object, and a callback delivered against a closed player is a crash you only",
        "     * see on teardown. The mesh/VideoMaterial are owned by the VideoPlayerComponent and are NOT",
        "     * closed here (Resource.kt:35-42).",
        "     */",
        "    fun release() {",
        "        player?.apply {",
        "            runCatching { unregisterCypressMediaPlayerCallback() }",
        "            runCatching { close() }",
        "        }",
        "        player = null",
        "    }",
        "}",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
