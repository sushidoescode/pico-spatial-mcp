/** Internal AppSpec codegen profile. No MCP tool is registered. */
export function generateBoundaryLabFiles(spec: AppSpec, pkg: string): { path: string; content: string }[] {
  if (!spec.boundaryLab) return [];
  if (spec.meta.packageName !== pkg) throw new Error("Boundary Lab package must match AppSpec meta.packageName");
  const files = [{
    path: generatedPath(pkg, "main", "content/BoundaryLabScene.kt"),
    content: generateWorld(spec, pkg),
  }];
  if (spec.boundaryLab.variant !== "dynamic_full") return files;
  files.push(
    { path: generatedPath(pkg, "main", "content/BoundaryProbeRoot.kt"), content: generateProbeRoot(spec, pkg) },
    { path: generatedPath(pkg, "debug", "agent/BoundaryProbe.kt"), content: generateDebugProbe(pkg) },
    { path: generatedPath(pkg, "debug", "agent/BoundaryProbeReceiver.kt"), content: generateDebugReceiver(pkg) },
    { path: generatedPath(pkg, "release", "agent/BoundaryProbe.kt"), content: generateReleaseProbe(pkg) },
    { path: "app/src/debug/AndroidManifest.xml", content: generateDebugManifest() },
  );
  return files;
}
