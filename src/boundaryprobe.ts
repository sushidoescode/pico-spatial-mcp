import type { AppSpec } from "./appspec.js";

const ktString = (value: string): string => JSON.stringify(value).replace(/\$/g, "\\$");

function generatedPath(pkg: string, sourceSet: "main" | "debug" | "release", suffix: string): string {
  return `app/src/${sourceSet}/java/${pkg.replace(/\./g, "/")}/${suffix}`;
}

function rootSentinel(spec: AppSpec): string {
  const profile = spec.boundaryLab!;
  return profile.variant === "manifest_full"
    ? profile.sentinels.manifestFull
    : profile.sentinels.manifestMixedRoot;
}

function generateWorld(spec: AppSpec, pkg: string): string {
  const profile = spec.boundaryLab!;
  const contentPkg = `${pkg}.content`;
  const gates = profile.gateSequenceM.flatMap((distance) =>
    ["FORWARD", "BACKWARD", "LEFT", "RIGHT"].map((axis) => `        Gate(${distance}f, Axis.${axis}),`));
  return [
    `package ${contentPkg}`,
    ``,
    `import android.os.Looper`,
    `import androidx.compose.foundation.background`,
    `import androidx.compose.foundation.layout.Arrangement`,
    `import androidx.compose.foundation.layout.Column`,
    `import androidx.compose.foundation.layout.padding`,
    `import androidx.compose.foundation.shape.RoundedCornerShape`,
    `import androidx.compose.runtime.Composable`,
    `import androidx.compose.ui.Modifier`,
    `import androidx.compose.ui.unit.IntSize`,
    `import androidx.compose.ui.unit.dp`,
    `import com.pico.spatial.core.container.SpatialViewContent`,
    `import com.pico.spatial.core.ecs.AttachmentPanelComponent`,
    `import com.pico.spatial.core.ecs.Entity`,
    `import com.pico.spatial.core.ecs.LookAtComponent`,
    `import com.pico.spatial.core.ecs.ModelComponent`,
    `import com.pico.spatial.core.ecs.TransformComponent`,
    `import com.pico.spatial.core.ecs.resource.MeshResource`,
    `import com.pico.spatial.core.ecs.resource.UnlitMaterial`,
    `import com.pico.spatial.core.math.Color4`,
    `import com.pico.spatial.core.math.Quat`,
    `import com.pico.spatial.core.math.Vector3`,
    `import com.pico.spatial.ui.design.PicoTheme`,
    `import com.pico.spatial.ui.design.Text`,
    `import com.pico.spatial.ui.foundation.content.AttachmentPanelBuilder`,
    `import com.pico.spatial.ui.foundation.content.SpatialViewAttachments`,
    `import com.pico.spatial.ui.foundation.content.panelSize`,
    `import java.util.IdentityHashMap`,
    `import java.util.concurrent.atomic.AtomicReference`,
    `import kotlinx.coroutines.CoroutineScope`,
    `import kotlinx.coroutines.CoroutineStart`,
    `import kotlinx.coroutines.Dispatchers`,
    `import kotlinx.coroutines.Job`,
    `import kotlinx.coroutines.NonCancellable`,
    `import kotlinx.coroutines.SupervisorJob`,
    `import kotlinx.coroutines.cancel`,
    `import kotlinx.coroutines.currentCoroutineContext`,
    `import kotlinx.coroutines.ensureActive`,
    `import kotlinx.coroutines.launch`,
    `import kotlinx.coroutines.withContext`,
    `import kotlinx.coroutines.yield`,
    ``,
    `/** Deterministic Boundary Lab geometry. Native resources are allocated off Main and attached`,
    ` * in bounded Main-thread batches so a fresh launch cannot repeat the historical FocusEvent ANR. */`,
    `object BoundaryLabScene {`,
    `    const val HIGH_CONTRAST_ENCLOSURE = "HIGH_CONTRAST_ENCLOSURE"`,
    `    const val MANIFEST_MIXED_SENTINEL = ${ktString(profile.sentinels.manifestMixedRoot)}`,
    `    const val MANIFEST_FULL_SENTINEL = ${ktString(profile.sentinels.manifestFull)}`,
    `    const val DYNAMIC_FULL_SENTINEL = ${ktString(profile.sentinels.dynamicFull)}`,
    `    const val ROOT_SENTINEL = ${ktString(rootSentinel(spec))}`,
    `    // Two gates x four entities = at most eight ECS attachments between yields.`,
    `    private const val ATTACH_BATCH_SIZE = 2`,
    ``,
    `    enum class Axis(val label: String) {`,
    `        FORWARD("FORWARD"), BACKWARD("BACKWARD"), LEFT("LEFT"), RIGHT("RIGHT")`,
    `    }`,
    `    data class Gate(val distanceM: Float, val axis: Axis) {`,
    `        val id: String = "boundary_gate_" + axis.label.lowercase() + "_" + distanceM.toInt() + "m"`,
    `    }`,
    `    val GATES: List<Gate> = listOf(`,
    ...gates,
    `    )`,
    ``,
    `    private enum class ResourceOwner { BUILD, SESSION, CLOSED }`,
    `    private class Resources(`,
    `        val unitBox: MeshResource,`,
    `        val dark: UnlitMaterial,`,
    `        val cyan: UnlitMaterial,`,
    `        val magenta: UnlitMaterial,`,
    `        val yellow: UnlitMaterial,`,
    `        val white: UnlitMaterial,`,
    `    ) {`,
    `        private val owner = AtomicReference<ResourceOwner>(ResourceOwner.BUILD)`,
    `        fun adoptBySession(): Boolean = owner.compareAndSet(ResourceOwner.BUILD, ResourceOwner.SESSION)`,
    `        fun closeByBuild() = closeIfOwned(ResourceOwner.BUILD)`,
    `        fun closeBySession() = closeIfOwned(ResourceOwner.SESSION)`,
    `        private fun closeIfOwned(expected: ResourceOwner) {`,
    `            if (!owner.compareAndSet(expected, ResourceOwner.CLOSED)) return`,
    `            listOf(white, yellow, magenta, cyan, dark).forEach { material -> runCatching { material.close() } }`,
    `            runCatching { unitBox.close() }`,
    `        }`,
    `    }`,
    `    private data class Session(`,
    `        val scope: CoroutineScope,`,
    `        val job: Job,`,
    `        var resources: Resources? = null,`,
    `        val ownedChildren: MutableList<Entity> = mutableListOf(),`,
    `    )`,
    `    private val sessions = IdentityHashMap<Entity, Session>()`,
    ``,
    `    fun build(root: Entity) {`,
    `        release(root)`,
    `        val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)`,
    `        lateinit var job: Job`,
    `        job = scope.launch(start = CoroutineStart.LAZY) {`,
    `            val resources = prepareResources()`,
    `            try {`,
    `                var accepted = false`,
    `                withContext(Dispatchers.Main.immediate) {`,
    `                    val session = sessions[root]`,
    `                    if (session == null || session.job !== job) return@withContext`,
    `                    accepted = true`,
    `                    session.resources = resources`,
    `                    val attachments = buildList<suspend () -> Unit> {`,
    `                        add { enclosure(root, resources) }`,
    `                        GATES.forEachIndexed { index, gateSpec -> add { gate(root, resources, gateSpec, index) } }`,
    `                    }`,
    `                    attachments.chunked(ATTACH_BATCH_SIZE).forEach { batch ->`,
    `                        batch.forEach { attach -> attach() }`,
    `                        yield()`,
    `                    }`,
    `                    currentCoroutineContext().ensureActive()`,
    `                    check(resources.adoptBySession()) { "Boundary Lab resource ownership changed during build" }`,
    `                }`,
    `                if (!accepted) resources.closeByBuild()`,
    `            } catch (cause: Throwable) {`,
    `                withContext(NonCancellable + Dispatchers.Main.immediate) {`,
    `                    val failed = sessions[root]?.takeIf { it.job === job }`,
    `                    if (failed != null) {`,
    `                        sessions.remove(root)`,
    `                        failed.ownedChildren.asReversed().forEach { entity ->`,
    `                            runCatching { root.removeChild(entity) }`,
    `                            runCatching { entity.destroy(true) }`,
    `                        }`,
    `                        failed.ownedChildren.clear()`,
    `                        failed.resources = null`,
    `                    }`,
    `                }`,
    `                withContext(NonCancellable + Dispatchers.Default) { resources.closeByBuild() }`,
    `                throw cause`,
    `            }`,
    `        }`,
    `        sessions[root] = Session(scope, job)`,
    `        job.start()`,
    `    }`,
    ``,
    `    fun release(root: Entity) {`,
    `        val session = sessions.remove(root) ?: return`,
    `        session.job.cancel()`,
    `        session.scope.cancel()`,
    `        session.ownedChildren.asReversed().forEach { entity ->`,
    `            runCatching { root.removeChild(entity) }`,
    `            runCatching { entity.destroy(true) }`,
    `        }`,
    `        session.ownedChildren.clear()`,
    `        val resources = session.resources ?: return`,
    `        session.resources = null`,
    `        CoroutineScope(NonCancellable + Dispatchers.Default).launch { resources.closeBySession() }`,
    `    }`,
    ``,
    `    private suspend fun prepareResources(): Resources {`,
    `        check(Looper.myLooper() != Looper.getMainLooper()) { "Boundary Lab resources must not allocate on Main" }`,
    `        val meshes = mutableListOf<MeshResource>()`,
    `        val materials = mutableListOf<UnlitMaterial>()`,
    `        try {`,
    `            val unitBox = MeshResource.createBox(Vector3(1f, 1f, 1f)).also { meshes += it }`,
    `            currentCoroutineContext().ensureActive()`,
    `            fun material(color: Color4): UnlitMaterial = UnlitMaterial.create().apply { setBaseColor(color) }.also { materials += it }`,
    `            val resources = Resources(`,
    `                unitBox = unitBox,`,
    `                dark = material(Color4(0.015f, 0.02f, 0.045f, 1f)),`,
    `                cyan = material(Color4(0.0f, 0.95f, 1.0f, 1f)),`,
    `                magenta = material(Color4(1.0f, 0.05f, 0.65f, 1f)),`,
    `                yellow = material(Color4(1.0f, 0.85f, 0.05f, 1f)),`,
    `                white = material(Color4(0.95f, 0.98f, 1.0f, 1f)),`,
    `            )`,
    `            currentCoroutineContext().ensureActive()`,
    `            return resources`,
    `        } catch (cause: Throwable) {`,
    `            materials.asReversed().forEach { material -> runCatching { material.close() } }`,
    `            meshes.asReversed().forEach { mesh -> runCatching { mesh.close() } }`,
    `            throw cause`,
    `        }`,
    `    }`,
    ``,
    `    private suspend fun enclosure(root: Entity, resources: Resources) {`,
    `        // Sparse wire/grid geometry preserves passthrough pixels in the Mixed control. Matched floor`,
    `        // and ceiling grids plus perimeter posts make it an all-view cue without opaque room slabs.`,
    `        for ((index, offset) in (-40..40 step 4).withIndex()) {`,
    `            val lineOrdinal = (index + 1).toString()`,
    `            val lineMaterial = if ((offset / 4) % 2 == 0) resources.cyan else resources.magenta`,
    `            primitive(root, HIGH_CONTRAST_ENCLOSURE + "_floor_x_" + lineOrdinal, resources, lineMaterial, Vector3(0f, 0.01f, offset.toFloat()), Vector3(80f, 0.018f, 0.018f))`,
    `            primitive(root, HIGH_CONTRAST_ENCLOSURE + "_floor_z_" + lineOrdinal, resources, lineMaterial, Vector3(offset.toFloat(), 0.01f, 0f), Vector3(0.018f, 0.018f, 80f))`,
    `            primitive(root, HIGH_CONTRAST_ENCLOSURE + "_ceiling_x_" + lineOrdinal, resources, lineMaterial, Vector3(0f, 6f, offset.toFloat()), Vector3(80f, 0.018f, 0.018f))`,
    `            primitive(root, HIGH_CONTRAST_ENCLOSURE + "_ceiling_z_" + lineOrdinal, resources, lineMaterial, Vector3(offset.toFloat(), 6f, 0f), Vector3(0.018f, 0.018f, 80f))`,
    `            if ((index + 1) % 2 == 0) yield()`,
    `        }`,
    `        val edges = listOf(-40f, 40f)`,
    `        edges.forEachIndexed { xIndex, x -> edges.forEachIndexed { zIndex, z ->`,
    `            val cornerOrdinal = (xIndex * edges.size + zIndex + 1).toString()`,
    `            primitive(root, HIGH_CONTRAST_ENCLOSURE + "_perimeter_" + cornerOrdinal, resources, resources.yellow, Vector3(x, 3f, z), Vector3(0.04f, 6f, 0.04f))`,
    `        } }`,
    `        yield()`,
    `    }`,
    ``,
    `    private fun gate(root: Entity, resources: Resources, gate: Gate, index: Int) {`,
    `        val position = gatePosition(gate)`,
    `        val material = when (gate.axis) {`,
    `            Axis.FORWARD -> resources.cyan`,
    `            Axis.BACKWARD -> resources.magenta`,
    `            Axis.LEFT -> resources.yellow`,
    `            Axis.RIGHT -> resources.white`,
    `        }`,
    `        val alongZ = gate.axis == Axis.LEFT || gate.axis == Axis.RIGHT`,
    `        val crossbarScale = if (alongZ) Vector3(0.10f, 0.12f, 2.4f) else Vector3(2.4f, 0.12f, 0.10f)`,
    `        val side = if (alongZ) Vector3(0f, 0f, 1.05f) else Vector3(1.05f, 0f, 0f)`,
    `        val base = "GATE_" + gate.axis.label + "_" + gate.distanceM.toInt() + "M"`,
    `        primitive(root, base + "_left", resources, material, Vector3(position.x - side.x, 1.2f, position.z - side.z), Vector3(0.12f, 2.4f, 0.12f))`,
    `        primitive(root, base + "_right", resources, material, Vector3(position.x + side.x, 1.2f, position.z + side.z), Vector3(0.12f, 2.4f, 0.12f))`,
    `        primitive(root, base + "_crossbar", resources, material, Vector3(position.x, 2.4f, position.z), crossbarScale)`,
    `        // A monotonically taller witness makes all six distances distinguishable without trusting entity names.`,
    `        val distanceOrdinal = index / 4`,
    `        primitive(root, base + "_witness_" + (distanceOrdinal + 1), resources, material, Vector3(position.x, 0.18f + distanceOrdinal * 0.08f, position.z), Vector3(0.28f, 0.36f + distanceOrdinal * 0.16f, 0.28f))`,
    `    }`,
    ``,
    `    fun gatePosition(gate: Gate): Vector3 = when (gate.axis) {`,
    `        Axis.FORWARD -> Vector3(0f, 0f, -gate.distanceM)`,
    `        Axis.BACKWARD -> Vector3(0f, 0f, gate.distanceM)`,
    `        Axis.LEFT -> Vector3(-gate.distanceM, 0f, 0f)`,
    `        Axis.RIGHT -> Vector3(gate.distanceM, 0f, 0f)`,
    `    }`,
    ``,
    `    fun gatePanelPosition(gate: Gate): Vector3 = gatePosition(gate).let { Vector3(it.x, 2.85f, it.z) }`,
    ``,
    `    private fun primitive(root: Entity, name: String, resources: Resources, material: UnlitMaterial, position: Vector3, scale: Vector3): Entity = Entity().also { entity ->`,
    `        entity.setName(name)`,
    `        entity.components.set(TransformComponent(position, Quat.identity(), scale))`,
    `        entity.components.set(ModelComponent(resources.unitBox, material))`,
    `        root.addChild(entity)`,
    `        sessions[root]?.ownedChildren?.add(entity)`,
    `    }`,
    `}`,
    ``,
    `private const val SENTINEL_PANEL_ID = "boundary_lab_sentinel"`,
    ``,
    `@Composable`,
    `fun rememberBoundaryPanelSizes(): Map<String, IntSize> {`,
    `    val sentinel = panelSize(760.dp, 180.dp)`,
    `    val gate = panelSize(420.dp, 140.dp)`,
    `    return buildMap {`,
    `        put(SENTINEL_PANEL_ID, sentinel)`,
    `        BoundaryLabScene.GATES.forEach { put(it.id, gate) }`,
    `    }`,
    `}`,
    ``,
    `fun AttachmentPanelBuilder.boundaryLabPanels(sizes: Map<String, IntSize>, sentinel: String) {`,
    `    AttachmentPanel(id = SENTINEL_PANEL_ID, size = sizes[SENTINEL_PANEL_ID], alignment = AttachmentPanelComponent.Alignment.CENTER) {`,
    `        BoundarySentinelPanel(sentinel)`,
    `    }`,
    `    BoundaryLabScene.GATES.forEach { gate ->`,
    `        AttachmentPanel(id = gate.id, size = sizes[gate.id], alignment = AttachmentPanelComponent.Alignment.CENTER) {`,
    `            BoundaryGatePanel(gate, sentinel)`,
    `        }`,
    `    }`,
    `}`,
    ``,
    `fun SpatialViewAttachments.seatBoundaryLabPanels(content: SpatialViewContent) {`,
    `    entity(SENTINEL_PANEL_ID)?.let { panel ->`,
    `        panel.components.get<TransformComponent>()?.setPosition(Vector3(0f, 1.65f, -2.2f))`,
    `        panel.components.set(LookAtComponent().apply { setViewerAsTarget() })`,
    `        content.addEntity(panel)`,
    `    }`,
    `    BoundaryLabScene.GATES.forEach { gate ->`,
    `        entity(gate.id)?.let { panel ->`,
    `            panel.components.get<TransformComponent>()?.setPosition(BoundaryLabScene.gatePanelPosition(gate))`,
    `            panel.components.set(LookAtComponent().apply { setViewerAsTarget() })`,
    `            content.addEntity(panel)`,
    `        }`,
    `    }`,
    `}`,
    ``,
    `/** Full-stage overload: keep every attachment beneath the replaceable AgentWorldRoot. */`,
    `fun SpatialViewAttachments.seatBoundaryLabPanels(worldRoot: Entity) {`,
    `    entity(SENTINEL_PANEL_ID)?.let { panel ->`,
    `        panel.components.get<TransformComponent>()?.setPosition(Vector3(0f, 1.65f, -2.2f))`,
    `        panel.components.set(LookAtComponent().apply { setViewerAsTarget() })`,
    `        check(worldRoot.addChild(panel)) { "boundary sentinel panel could not be parented beneath AgentWorldRoot" }`,
    `    }`,
    `    BoundaryLabScene.GATES.forEach { gate ->`,
    `        entity(gate.id)?.let { panel ->`,
    `            panel.components.get<TransformComponent>()?.setPosition(BoundaryLabScene.gatePanelPosition(gate))`,
    `            panel.components.set(LookAtComponent().apply { setViewerAsTarget() })`,
    `            check(worldRoot.addChild(panel)) { "boundary gate panel could not be parented beneath AgentWorldRoot" }`,
    `        }`,
    `    }`,
    `}`,
    ``,
    `@Composable`,
    `private fun BoundarySentinelPanel(sentinel: String) {`,
    `    PicoTheme {`,
    `        val colors = PicoTheme.colorScheme`,
    `        val type = PicoTheme.typography`,
    `        Column(modifier = Modifier.background(colors.fillSecondary, RoundedCornerShape(14.dp)).padding(22.dp)) {`,
    `            Text(sentinel, style = type.titleLarge, color = colors.labelPrimary)`,
    `            Text("BOUNDARY LAB · 32 m ENVELOPE", style = type.bodyLarge, color = colors.fillPrimary)`,
    `        }`,
    `    }`,
    `}`,
    ``,
    `@Composable`,
    `private fun BoundaryGatePanel(gate: BoundaryLabScene.Gate, sentinel: String) {`,
    `    PicoTheme {`,
    `        val colors = PicoTheme.colorScheme`,
    `        val type = PicoTheme.typography`,
    `        Column(`,
    `            modifier = Modifier.background(colors.fillSecondary, RoundedCornerShape(10.dp)).padding(14.dp),`,
    `            verticalArrangement = Arrangement.spacedBy(4.dp),`,
    `        ) {`,
    `            Text(gate.distanceM.toInt().toString() + " m · " + gate.axis.label, style = type.titleLarge, color = colors.labelPrimary)`,
    `            Text(sentinel, style = type.bodyLarge, color = colors.fillPrimary)`,
    `            Text("ROUTE GATE", style = type.bodyLarge, color = colors.labelSecondary)`,
    `        }`,
    `    }`,
    `}`,
    ``,
  ].join("\n");
}

function generateProbeRoot(spec: AppSpec, pkg: string): string {
  const contentPkg = `${pkg}.content`;
  return [
    `package ${contentPkg}`,
    ``,
    `import android.app.Activity`,
    `import android.view.ViewTreeObserver`,
    `import androidx.compose.foundation.layout.fillMaxSize`,
    `import androidx.compose.runtime.Composable`,
    `import androidx.compose.runtime.DisposableEffect`,
    `import androidx.compose.runtime.LaunchedEffect`,
    `import androidx.compose.runtime.remember`,
    `import androidx.compose.ui.Modifier`,
    `import androidx.compose.ui.platform.LocalContext`,
    `import androidx.compose.ui.platform.LocalView`,
    `import androidx.lifecycle.LifecycleEventObserver`,
    `import androidx.lifecycle.compose.LocalLifecycleOwner`,
    `import ${pkg}.SpatialContainers`,
    `import ${pkg}.agent.BoundaryProbe`,
    `import com.pico.spatial.core.ecs.Entity`,
    `import com.pico.spatial.core.ecs.TransformComponent`,
    `import com.pico.spatial.core.math.Quat`,
    `import com.pico.spatial.core.math.Vector3`,
    `import com.pico.spatial.ui.foundation.content.SpatialView`,
    `import com.pico.spatial.ui.platform.containers.LocalSpatialNavigator`,
    `import com.pico.spatial.ui.platform.containers.StageStyle`,
    `import java.util.concurrent.atomic.AtomicReference`,
    `import kotlinx.coroutines.Dispatchers`,
    `import kotlinx.coroutines.NonCancellable`,
    `import kotlinx.coroutines.withContext`,
    ``,
    `/** Root-owned experiment bridge. Lifecycle changes are observed but never close the Full Stage. */`,
    `@Composable`,
    `fun BoundaryProbeRoot() {`,
    `    val activity = LocalContext.current as Activity`,
    `    BoundaryProbe.bindLaunchIntent(activity.intent)`,
    `    val navigator = LocalSpatialNavigator.current`,
    `    val lifecycleOwner = LocalLifecycleOwner.current`,
    `    val view = LocalView.current`,
    `    val openRequest = BoundaryProbe.openRequest`,
    ``,
    `    DisposableEffect(lifecycleOwner, view) {`,
    `        val lifecycleObserver = LifecycleEventObserver { _, event -> BoundaryProbe.lifecycle(event.name) }`,
    `        val focusObserver = ViewTreeObserver.OnWindowFocusChangeListener { focused -> BoundaryProbe.focus(focused) }`,
    `        lifecycleOwner.lifecycle.addObserver(lifecycleObserver)`,
    `        view.viewTreeObserver.addOnWindowFocusChangeListener(focusObserver)`,
    `        BoundaryProbe.focus(view.hasWindowFocus())`,
    `        onDispose {`,
    `            lifecycleOwner.lifecycle.removeObserver(lifecycleObserver)`,
    `            if (view.viewTreeObserver.isAlive) view.viewTreeObserver.removeOnWindowFocusChangeListener(focusObserver)`,
    `            // Deliberately no closeStage here: ON_PAUSE/disposal is an observed signal, not recovery authority.`,
    `        }`,
    `    }`,
    ``,
    `    LaunchedEffect(openRequest?.generation) {`,
    `        val request = openRequest ?: return@LaunchedEffect`,
    `        if (!BoundaryProbe.claimOpen(request)) return@LaunchedEffect`,
    `        withContext(NonCancellable) {`,
    `            BoundaryProbe.stageOpenRequested(request)`,
    `            navigator.openStage(SpatialContainers.ID_DYNAMIC_FULL, StageStyle.Full)`,
    `            BoundaryProbe.stageOpenReturned(request)`,
    `        }`,
    `    }`,
    `    HomeStage()`,
    `}`,
    ``,
    `/** Secondary Full content. It owns a separate scene root and the visually distinct DYNAMIC FULL sentinel. */`,
    `@Composable`,
    `fun BoundaryFullStage() {`,
    `    val navigator = LocalSpatialNavigator.current`,
    `    val lifecycleOwner = LocalLifecycleOwner.current`,
    `    val view = LocalView.current`,
    `    val closeRequest = BoundaryProbe.closeRequest`,
    `    val panelSizes = rememberBoundaryPanelSizes()`,
    `    val sceneRoot = remember { AtomicReference<Entity?>(null) }`,
    `    DisposableEffect(lifecycleOwner, view) {`,
    `        val ownsObservations = BoundaryProbe.claimDynamicObservationOwner()`,
    `        val lifecycleObserver = LifecycleEventObserver { _, event -> if (ownsObservations) BoundaryProbe.dynamicLifecycle(event.name) }`,
    `        val focusObserver = ViewTreeObserver.OnWindowFocusChangeListener { focused -> if (ownsObservations) BoundaryProbe.dynamicFocus(focused) }`,
    `        if (ownsObservations) {`,
    `            lifecycleOwner.lifecycle.addObserver(lifecycleObserver)`,
    `            view.viewTreeObserver.addOnWindowFocusChangeListener(focusObserver)`,
    `            BoundaryProbe.dynamicFocus(view.hasWindowFocus())`,
    `        }`,
    `        onDispose {`,
    `            if (ownsObservations) {`,
    `                lifecycleOwner.lifecycle.removeObserver(lifecycleObserver)`,
    `                if (view.viewTreeObserver.isAlive) view.viewTreeObserver.removeOnWindowFocusChangeListener(focusObserver)`,
    `                BoundaryProbe.releaseDynamicObservationOwner()`,
    `            }`,
    `        }`,
    `    }`,
    `    DisposableEffect(Unit) {`,
    `        onDispose { sceneRoot.getAndSet(null)?.let { BoundaryLabScene.release(it) } }`,
    `    }`,
    `    LaunchedEffect(closeRequest?.generation) {`,
    `        val request = closeRequest ?: return@LaunchedEffect`,
    `        if (!BoundaryProbe.claimClose(request)) return@LaunchedEffect`,
    `        withContext(NonCancellable) {`,
    `            BoundaryProbe.explicitCloseRequested(request)`,
    `            navigator.closeStage()`,
    `            BoundaryProbe.explicitCloseReturned(request)`,
    `        }`,
    `    }`,
    `    SpatialView(`,
    `        modifier = Modifier.fillMaxSize(),`,
    `        attachments = { boundaryLabPanels(panelSizes, BoundaryLabScene.DYNAMIC_FULL_SENTINEL) },`,
    `        initial = { content, attachments ->`,
    `            withContext(Dispatchers.Main.immediate) {`,
    `                val root = Entity()`,
    `                root.setName("BoundaryDynamicFullRoot")`,
    `                root.components.set(TransformComponent(Vector3.ZERO, Quat.identity(), Vector3(1f, 1f, 1f)))`,
    `                content.addEntity(root)`,
    `                sceneRoot.set(root)`,
    `                BoundaryLabScene.build(root)`,
    `                attachments.seatBoundaryLabPanels(content)`,
    `            }`,
    `        },`,
    `    )`,
    `}`,
    ``,
  ].join("\n");
}

function generateDebugProbe(pkg: string): string {
  return [
    `package ${pkg}.agent`,
    ``,
    `import android.content.Intent`,
    `import android.os.SystemClock`,
    `import android.util.Log`,
    `import androidx.compose.runtime.getValue`,
    `import androidx.compose.runtime.mutableStateOf`,
    `import androidx.compose.runtime.setValue`,
    `import java.security.MessageDigest`,
    `import org.json.JSONObject`,
    ``,
    `/** Debug-only, launch-bound BoundaryProbe command authority. Raw capability bytes are never logged. */`,
    `object BoundaryProbe {`,
    `    const val ACTION = "${pkg}.BOUNDARY_PROBE"`,
    `    const val RECEIVER_CLASS = "${pkg}.agent.BoundaryProbeReceiver"`,
    `    const val STAGE_ID = "dynamic-full"`,
    `    const val EXTRA_SESSION_ID = "pico.boundary.session"`,
    `    const val EXTRA_CAPABILITY = "pico.boundary.capability"`,
    `    const val EXTRA_GENERATION = "pico.boundary.generation"`,
    `    const val EXTRA_COMMAND = "pico.boundary.command"`,
    `    const val EXTRA_STAGE_ID = "pico.boundary.stage"`,
    `    const val COMMAND_OPEN = "open"`,
    `    const val COMMAND_CLOSE = "close"`,
    `    private const val TAG = "BoundaryProbe"`,
    `    private const val PREFIX = "PICO_BOUNDARY_PROBE_V1 "`,
    ``,
    `    data class OpenRequest(val sessionId: String, val generation: Long)`,
    `    data class CloseRequest(val sessionId: String, val generation: Long)`,
    `    private enum class RouteState { IDLE, OPEN_PENDING, OPENING, OPEN, CLOSE_PENDING, CLOSING }`,
    `    private enum class ObservationOwner { MANIFEST_ROOT, DYNAMIC_FULL }`,
    ``,
    `    var openRequest by mutableStateOf<OpenRequest?>(null)`,
    `        private set`,
    `    var closeRequest by mutableStateOf<CloseRequest?>(null)`,
    `        private set`,
    `    private var boundSessionId: String? = null`,
    `    private var boundCapability: String? = null`,
    `    private var nextGeneration: Long? = null`,
    `    private var activeGeneration: Long? = null`,
    `    private var routeState = RouteState.IDLE`,
    `    private var observationOwner = ObservationOwner.MANIFEST_ROOT`,
    `    private var dynamicStageActive = false`,
    `    private var returnedCycle = false`,
    `    private var stageOpenReturnedGeneration: Long? = null`,
    `    private var sequence = 0L`,
    ``,
    `    fun bindLaunchIntent(intent: Intent) {`,
    `        if (boundSessionId != null) return`,
    `        val session = intent.getStringExtra(EXTRA_SESSION_ID) ?: return`,
    `        val capability = intent.getStringExtra(EXTRA_CAPABILITY) ?: return`,
    `        val generation = intent.getLongExtra(EXTRA_GENERATION, -1L)`,
    `        if (!session.matches(Regex("[A-Za-z0-9][A-Za-z0-9._:-]{0,127}"))) return`,
    `        if (!capability.matches(Regex("[A-Za-z0-9_-]{32,256}"))) return`,
    `        if (generation <= 0L || generation > Int.MAX_VALUE.toLong()) return`,
    `        boundSessionId = session`,
    `        boundCapability = capability`,
    `        nextGeneration = generation`,
    `        activeGeneration = null`,
    `        routeState = RouteState.IDLE`,
    `        observationOwner = ObservationOwner.MANIFEST_ROOT`,
    `        dynamicStageActive = false`,
    `        returnedCycle = false`,
    `        stageOpenReturnedGeneration = null`,
    `        openRequest = null`,
    `        closeRequest = null`,
    `        sequence = 0L`,
    `        Log.i(TAG, "launch binding session=" + session + " generation=" + generation + " capabilitySha256=" + capabilityFingerprint(capability))`,
    `    }`,
    ``,
    `    @Synchronized`,
    `    fun acceptExplicitCommand(intent: Intent, componentClass: String): Boolean {`,
    `        val session = intent.getStringExtra(EXTRA_SESSION_ID) ?: return false`,
    `        val capability = intent.getStringExtra(EXTRA_CAPABILITY) ?: return false`,
    `        val generation = intent.getLongExtra(EXTRA_GENERATION, -1L)`,
    `        val command = intent.getStringExtra(EXTRA_COMMAND) ?: return false`,
    `        val stageId = intent.getStringExtra(EXTRA_STAGE_ID) ?: return false`,
    `        if (session.length !in 1..128) return false`,
    `        if (capability.length !in 32..256) return false`,
    `        if (command.length !in 1..16) return false`,
    `        if (stageId.length !in 1..64) return false`,
    `        if (intent.action != ACTION) return false`,
    `        if (componentClass != RECEIVER_CLASS) return false`,
    `        if (session != boundSessionId) return false`,
    `        if (generation != nextGeneration) return false`,
    `        if (stageId != STAGE_ID) return false`,
    `        if (command != COMMAND_OPEN && command != COMMAND_CLOSE) return false`,
    `        if (!constantTimeEquals(capability, boundCapability ?: return false)) return false`,
    `        val canOpen = !dynamicStageActive && (routeState == RouteState.IDLE || (routeState == RouteState.OPEN && returnedCycle))`,
    `        if (command == COMMAND_OPEN && !canOpen) return false`,
    `        if (command == COMMAND_CLOSE && (routeState != RouteState.OPEN || !dynamicStageActive)) return false`,
    ``,
    `        // All authentication checks precede sequence or observable-state mutation.`,
    `        // Consume this generation before publishing Compose state that schedules navigation.`,
    `        nextGeneration = generation + 1`,
    `        activeGeneration = generation`,
    `        sequence = 0L`,
    `        emit(kind = "command_received", generation = generation, detail = "command=" + command)`,
    `        if (command == COMMAND_OPEN) {`,
    `            returnedCycle = false`,
    `            stageOpenReturnedGeneration = null`,
    `            routeState = RouteState.OPEN_PENDING`,
    `            openRequest = OpenRequest(session, generation)`,
    `        }`,
    `        if (command == COMMAND_CLOSE) {`,
    `            routeState = RouteState.CLOSE_PENDING`,
    `            closeRequest = CloseRequest(session, generation)`,
    `        }`,
    `        return true`,
    `    }`,
    ``,
    `    @Synchronized`,
    `    fun claimDynamicObservationOwner(): Boolean {`,
    `        if (routeState != RouteState.OPENING && routeState != RouteState.OPEN) return false`,
    `        if (observationOwner != ObservationOwner.MANIFEST_ROOT) return false`,
    `        if (routeState == RouteState.OPENING) routeState = RouteState.OPEN`,
    `        dynamicStageActive = true`,
    `        returnedCycle = false`,
    `        observationOwner = ObservationOwner.DYNAMIC_FULL`,
    `        return true`,
    `    }`,
    `    @Synchronized`,
    `    fun releaseDynamicObservationOwner() {`,
    `        if (observationOwner != ObservationOwner.DYNAMIC_FULL) return`,
    `        observationOwner = ObservationOwner.MANIFEST_ROOT`,
    `        dynamicStageActive = false`,
    `        if (routeState == RouteState.OPEN) returnedCycle = true`,
    `    }`,
    ``,
    `    @Synchronized`,
    `    fun claimOpen(request: OpenRequest): Boolean {`,
    `        if (routeState != RouteState.OPEN_PENDING || openRequest != request) return false`,
    `        if (request.sessionId != boundSessionId || request.generation != activeGeneration) return false`,
    `        routeState = RouteState.OPENING`,
    `        return true`,
    `    }`,
    `    @Synchronized`,
    `    fun claimClose(request: CloseRequest): Boolean {`,
    `        if (routeState != RouteState.CLOSE_PENDING || closeRequest != request) return false`,
    `        if (request.sessionId != boundSessionId || request.generation != activeGeneration) return false`,
    `        routeState = RouteState.CLOSING`,
    `        return true`,
    `    }`,
    ``,
    `    @Synchronized`,
    `    fun stageOpenRequested(request: OpenRequest) {`,
    `        if (routeState == RouteState.OPENING && request.sessionId == boundSessionId && request.generation == activeGeneration)`,
    `            emit("stage_open_requested", request.generation, requestedDynamicStageStyle = "Full")`,
    `    }`,
    `    @Synchronized`,
    `    fun stageOpenReturned(request: OpenRequest) {`,
    `        if ((routeState == RouteState.OPENING || routeState == RouteState.OPEN) && request.sessionId == boundSessionId && request.generation == activeGeneration && stageOpenReturnedGeneration != request.generation) {`,
    `            stageOpenReturnedGeneration = request.generation`,
    `            emit("stage_open_returned", request.generation, requestedDynamicStageStyle = "Full")`,
    `            routeState = RouteState.OPEN`,
    `        }`,
    `    }`,
    `    @Synchronized`,
    `    fun explicitCloseRequested(request: CloseRequest) {`,
    `        if (routeState == RouteState.CLOSING && request.sessionId == boundSessionId && request.generation == activeGeneration) emit("explicit_close_requested", request.generation)`,
    `    }`,
    `    @Synchronized`,
    `    fun explicitCloseReturned(request: CloseRequest) {`,
    `        if (routeState == RouteState.CLOSING && request.sessionId == boundSessionId && request.generation == activeGeneration) {`,
    `            emit("explicit_close_returned", request.generation)`,
    `            routeState = RouteState.IDLE`,
    `        }`,
    `    }`,
    `    @Synchronized`,
    `    fun lifecycle(event: String) {`,
    `        val generation = activeGeneration ?: return`,
    `        if (event !in setOf("ON_CREATE", "ON_START", "ON_RESUME", "ON_PAUSE", "ON_STOP", "ON_DESTROY")) return`,
    `        if (observationOwner == ObservationOwner.MANIFEST_ROOT) emit("lifecycle", generation, lifecycle = event)`,
    `    }`,
    `    @Synchronized`,
    `    fun focus(focused: Boolean) {`,
    `        val generation = activeGeneration ?: return`,
    `        if (observationOwner == ObservationOwner.MANIFEST_ROOT) emit("focus", generation, detail = "root=" + focused)`,
    `    }`,
    `    @Synchronized`,
    `    fun dynamicLifecycle(event: String) {`,
    `        if (observationOwner != ObservationOwner.DYNAMIC_FULL) return`,
    `        val generation = activeGeneration ?: return`,
    `        if (event in setOf("ON_CREATE", "ON_START", "ON_RESUME", "ON_PAUSE", "ON_STOP", "ON_DESTROY"))`,
    `            emit("lifecycle", generation, lifecycle = event, detail = "owner=dynamic_full")`,
    `    }`,
    `    @Synchronized`,
    `    fun dynamicFocus(focused: Boolean) {`,
    `        if (observationOwner != ObservationOwner.DYNAMIC_FULL) return`,
    `        val generation = activeGeneration ?: return`,
    `        emit("focus", generation, detail = "dynamic_full=" + focused)`,
    `    }`,
    ``,
    `    private fun emit(kind: String, generation: Long, lifecycle: String? = null, requestedDynamicStageStyle: String? = null, detail: String? = null) {`,
    `        val session = boundSessionId ?: return`,
    `        sequence += 1L`,
    `        val event = JSONObject()`,
    `            .put("schemaVersion", 1)`,
    `            .put("sessionId", session)`,
    `            .put("generation", generation)`,
    `            .put("seq", sequence)`,
    `            .put("monotonicNs", SystemClock.elapsedRealtimeNanos().toString())`,
    `            .put("kind", kind)`,
    `        if (lifecycle != null) event.put("lifecycle", lifecycle)`,
    `        if (requestedDynamicStageStyle != null) event.put("requestedDynamicStageStyle", requestedDynamicStageStyle)`,
    `        if (detail != null) event.put("detail", detail)`,
    `        Log.i(TAG, PREFIX + event.toString())`,
    `    }`,
    ``,
    `    private fun constantTimeEquals(left: String, right: String): Boolean =`,
    `        MessageDigest.isEqual(left.toByteArray(Charsets.UTF_8), right.toByteArray(Charsets.UTF_8))`,
    ``,
    `    private fun capabilityFingerprint(value: String): String = MessageDigest.getInstance("SHA-256")`,
    `        .digest(value.toByteArray(Charsets.UTF_8)).joinToString("") { byte -> "%02x".format(byte) }`,
    `}`,
    ``,
  ].join("\n");
}

