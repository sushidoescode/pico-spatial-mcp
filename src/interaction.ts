import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * interaction.ts — v5.0 INTERACTION primitive (second of the three brief-to-app compiler prerequisites).
 *
 * Source-verified facts (SDK 0.13.3), built on the PROVEN rayCast recipe (collider.ts) so it inherits
 * the on-device gotchas rather than re-deriving them:
 *  - `InteractableComponent()` (no-arg) marks an entity as interactable; it must ALSO carry a queryable
 *    CollisionComponent for a ray to hit it.
 *  - `CollisionComponent(listOf(ShapeResource.createBox(FULL extents)), PhysicsMaterialResource(...),
 *    CollisionResponseMode.COLLIDER_FULL, CollisionFilter.COLLISION_FILTER_DEFAULT,
 *    CollisionInfoDetailLevel.BRIEF)` — the verified 5-arg ctor; only PRIMITIVE shapes register on-device.
 *  - `scene.rayCast(origin, direction, length, CollisionCastHitMode.NEAREST,
 *    CollisionGroup(CollisionGroup.COLLISION_GROUP_ALL), null).results.firstOrNull()` → CollisionCastResult?;
 *    a queryable ray needs a PhysicsWorldComponent on an ancestor (SpatialColliders.attachPhysicsWorld).
 *  - highlight uses `TransformComponent.scaleVector` (a mutable Vector3 property — NOT `.scale`).
 *
 * The honesty engine hangs off the trigger class baked into each call: BROADCAST select/hover is
 * C0 (emulator-verifiable via <pkg>.DEBUG_CMD — this is WHY the emulator has no controller/gaze); the
 * ray path (gaze-dwell / controller-ray) is real only on Swan (C3). select()/hover() are the broadcast
 * entry points; pick(scene, origin, dir) is the ray entry point. Selection state + an optional
 * scale-bump highlight are built in (a same-scale highlight is invisible → we scale, the retained lesson).
 */
export function registerInteractionTools(server: McpServer) {
  server.registerTool(
    "generate_interaction_kotlin",
    {
      description:
        "Emit SceneInteraction.kt — a raycast-driven selection/hover engine for spatial objects. register(id, entity, ...) marks an object interactable (InteractableComponent + a primitive box CollisionComponent so a ray can hit it) and stores its onSelect/onHover callbacks; select(id)/hover(id) are the BROADCAST entry points (C0, emulator-verifiable via <pkg>.DEBUG_CMD) and pick(scene, origin, dir) is the RAY entry point (gaze-dwell/controller-ray — real only on Swan, C3). Tracks selection state and applies an optional scale-bump highlight (scaleVector — a same-scale highlight is invisible, the retained lesson). Requires a PhysicsWorldComponent on an ancestor for the ray path (use SpatialColliders.attachPhysicsWorld from generate_collider_kotlin). Compiles against SDK 0.13.3; broadcast-select + highlight are vision-verifiable on the emulator, controller-ray is built-for-Swan. RETURNS: raw Kotlin text (write it to the targetPath yourself).",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
        highlightScale: z.number().optional().describe("Scale multiplier applied to the selected item (default 1.1). Set 1.0 to disable the scale highlight."),
        defaultBoxSize: z.array(z.number()).optional().describe("Default interactable collider FULL box size [x,y,z] in meters (default [0.6,0.6,0.04]). createBox uses FULL extents."),
        friction: z.number().optional().describe("Collider static/dynamic friction (default 0.5)."),
      },
    },
    async ({ packageName, highlightScale, defaultBoxSize, friction }) => {
      const hs = highlightScale ?? 1.1;
      const box = (defaultBoxSize && defaultBoxSize.length === 3 ? defaultBoxSize : [0.6, 0.6, 0.04]) as number[];
      const fric = friction ?? 0.5;
      const kt = [
        `package ${packageName}`,
        "",
        "import android.os.Handler",
        "import android.os.Looper",
        "import android.util.Log",
        "import com.pico.spatial.core.ecs.CollisionComponent",
        "import com.pico.spatial.core.ecs.Entity",
        "import com.pico.spatial.core.ecs.InteractableComponent",
        "import com.pico.spatial.core.ecs.Scene",
        "import com.pico.spatial.core.ecs.TransformComponent",
        "import com.pico.spatial.core.ecs.resource.PhysicsMaterialResource",
        "import com.pico.spatial.core.ecs.resource.ShapeResource",
        "import com.pico.spatial.core.ecs.simulation.CollisionCastHitMode",
        "import com.pico.spatial.core.ecs.simulation.CollisionFilter",
        "import com.pico.spatial.core.ecs.simulation.CollisionGroup",
        "import com.pico.spatial.core.ecs.simulation.CollisionInfoDetailLevel",
        "import com.pico.spatial.core.ecs.simulation.CollisionResponseMode",
        "import com.pico.spatial.core.math.Vector3",
        "",
        "/**",
        " * Generated by generate_interaction_kotlin. Raycast + broadcast-driven selection/hover.",
        " * Trigger classes (each AppSpec interaction node carries one; the comment is the honesty tag):",
        " *   BROADCAST  select(id)/hover(id) via <pkg>.DEBUG_CMD ........ C0 emulator-verifiable",
        " *   GAZE_DWELL head-forward ray dwell (emulator has no gaze) ... broadcast-emulated C0 / real C3",
        " *   CONTROLLER_RAY 6DOF controller ray + trigger ............... C3 headset-only",
        " *   PRESS      a button press ............................. NOT this file — compiles to the",
        " *              clickable in-world GameMenu (generate_game_menu_kotlin), C0 (mouse bridge + broadcast)",
        " * Usage:",
        " *   SceneInteraction.register(\"item0\", cardEntity) { id -> showDetail(id) }",
        " *   // emulator: adb shell am broadcast -a <pkg>.DEBUG_CMD --es cmd select:item0",
        " *   // headset:  SceneInteraction.pick(model.scene, controllerOrigin, controllerForward)",
        " * Requires SpatialColliders.attachPhysicsWorld(root) (generate_collider_kotlin) for the ray path.",
        " * VERIFY: compiles; broadcast-select + scale highlight are vision-verifiable (LOOK); ray = Swan.",
        " */",
        "object SceneInteraction {",
        "    /** The interaction layer. Deliberately bit 0 (== COLLISION_GROUP_DEFAULT) so ray picking",
        "     *  with COLLISION_GROUP_ALL is unchanged; the MASK is what keeps physics bodies out. */",
        '    const val GROUP_INTERACTION: UInt = 1u',
        '    private const val TAG = "SceneInteraction"',
        "",
        "    class Interactable(",
        "        val id: String,",
        "        val entity: Entity,",
        "        val onSelect: (String) -> Unit,",
        "        val onHover: ((String) -> Unit)?,",
        "        val baseScale: Vector3,",
        "    )",
        "",
        "    private val registry = LinkedHashMap<String, Interactable>()",
        "    private val entityToId = HashMap<Entity, String>()",
        "",
        "    var selected: String? = null",
        "        private set",
        "    var hovered: String? = null",
        "        private set",
        `    var highlightScale: Float = ${hs}f`,
        "    var onSelectionChanged: ((String?) -> Unit)? = null",
        "",
        "    private fun physMat() = PhysicsMaterialResource(" + `${fric}f, ${fric}f, 0f)`,
        "",
        "    private val mainHandler = Handler(Looper.getMainLooper())",
        "",
        "    // Scene mutation (highlight scaleVector, entity creation in onSelect) MUST run on the main thread.",
        "    // Broadcast-driven select/hover arrive on a binder thread on the emulator, so marshal to main.",
        "    private fun onMain(block: () -> Unit) {",
        "        if (Looper.myLooper() == Looper.getMainLooper()) block() else mainHandler.post(block)",
        "    }",
        "",
        "    /** Mark [entity] interactable (InteractableComponent + a primitive box collider) and store callbacks. */",
        "    fun register(",
        "        id: String,",
        "        entity: Entity,",
        `        boxSize: Vector3 = Vector3(${box[0]}f, ${box[1]}f, ${box[2]}f),`,
        "        onHover: ((String) -> Unit)? = null,",
        "        onSelect: (String) -> Unit,",
        "    ) {",
        "        runCatching {",
        "            entity.components.set(InteractableComponent())",
        "            entity.components.set(",
        "                CollisionComponent(",
        "                    listOf(ShapeResource.createBox(boxSize)),",
        "                    physMat(),",
        "                    // v35.13 TRIGGER_LITE, not COLLIDER_FULL. A tap target with COLLIDER_FULL is a",
        "                    // PHYSICAL OBSTACLE: CollisionResponseMode.COLLIDER_FULL 'applies physical",
        "                    // collision effects' (CollisionResponseMode.kt:41-46), and both this and every",
        "                    // ScenePhysics body default to COLLISION_FILTER_DEFAULT (group 1u, mask ALL),",
        "                    // which always pairs (CollisionFilter.kt:26-28,93-97). So every selectable card",
        "                    // used to be an invisible wall that dynamic bodies bounced off. PICO's own",
        "                    // spatial-tap target is TRIGGER_LITE on a private group: InteractionReceiver.kt:49-55.",
        "                    CollisionResponseMode.TRIGGER_LITE,",
        "                    // group stays bit 0 so Scene.rayCast(..., COLLISION_GROUP_ALL, ...) still picks it;",
        "                    // the MASK is what excludes physics. Pair rule: (A.mask AND B.group) != 0 in BOTH",
        "                    // directions — a physics body on any other bit can no longer pair with UI.",
        "                    CollisionFilter(CollisionGroup(GROUP_INTERACTION), CollisionGroup(GROUP_INTERACTION)),",
        "                    CollisionInfoDetailLevel.BRIEF,",
        "                ),",
        "            )",
        "            val base = entity.components.get<TransformComponent>()?.scaleVector ?: Vector3(1f, 1f, 1f)",
        "            registry[id] = Interactable(id, entity, onSelect, onHover, base)",
        "            entityToId[entity] = id",
        "            Log.i(TAG, \"registered interactable '$id'\")",
        "        }.onFailure { Log.e(TAG, \"register '$id' failed: ${it.message}\") }",
        "    }",
        "",
        "    /** BROADCAST/GAZE commit (C0): highlight + fire onSelect for [id]. */",
        "    fun select(id: String) = onMain {",
        "        val item = registry[id] ?: run { Log.w(TAG, \"select: unknown id '$id'\"); return@onMain }",
        "        setHighlight(selected, false)",
        "        selected = id",
        "        setHighlight(id, true)",
        "        runCatching { item.onSelect(id) }.onFailure { Log.e(TAG, \"onSelect '$id' failed: ${it.message}\") }",
        "        onSelectionChanged?.invoke(id)",
        "        Log.i(TAG, \"selected $id\")",
        "    }",
        "",
        "    /** BROADCAST/GAZE preview (C0): fire onHover for [id] without committing. */",
        "    fun hover(id: String) = onMain {",
        "        val item = registry[id] ?: run { Log.w(TAG, \"hover: unknown id '$id'\"); return@onMain }",
        "        hovered = id",
        "        runCatching { item.onHover?.invoke(id) }.onFailure { Log.e(TAG, \"onHover '$id' failed: ${it.message}\") }",
        "    }",
        "",
        "    /** RAY path (gaze/controller — C3 on Swan): cast into [scene] and select the nearest interactable hit. */",
        "    fun pick(scene: Scene?, origin: Vector3, direction: Vector3, maxDistance: Float = 10f): String? {",
        "        val hit = runCatching {",
        "            // PRECONDITION: an ancestor of the hit targets must carry a PhysicsWorldComponent,",
        "            // or rayCast returns 0 hits with no error and this silently never selects anything.",
        "            // SpatialColliders.attachPhysicsWorld(root) from generate_collider_kotlin does it.",
        "            scene?.rayCast(",
        "                origin, direction, maxDistance, CollisionCastHitMode.NEAREST,",
        "                CollisionGroup(CollisionGroup.COLLISION_GROUP_ALL), null,",
        "            )?.results?.firstOrNull()",
        "        }.getOrNull() ?: return null",
        "        val id = entityToId[hit.entity] ?: return null.also { Log.i(TAG, \"pick hit a non-interactable\") }",
        "        select(id)",
        "        return id",
        "    }",
        "",
        "    /** Forget all interactables (e.g. on a scene transition). */",
        "    fun clear() {",
        "        registry.clear(); entityToId.clear(); selected = null; hovered = null",
        "    }",
        "",
        "    private fun setHighlight(id: String?, on: Boolean) {",
        "        val item = id?.let { registry[it] } ?: return",
        "        val tc = item.entity.components.get<TransformComponent>() ?: return",
        "        val f = if (on) highlightScale else 1f",
        "        runCatching {",
        "            tc.scaleVector = Vector3(item.baseScale.x * f, item.baseScale.y * f, item.baseScale.z * f)",
        "        }.onFailure { Log.e(TAG, \"highlight '$id' failed: ${it.message}\") }",
        "    }",
        "}",
        "",
        "/*",
        " * ── Wiring the BROADCAST channel (emulator drive path, C0) ──────────────────────────────────",
        " * In your Activity/initializer register a receiver for <pkg>.DEBUG_CMD and route to SceneInteraction:",
        " *",
        " *   val f = IntentFilter(\"" + packageName.replace(/\.content$/, "") + ".DEBUG_CMD\")",
        " *   registerReceiver(object : BroadcastReceiver() {",
        " *       override fun onReceive(c: Context, i: Intent) {",
        " *           val cmd = i.getStringExtra(\"cmd\") ?: return",
        " *           when {",
        " *               cmd.startsWith(\"select:\") -> SceneInteraction.select(cmd.removePrefix(\"select:\"))",
        " *               cmd.startsWith(\"hover:\")  -> SceneInteraction.hover(cmd.removePrefix(\"hover:\"))",
        " *           }",
        " *       }",
        " *   }, f, Context.RECEIVER_EXPORTED)",
        " *",
        " *   Drive it:  adb shell am broadcast -a <pkg>.DEBUG_CMD --es cmd select:item0",
        " */",
        "",
      ].join("\n");
      return ok(kt);
    },
  );
}
