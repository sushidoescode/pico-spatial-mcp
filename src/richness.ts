import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * v3.8 richness codegen — spatial audio / animation / persistent anchors. Each emits Kotlin that
 * COMPILES against the SDK (authoring/attach proven structurally); the RUNTIME behaviour (audio
 * playback, keyframe playback, cross-launch anchor persistence) is HEADSET-ONLY and flagged.
 * APIs sources-confirmed (core/sense 0.13.3).
 */

function audioKt(pkg: string): string {
  return [
    `package ${pkg}`,
    "",
    "import android.util.Log",
    "import com.pico.spatial.core.ecs.Entity",
    "import com.pico.spatial.core.ecs.ObjectAudioComponent",
    "",
    "/**",
    " * Generated by generate_spatial_audio_kotlin. Attaches a 3D positional audio source",
    " * (ObjectAudioComponent: volume + spatial radius/attenuation) to an entity.",
    " * !!! VERIFY ON: PICO Swan headset. The component ATTACH is structural (logcat-assertable on the",
    " * emulator); audio PLAYBACK is headset-only (the emulator has no guaranteed audio device).",
    " * Load the clip via the editor-authored SpatialAudioFile (author_editor_component) or an",
    " * AudioResourceLibraryComponent on the scene root.",
    " */",
    "object SpatialAudio {",
    '    private const val TAG = "SpatialAudio"',
    "",
    "    /** Attach a 3D audio source to [entity]. Call after the entity is in the scene. */",
    "    fun attach(entity: Entity, volume: Float = 1f, radiusLevel: Float = 1f) {",
    "        runCatching {",
    "            val audio = ObjectAudioComponent().apply {",
    "                this.volume = volume",
    "                this.soundRadiusLevel = radiusLevel",
    "            }",
    "            entity.components.set(audio)",
    '            Log.i(TAG, "3D audio source attached (vol=$volume radius=$radiusLevel) — playback is headset-only")',
    "        }.onFailure { Log.e(TAG, \"audio attach failed: ${it.message}\") }",
    "    }",
    "}",
    "",
  ].join("\n");
}

function animationKt(pkg: string): string {
  return [
    `package ${pkg}`,
    "",
    "import android.util.Log",
    "import com.pico.spatial.core.ecs.Entity",
    "import com.pico.spatial.core.ecs.animation.AnimationPlayConfig",
    "import com.pico.spatial.core.ecs.animation.AnimationPlaybackController",
    "import com.pico.spatial.core.ecs.resource.AnimationResource",
    "",
    "/**",
    " * Generated by generate_animation_kotlin. Plays an AnimationResource on an entity + loop helper.",
    " * !!! VERIFY ON: confirm the visible motion on the emulator with verify_visual, or on PICO Swan.",
    " * Obtain [res] from your pipeline — AnimationResource.generateWithTweenAnimation(tween) for",
    " * procedural tweens, or your editor-authored animation asset. (There is no AnimationResource.load",
    " * by name in this SDK version — javap-confirm the asset path for editor animations on your build.)",
    " */",
    "object SceneAnimation {",
    '    private const val TAG = "SceneAnimation"',
    "",
    "    /** Play [res] on [entity]; returns the controller (pause/resume/stop/isComplete). */",
    "    fun play(entity: Entity, res: AnimationResource): AnimationPlaybackController? =",
    "        runCatching { entity.playAnimation(res, AnimationPlayConfig()) }",
    '            .onSuccess { Log.i(TAG, "playAnimation -> valid=${it.valid} playing=${it.isPlaying()}") }',
    "            .getOrElse { Log.e(TAG, \"playAnimation failed: ${it.message}\"); null }",
    "",
    "    /** Re-trigger when complete (poll from your frame loop) for a simple loop. */",
    "    fun loopIfComplete(ctrl: AnimationPlaybackController?, entity: Entity, res: AnimationResource): AnimationPlaybackController? =",
    "        if (ctrl == null || ctrl.isComplete()) play(entity, res) else ctrl",
    "}",
    "",
  ].join("\n");
}

function anchorKt(pkg: string): string {
  return [
    `package ${pkg}`,
    "",
    "import android.util.Log",
    "import com.pico.spatial.core.math.EulerAngles",
    "import com.pico.spatial.core.math.Vector3",
    "import com.pico.spatial.sense.world.WorldAnchor",
    "import com.pico.spatial.sense.world.WorldTrackingManager",
    "import com.pico.spatial.sense.world.WorldTrackingResult",
    "import java.util.UUID",
    "",
    "/**",
    " * Generated by generate_persistent_anchor_kotlin. Save/load persistent WorldAnchor poses across",
    " * launches via WorldTrackingManager.",
    " * !!! VERIFY ON: PICO Swan headset. The EMULATOR has no world-tracking — createAnchor/loadAnchor",
    " * return a WorldTrackingResult failure there (no real anchoring; cross-launch persistence is",
    " * headset-only). The calls compile + run; persist returned anchorUUIDs to reload next launch.",
    " */",
    "object WorldAnchors {",
    '    private const val TAG = "WorldAnchors"',
    "",
    "    private fun <T> WorldTrackingResult<T>.dataOrNull(): T? = (this as? WorldTrackingResult.Success)?.data",
    "",
    "    /** Create a persistent anchor at a pose. Returns the WorldAnchor (persist its anchorUUID) or null. */",
    "    suspend fun create(position: Vector3, rotation: EulerAngles = EulerAngles(0f, 0f, 0f)): WorldAnchor? =",
    "        runCatching { WorldTrackingManager.createAnchor(position, rotation).dataOrNull() }",
    "            .getOrElse { Log.e(TAG, \"createAnchor failed (emulator? headset-only): ${it.message}\"); null }",
    "",
    "    /** Reload previously-persisted anchors by UUID (empty = all). */",
    "    suspend fun load(uuids: Array<UUID> = arrayOf()): Array<WorldAnchor> =",
    "        runCatching { WorldTrackingManager.loadAnchor(uuids).dataOrNull() ?: emptyArray() }",
    "            .getOrElse { Log.e(TAG, \"loadAnchor failed (emulator? headset-only): ${it.message}\"); emptyArray() }",
    "",
    "    suspend fun remove(uuid: UUID) { runCatching { WorldTrackingManager.removeAnchor(uuid) } }",
    "}",
    "",
  ].join("\n");
}

export function registerRichnessTools(server: McpServer) {
  server.registerTool(
    "generate_spatial_audio_kotlin",
    {
      description:
        "Emit SpatialAudio.kt: attach a 3D positional audio source (ObjectAudioComponent — volume + spatial radius) to an entity. Component attach is structural (logcat-assertable); audio PLAYBACK is headset-only (no guaranteed emulator audio device). Load the clip via the editor SpatialAudioFile / AudioResourceLibraryComponent.",
      inputSchema: { packageName: z.string().describe("Kotlin package, e.g. com.example.app.content") },
    },
    async ({ packageName }) => ok(audioKt(packageName)),
  );

  server.registerTool(
    "generate_animation_kotlin",
    {
      description:
        "Emit SceneAnimation.kt: load an AnimationResource from the bundle and play it on an entity (Entity.playAnimation -> AnimationPlaybackController), with a simple loop helper. CAVEAT (v8.1): AnimationResource playback does NOT reliably propagate through the SpatialView hierarchy for RUNTIME-built entities — expect NO visible motion there. Use this only for editor-authored/baked animation on loaded assets; for procedural motion on runtime entities use `generate_scene_animator_kotlin` (SceneAnimator, the vision-verified path). Loading/attach is structural.",
      inputSchema: { packageName: z.string().describe("Kotlin package, e.g. com.example.app.content") },
    },
    async ({ packageName }) => ok(animationKt(packageName)),
  );

  server.registerTool(
    "generate_persistent_anchor_kotlin",
    {
      description:
        "Emit WorldAnchors.kt: create/load/remove persistent WorldAnchor poses across launches via WorldTrackingManager. Compiles + runs, but the EMULATOR has no world-tracking (createAnchor/loadAnchor return errors there) — real anchoring + cross-launch persistence are HEADSET-ONLY (C1). Persist returned UUIDs to reload.",
      inputSchema: { packageName: z.string().describe("Kotlin package, e.g. com.example.app.content") },
    },
    async ({ packageName }) => ok(anchorKt(packageName)),
  );
}
