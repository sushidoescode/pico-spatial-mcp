/**
 * v3.8 Swan-readiness: package hardware-sensitive C1/C3/C4 initializers behind guarded calls. Some
 * C1 APIs now return simulated data on the emulator; other paths still fail or defer there. The
 * keyed bring-up checklist distinguishes emulator simulation from physical-room/device proof.
 */

function headsetReadinessKt(pkg: string): string {
  return [
    `package ${pkg}`,
    "",
    "import android.util.Log",
    "",
    "/**",
    " * Generated by generate_headset_readiness_codegen. A guarded init registry for hardware-",
    " * sensitive features (C1 sense/plane surface pins and anchors, C3 controller-ray interaction,",
    " * C4 in-front panels). Each initializer runs inside runCatching. Plane tracking can return the",
    " * emulator's simulated room; unsupported paths log and skip instead of crashing.",
    " *",
    " * Wire your headset features as lambdas, e.g.:",
    " *   HeadsetReadiness.register(\"planePins\") { SceneUnderstanding.start() }      // C1",
    " *   HeadsetReadiness.register(\"anchors\")   { /* WorldAnchors.load(...) */ }     // C1",
    " *   HeadsetReadiness.register(\"controllerRay\") { /* controller select wiring */ } // C3",
    " * then call HeadsetReadiness.enable() once after the scene loads.",
    " */",
    "object HeadsetReadiness {",
    '    private const val TAG = "HeadsetReadiness"',
    "    private val inits = mutableListOf<Pair<String, () -> Unit>>()",
    "",
    "    /** Register a hardware-sensitive initializer (runs guarded; may use emulator simulation). */",
    "    fun register(name: String, init: () -> Unit) { inits.add(name to init) }",
    "",
    "    /** Run all registered headset initializers, each guarded. Safe on the emulator. */",
    "    fun enable() {",
    "        for ((name, init) in inits) {",
    "            runCatching { init() }",
    '                .onSuccess { Log.i(TAG, "headset feature enabled: $name") }',
    '                .onFailure { Log.w(TAG, "headset feature \'$name\' skipped (emulator? no hardware): ${it.message}") }',
    "        }",
    "    }",
    "}",
    "",
  ].join("\n");
}

/**
 * Standalone hand-pinch input registry. Every SDK symbol is confirmed in the 0.13 agent-vault
 * (api-reference/com.pico.spatial.tracking.hand.md + com.pico.spatial.tracking.md): HandTrackingProvider
 * is a DataProvider<HandTrackingData> (@RequiredFullSpace) with start/stop/addListener/removeListener;
 * HandTrackingData carries left/right HandPose?; HandPose[HandJoint.Index] returns a HandJoint with a
 * Vector3 position. There is NO SDK "pinch" API — the pinch is DERIVED (thumb-tip↔index-tip distance),
 * the same detection generate_game_menu_kotlin's handInput path already emits.
 */
function handPinchInputKt(pkg: string): string {
  return [
    `package ${pkg}`,
    "",
    "import android.os.Handler",
    "import android.os.Looper",
    "import android.util.Log",
    "import com.pico.spatial.core.math.Vector3",
    "import com.pico.spatial.tracking.DataProvider",
    "import com.pico.spatial.tracking.hand.HandJoint",
    "import com.pico.spatial.tracking.hand.HandPose",
    "import com.pico.spatial.tracking.hand.HandTrackingData",
    "import com.pico.spatial.tracking.hand.HandTrackingProvider",
    "import kotlin.math.sqrt",
    "",
    "/**",
    " * Generated by generate_hand_input_kotlin. HEADSET-ONLY (C3) hand-pinch input: a PINCH",
    " * (thumb-tip↔index-tip closer than PINCH_DIST) fires onPinch with the index-fingertip position.",
    " * The emulator's HandTrackingProvider supplies no hands, so this NO-OPS there (start() logs a",
    " * marker either way). Register it behind HeadsetReadiness so the app never crashes without hardware:",
    " *   HeadsetReadiness.register(\"handPinch\") { HandPinchInput.start { tip -> /* route to select/poke */ } }",
    " *   // then HeadsetReadiness.enable() once after the scene loads",
    " */",
    "object HandPinchInput {",
    '    private const val TAG = "HandPinchInput"',
    "    private const val PINCH_DIST = 0.035f // metres: thumb-tip to index-tip = a pinch",
    "    private val provider = HandTrackingProvider()",
    "    private val main = Handler(Looper.getMainLooper())",
    "    private var onPinch: ((Vector3) -> Unit)? = null",
    "    private var leftWas = false",
    "    private var rightWas = false",
    "    // NOTE: onProvideData is NOT on the main thread -> post the app callback to main.",
    "    private val listener = DataProvider.DataListener<HandTrackingData> { d ->",
    "        leftWas = pinch(d.left, leftWas); rightWas = pinch(d.right, rightWas)",
    "    }",
    "",
    "    /** Start hand tracking; handler fires on the MAIN thread at the index-tip position per fresh pinch. */",
    "    fun start(handler: (indexTip: Vector3) -> Unit) {",
    "        onPinch = handler",
    "        runCatching { provider.start(); provider.addListener(listener) }",
    '            .onSuccess { Log.i(TAG, "hand input started (headset-only; the emulator provides no hands)") }',
    '            .onFailure { Log.w(TAG, "hand input unavailable (emulator? no hardware): ${it.message}") }',
    "    }",
    "",
    "    fun stop() { runCatching { provider.removeListener(listener); provider.stop() }; onPinch = null }",
    "",
    "    private fun pinch(pose: HandPose?, was: Boolean): Boolean {",
    "        pose ?: return false",
    "        val thumb = runCatching { pose[HandJoint.Index.THUMB_TIP].position }.getOrNull() ?: return was",
    "        val index = runCatching { pose[HandJoint.Index.INDEX_TIP].position }.getOrNull() ?: return was",
    "        val now = dist(thumb, index) < PINCH_DIST",
    "        if (now && !was) main.post { onPinch?.invoke(index) } // rising edge = a fresh pinch",
    "        return now",
    "    }",
    "",
    "    private fun dist(a: Vector3, b: Vector3): Float {",
    "        val dx = a.x - b.x; val dy = a.y - b.y; val dz = a.z - b.z",
    "        return sqrt(dx * dx + dy * dy + dz * dz)",
    "    }",
    "}",
    "",
  ].join("\n");
}

export function registerSwanTools(server: McpServer) {
  server.registerTool(
    "generate_headset_readiness_codegen",
    {
      description:
        "Emit HeadsetReadiness.kt — a guarded registry for hardware-sensitive C1/C3/C4 initializers. Plane/mesh scene understanding can use the emulator's simulated room; controller, persistence, and physical-room conclusions remain hardware-gated. Unsupported initializers log and skip rather than crashing. Returns the Kotlin plus a manifest that separates simulator evidence from Swan obligations.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
      },
    },
    async ({ packageName }) =>
      okJson({
        file: { path: `app/src/main/java/${packageName.replace(/\./g, "/")}/HeadsetReadiness.kt`, content: headsetReadinessKt(packageName) },
        headsetFeatureManifest: [
          { feature: "sense/plane surface pins", ceiling: "C1", generator: "generate_scene_understanding_kotlin", emulator: "simulated room: ~43 semantic planes and 42–44 mesh anchors measured after readiness polling", swan: "must prove pins snap to a user's physical surfaces" },
          { feature: "WorldAnchor persistence", ceiling: "C1", generator: "generate_persistent_anchor_kotlin", emulator: "no world-tracking — returns errors", swan: "persists poses across launches" },
          { feature: "controller-ray interaction", ceiling: "C3", generator: "(head-ray fallback today; controller API on Swan)", emulator: "use HMD head-ray + app_broadcast", swan: "6DOF controller ray + trigger select" },
          { feature: "in-front interactive Compose panels", ceiling: "C4", generator: "(platform window-transform API)", emulator: "use in-world textured-quad UI", swan: "real window placement in front" },
        ],
        note: "Register each initializer as a lambda and call HeadsetReadiness.enable(). A successful emulator plane path is simulation evidence, not Swan physical-room proof; feed the remaining obligations to swan_bring_up_checklist.",
      }),
  );

  server.registerTool(
    "generate_hand_input_kotlin",
    {
      description:
        "Emit HandPinchInput.kt — a HEADSET-ONLY (C3) hand-pinch input registry for the HeadsetReadiness guarded-init pattern. Every SDK symbol is vault-confirmed (com.pico.spatial.tracking.hand: HandTrackingProvider/HandTrackingData/HandPose/HandJoint.Index; DataProvider start/stop/addListener) — there is NO SDK 'pinch' API, so the pinch is DERIVED as thumb-tip↔index-tip distance, the same detection generate_game_menu_kotlin's handInput path emits. On the emulator HandTrackingProvider supplies no hands: start() logs a marker and no pinches ever fire (honest no-op) — the feature is UNVERIFIABLE there; record it built_for_headset and close it via swan_verify_matrix + a device_verified entry on real hardware. Not compile-verified standalone in this repo yet (the sibling GameMenuHandInput pattern is what it mirrors); run a gradle build after wiring.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package, e.g. com.example.app.content"),
      },
    },
    async ({ packageName }) =>
      okJson({
        file: { path: `app/src/main/java/${packageName.replace(/\./g, "/")}/HandPinchInput.kt`, content: handPinchInputKt(packageName) },
        wiring: [
          'HeadsetReadiness.register("handPinch") { HandPinchInput.start { tip -> /* route tip to your select/poke entry point */ } }',
          "HeadsetReadiness.enable()  // once, after the scene loads (generate_headset_readiness_codegen)",
        ],
        emulatorBehavior: "no hands from HandTrackingProvider → no pinches; start() logs 'hand input started (headset-only; the emulator provides no hands)' as the wiring marker (assert via assert_logcat tag HandPinchInput).",
        note: "C3 headset-only: ledger it as built_for_headset now; the hand_pinch row in swan_verify_matrix flips to device_verified only from a record_verification entry with real-hardware evidence.",
      }),
  );

  server.registerTool(
    "swan_bring_up_checklist",
    {
      description:
        "Emit a keyed PICO Swan bring-up checklist (markdown): for each headset-only feature, the exact on-hardware re-test so day-one-on-Swan is a verification pass, not a build. Feed it the headset-feature manifest from generate_headset_readiness_codegen + the capability_report builtForHeadset bucket.",
      inputSchema: {
        appName: z.string().optional(),
        features: z
          .array(
            z.object({
              feature: z.string(),
              ceiling: z.string().optional().describe("C1/C3/C4 (the ledger's C4_headset_only / C0_emulator spellings are normalized)."),
              retest: z.string().optional().describe("How to verify it on Swan."),
            }),
          )
          .describe("Headset-only features to re-test on hardware."),
      },
    },
    async ({ appName, features }) => {
      const retestDefault: Record<string, string> = {
        C1: "put the headset on a real surface; confirm pins snap to floor/wall/ceiling and anchors persist across a relaunch.",
        C3: "point the 6DOF controller ray at a target and pull the trigger; confirm select fires (vs the emulator head-ray/broadcast path).",
        C4: "confirm interactive Compose panels render IN FRONT and respond to the controller (vs the emulator in-world textured-quad fallback).",
      };
      // The trust ledger's cClass enum says "C4_headset_only"/"C0_emulator" (ledger.ts) — normalize so
      // ledger-fed ceilings still hit the C1/C3/C4 retest map instead of falling through to the generic line.
      const normCeiling = (c?: string) => c?.replace(/_headset_only$/, "").replace(/_emulator$/, "");
      const md = [
        `# PICO Swan bring-up checklist${appName ? `: ${appName}` : ""}`,
        ``,
        `> Day one on hardware = verify these (they were built + compile-checked on the emulator but are HEADSET-ONLY). Everything else was already emulator-verified.`,
        ``,
        ...features.map((f, i) => {
          const ceil = normCeiling(f.ceiling);
          const how = f.retest ?? (ceil ? retestDefault[ceil] : undefined) ?? "verify the feature behaves as designed on hardware.";
          return `- [ ] **${f.feature}**${ceil ? ` _(ceiling ${ceil})_` : ""} — ${how}`;
        }),
        ``,
        `Regressions: run \`verify_baseline\` against emulator baselines where applicable; structural via \`assert_scene\`.`,
      ].join("\n");
      return ok(md);
    },
  );
}
