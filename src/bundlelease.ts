import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok, fail } from "./util.js";

/**
 * bundlelease.ts — v35.18 a refcounted AssetBundle registry.
 *
 * THE PROBLEM IT SOLVES. Five of our generators call AssetBundle.load independently —
 * assemble.ts, surfaceplace.ts, environment.ts, databinding.ts, signageboard.ts — so an app using
 * three of them loads the SAME bundle three times, and (before v35.5) released none of it. v35.5
 * fixed the single-owner case inside databinding with a keyed cache; this is the cross-generator,
 * multi-owner case, where the same model can be live in a list, a detail view and the scene at once
 * and must survive any ONE of them letting go.
 *
 * PROVENANCE, stated precisely, because the conformance report got this wrong. That report said to
 * model this on "WelcomeSpace/.../data/AssetBundle.kt", describing an AssetBundleManager with a
 * Mutex, a modelOwners map and acquire/release. **That file is 83 lines in the 6.0.0 GitHub copy and
 * 29 lines in PICO's authentic 0.13.3 archive, where none of that exists** — the 0.13.3 sample is
 * just a lazily-loaded shared singleton:
 *     val assetBundle = CoroutineScope(Dispatchers.IO).async(start = CoroutineStart.LAZY) {
 *         AssetBundle.load(BUNDLE_URI)
 *     }
 * So this pattern is NOT demonstrated by any 0.13.3 sample. What makes it safe to ship anyway is
 * that every SDK call it needs is confirmed in the 0.13.3 jars:
 *     AssetBundle.load(path, loadType)   `ecs/resource/AssetBundle.kt:470`
 *     AssetBundle.releaseModel(name)     `:213`
 *     AssetBundle.close()                `:235`  (it is Closeable, `:76-77`)
 *     AssetBundle.valid                  `:82`
 * Idiom from 6.0.0, API surface verified against 0.13.3, and said out loud rather than dressed up as
 * a 0.13.3 sample pattern.
 *
 * THREE THINGS IT ENCODES:
 *  1. OWNER-KEYED REFCOUNTS, not a plain count. `release("chair", "preview")` must not free a model
 *     the room still holds. Owners are namespaced strings so the same model can be leased by several
 *     call sites, and only the LAST release actually frees.
 *  2. `valid` IS RE-CHECKED before every use (AssetBundle.kt:82). A closed bundle handed back from a
 *     cache is the failure this prevents.
 *  3. A Mutex, because acquire is a suspend function doing IO and two concurrent acquires of the same
 *     path would otherwise both load it. Kotlin's Mutex, not synchronized: the critical section
 *     suspends.
 */

export interface BundleLeaseArgs {
  packageName: string;
  bundles?: string[];
}

export function generateBundleLeaseKotlin(args: BundleLeaseArgs): string {
  const { packageName } = args;
  const bundles = (args.bundles ?? []).filter((b) => b.trim());
  for (const b of bundles) {
    if (!b.startsWith("asset://") && !b.startsWith("file://")) {
      throw new Error(`bundle path must carry a scheme (asset:// | file://) — got '${b}'`);
    }
  }

  return [
    `package ${packageName}`,
    ``,
    `import android.util.Log`,
    `import com.pico.spatial.core.ecs.Entity`,
    `import com.pico.spatial.core.ecs.resource.AssetBundle`,
    `import kotlinx.coroutines.Dispatchers`,
    `import kotlinx.coroutines.sync.Mutex`,
    `import kotlinx.coroutines.sync.withLock`,
    `import kotlinx.coroutines.withContext`,
    ``,
    `/**`,
    ` * Generated by generate_bundle_lease_kotlin — ONE AssetBundle per path, shared by every caller,`,
    ` * released when the last owner lets go.`,
    ` *`,
    ` * Without this, each generator that needs a bundle loads its own copy: an app that seats a model`,
    ` * on a surface, dresses a set and binds a data catalog loads the same bundle three times.`,
    ` *`,
    ` * Owners are namespaced strings — "room", "preview:chair", "display:chair" — so the same model can`,
    ` * be live in several places and only the LAST release frees it.`,
    ` *`,
    ` *   val bundle = SceneBundles.acquire("asset://furniture.bundle", "room")`,
    ` *   val chair = SceneBundles.loadModel("asset://furniture.bundle", "chair", "room")`,
    ` *   ...`,
    ` *   SceneBundles.release("asset://furniture.bundle", "room")   // frees only if nobody else holds it`,
    ` *   SceneBundles.closeAll()                                    // teardown`,
    ` */`,
    `object SceneBundles {`,
    `    private const val TAG = "SceneBundles"`,
    ``,
    ...(bundles.length
      ? [
          `    /** Known bundle paths for this app. */`,
          ...bundles.map((b, i) => `    const val BUNDLE_${i} = ${JSON.stringify(b)}`),
          ``,
        ]
      : []),
    `    // A Mutex, not synchronized: acquire() suspends (the load is IO), and a synchronized block`,
    `    // cannot span a suspension point. Two concurrent acquires of the same path would otherwise`,
    `    // each load their own copy — the exact duplication this object exists to prevent.`,
    `    private val lock = Mutex()`,
    `    private val bundles = mutableMapOf<String, AssetBundle>()`,
    `    private val owners = mutableMapOf<String, MutableSet<String>>()`,
    ``,
    `    /** Lease [path] for [owner]. Loads once; later callers get the same instance. */`,
    `    suspend fun acquire(path: String, owner: String): AssetBundle? = lock.withLock {`,
    `        runCatching {`,
    `            val existing = bundles[path]`,
    `            // Re-check validity every time (AssetBundle.kt:82). A cache that hands back a CLOSED`,
    `            // bundle is worse than no cache — every use of it fails downstream, far from here.`,
    `            val bundle = if (existing != null && existing.valid) existing else {`,
    `                if (existing != null) Log.w(TAG, "cached bundle for " + path + " was invalid — reloading")`,
    `                val loaded = withContext(Dispatchers.IO) { AssetBundle.load(path) }`,
    `                bundles[path] = loaded`,
    `                loaded`,
    `            }`,
    `            owners.getOrPut(path) { mutableSetOf() }.add(owner)`,
    `            bundle`,
    `        }.onFailure { Log.e(TAG, "acquire(" + path + ", " + owner + ") failed: " + it.message) }.getOrNull()`,
    `    }`,
    ``,
    `    /** Load a named model from a leased bundle, taking the lease if it is not held yet. */`,
    `    suspend fun loadModel(path: String, modelName: String, owner: String): Entity? {`,
    `        val bundle = acquire(path, owner) ?: return null`,
    `        return runCatching { Entity.loadSuspend(modelName, bundle) }`,
    `            .onFailure { Log.e(TAG, "loadModel('" + modelName + "') failed: " + it.message) }`,
    `            .getOrNull()`,
    `    }`,
    ``,
    `    /**`,
    `     * Drop [owner]'s lease. The bundle is closed ONLY when the last owner releases it — this is`,
    `     * the whole point: release("furniture", "preview") must not free a model the room still shows.`,
    `     */`,
    `    suspend fun release(path: String, owner: String) = lock.withLock {`,
    `        val set = owners[path] ?: return@withLock`,
    `        set.remove(owner)`,
    `        if (set.isNotEmpty()) {`,
    `            Log.i(TAG, "release(" + path + ", " + owner + ") — " + set.size + " owner(s) remain")`,
    `            return@withLock`,
    `        }`,
    `        owners.remove(path)`,
    `        bundles.remove(path)?.let { runCatching { it.close() } }`,
    `        Log.i(TAG, "released and closed " + path)`,
    `    }`,
    ``,
    `    /** Release a single MODEL without dropping the bundle lease (AssetBundle.kt:213). */`,
    `    suspend fun releaseModel(path: String, modelName: String) = lock.withLock {`,
    `        bundles[path]?.takeIf { it.valid }?.let { runCatching { it.releaseModel(modelName) } }`,
    `        Unit`,
    `    }`,
    ``,
    `    /** MANDATORY teardown — onCleared / onDispose / ON_DESTROY. */`,
    `    suspend fun closeAll() = lock.withLock {`,
    `        bundles.values.forEach { runCatching { it.close() } }`,
    `        bundles.clear()`,
    `        owners.clear()`,
    `        Log.i(TAG, "all bundles closed")`,
    `    }`,
    `}`,
    ``,
  ].join("\n");
}

export function registerBundleLeaseTools(server: McpServer) {
  server.registerTool(
    "generate_bundle_lease_kotlin",
    {
      description:
        "Emit SceneBundles.kt — ONE AssetBundle per path, shared across callers, refcounted by OWNER, closed when the last owner releases. WHY: five of our generators (app wiring, surface placement, environment, data binding, signage) each call AssetBundle.load independently, so an app using three of them loads the same bundle three times. v35.5 fixed the single-owner case inside data binding with a keyed cache; this is the cross-generator, multi-owner case, where the same model can be live in a list, a detail view and the scene at once and must survive any ONE of them letting go. PROVENANCE, stated honestly: the conformance report said to model this on WelcomeSpace's AssetBundle.kt, but that refcounted manager exists only in the 6.0.0 GitHub copy (83 lines) — PICO's authentic 0.13.3 archive has 29 lines and just a lazily-loaded shared singleton. So NO 0.13.3 sample demonstrates this pattern; what makes it safe is that every SDK call it needs is confirmed in the 0.13.3 jars (AssetBundle.load :470, releaseModel :213, close :235, valid :82). THREE THINGS IT ENCODES: owner-keyed refcounts so release(path,'preview') cannot free a model the room still holds; a re-check of AssetBundle.valid before every use, because a cache that hands back a CLOSED bundle fails far from the cache; and a Kotlin Mutex rather than synchronized, because acquire suspends on IO and two concurrent acquires would otherwise each load their own copy. HONEST STATUS: structural — jar-cited, not sample-demonstrated at 0.13.3, and not yet built or looked at.",
      inputSchema: {
        packageName: z.string().describe("Kotlin package for the emitted file, e.g. com.example.app.content"),
        bundles: z.array(z.string()).optional().describe("Known bundle paths with a scheme, e.g. ['asset://furniture.bundle']. Emitted as BUNDLE_n constants; the API works with any path either way."),
      },
    },
    async ({ packageName, bundles }) => {
      try {
        return ok(generateBundleLeaseKotlin({ packageName, bundles }));
      } catch (e: any) {
        return fail(String(e?.message ?? e));
      }
    },
  );
}
