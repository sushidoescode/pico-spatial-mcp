import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { ok } from "./util.js";

/**
 * livedata.ts — v10.15 (P13): LIVE-DATA spatial panels.
 *
 * A floating panel that POLLS an external JSON source every N seconds and updates its display in
 * real time — turning the spatial workspace into a live monitor/dashboard. Emits a WebView activity
 * that loads a self-contained polling page (baseURL set to the data origin so same-origin fetch
 * works). Real HTML text updates live; WebView debugging on for deterministic DOM verification.
 */
export function registerLiveDataTools(server: McpServer) {
  server.registerTool(
    "generate_live_data_panel",
    {
      description:
        "Emit LiveDataPanel.kt (P13) — a floating spatial panel that POLLS a JSON URL every pollSec and updates its label:value rows LIVE (real HTML text; no baked textures). A WebView activity loads a self-contained polling page with its origin set to the data URL so same-origin fetch works. Use for live monitors/dashboards fed by an API or a served file (adb reverse tcp:PORT tcp:PORT + a host server). RETURNS: JSON {kotlin, manifestEntry} — write to content/LiveDataPanel.kt, merge manifestEntry (+ INTERNET/cleartext for http), open with `am start -n <pkg>/<contentPkg>.LiveDataPanelActivity`. WebView debugging on (CDP-verifiable: change the data, read the DOM).",
      inputSchema: {
        packageName: z.string().describe("Content package, e.g. com.example.app.content"),
        title: z.string().optional().describe("Panel title (default 'LIVE')."),
        dataUrl: z.string().describe("JSON endpoint to poll, e.g. http://localhost:8791/data.json (host: adb reverse + a server)."),
        fields: z.array(z.object({ key: z.string(), label: z.string() })).min(1).describe("JSON keys -> row labels, e.g. [{key:'temp',label:'TEMP'},{key:'load',label:'LOAD'}]."),
        pollSec: z.number().optional().describe("Poll interval seconds (default 2)."),
      },
    },
    async ({ packageName, title, dataUrl, fields, pollSec }) => {
      const appPkg = packageName.replace(/\.content$/, "");
      const t = title ?? "LIVE";
      const origin = (() => { try { const u = new URL(dataUrl); return `${u.protocol}//${u.host}/`; } catch { return "http://localhost/"; } })();
      const rows = fields.map((f) => `<div class=row><span class=lbl>${f.label.replace(/</g, "")}</span><span class=val id="f_${f.key}">…</span></div>`).join("");
      const keys = JSON.stringify(fields.map((f) => f.key));
      const html = `<!doctype html><html><head><meta charset=utf-8><style>
html,body{margin:0;height:100%;background:#0b1020;color:#eaf0ff;font-family:-apple-system,Roboto,sans-serif;padding:6vw}
h1{color:#7fd7ff;font-size:8vw;margin:0 0 4vw}
.row{display:flex;justify-content:space-between;padding:3vw 0;border-bottom:1px solid #22305e;font-size:5vw}
.lbl{color:#9aa4bf}.val{color:#7dff9b;font-weight:800}
#stamp{position:fixed;bottom:3vw;right:4vw;color:#4a5878;font-size:3vw}
</style></head><body><h1>${t}</h1>${rows}<div id=stamp>polling…</div>
<script>
const URL_=${JSON.stringify(dataUrl)}, KEYS=${keys}, MS=${(pollSec ?? 2) * 1000};
let ticks=0;
async function poll(){
  try{ const d=await (await fetch(URL_,{cache:'no-store'})).json();
    for(const k of KEYS){ const e=document.getElementById('f_'+k); if(e) e.textContent = (d[k]!==undefined? d[k] : '—'); }
    document.getElementById('stamp').textContent='updated #' + (++ticks);
  }catch(e){ document.getElementById('stamp').textContent='poll error'; }
}
setInterval(poll, MS); poll();
</script></body></html>`;
      const kt = [
        `package ${packageName}`,
        ``,
        `import android.annotation.SuppressLint`,
        `import android.os.Bundle`,
        `import android.webkit.WebView`,
        `import androidx.activity.ComponentActivity`,
        ``,
        `/**`,
        ` * Generated by generate_live_data_panel — a floating panel polling ${dataUrl} every ${(pollSec ?? 2)}s.`,
        ` * Open: am start -n ${appPkg}/${packageName}.LiveDataPanelActivity`,
        ` */`,
        `class LiveDataPanelActivity : ComponentActivity() {`,
        `    @SuppressLint("SetJavaScriptEnabled")`,
        `    override fun onCreate(savedInstanceState: Bundle?) {`,
        `        super.onCreate(savedInstanceState)`,
        `        WebView.setWebContentsDebuggingEnabled(true)`,
        `        val wv = WebView(this)`,
        `        wv.settings.javaScriptEnabled = true`,
        `        // baseURL = the data origin so the page's fetch() is same-origin`,
        `        wv.loadDataWithBaseURL(${JSON.stringify(origin)}, HTML, "text/html", "utf-8", null)`,
        `        setContentView(wv)`,
        `    }`,
        `    companion object { private val HTML = ${JSON.stringify(html)} }`,
        `}`,
        ``,
      ].join("\n");
      const manifestEntry = `<activity android:name="${packageName}.LiveDataPanelActivity" android:exported="true" android:taskAffinity="${appPkg}.livedata" android:launchMode="singleTask" />`;
      return ok(JSON.stringify({ kotlin: kt, manifestEntry, dataOrigin: origin, note: "Write to content/LiveDataPanel.kt; merge manifestEntry + set android:usesCleartextTraffic on <application> (http) + INTERNET permission; serve the data (adb reverse tcp:PORT tcp:PORT + host server); open with am start. Change the served JSON -> the panel updates within pollSec." }, null, 2));
    },
  );
}
