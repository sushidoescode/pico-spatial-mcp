package com.example.spatialapp.content

import android.util.Log
import com.pico.spatial.core.ecs.DirectionalLightComponent
import com.pico.spatial.core.ecs.Entity
import com.pico.spatial.core.ecs.EnvironmentLightingSettingsComponent
import com.pico.spatial.core.ecs.GroundShadowComponent
import com.pico.spatial.core.ecs.PointLightComponent
import com.pico.spatial.core.ecs.SpotLightComponent
import com.pico.spatial.core.ecs.TransformComponent
import com.pico.spatial.core.math.Color4
import com.pico.spatial.core.math.EulerAngles
import com.pico.spatial.core.math.Quat
import com.pico.spatial.core.math.Vector3

/**
 * Generated by generate_full_lighting_rig_kotlin. A complete lighting rig: directional sun +
 * point (falloff) + spot (cone) + ground/contact shadow + IBL. Call SceneLightingRig.apply(content).
 * VERIFY: compiles; point falloff / spot cone / contact shadow are vision-verifiable on a BAKED-MESH
 * scene via capture_frame (the system-lit home env will not change).
 */
object SceneLightingRig {
    private const val TAG = "SceneLightingRig"

    fun apply(content: Entity) {
        runCatching {
            content.components.set(EnvironmentLightingSettingsComponent(1.4f))
            content.components.set(GroundShadowComponent(true, true)) // contact/ground shadows

            val sun = Entity().also { it.setName("RigSun") }
            sun.components.set(TransformComponent(Vector3(0f, 3f, 0f), Quat.identity(), Vector3(1f, 1f, 1f)).setEulerAngles(EulerAngles(-50f, -30f, 0f)))
            sun.components.set(DirectionalLightComponent(Color4(1f, 0.96f, 0.9f, 1f), 1400f))
            content.addChild(sun)

            val point = Entity().also { it.setName("RigPoint") }
            point.components.set(TransformComponent(Vector3(1.2f, 1.6f, -1.4f), Quat.identity(), Vector3(1f, 1f, 1f)))
            point.components.set(PointLightComponent(Color4(1f, 0.82f, 0.55f, 1f), 900f, 4f)) // warm lamp, 4m falloff
            content.addChild(point)

            val spot = Entity().also { it.setName("RigSpot") }
            spot.components.set(TransformComponent(Vector3(-1.1f, 2.3f, -1.2f), Quat.identity(), Vector3(1f, 1f, 1f)).setEulerAngles(EulerAngles(-70f, 18f, 0f)))
            spot.components.set(SpotLightComponent(Color4(0.9f, 0.95f, 1f, 1f), 1300f, 6f, 0.45f, 0.7f)) // cone inner 0.45 / outer 0.7 rad
            content.addChild(spot)
            Log.i(TAG, "full lighting rig applied (sun+point+spot+groundShadow+ibl)")
        }.onFailure { Log.e(TAG, "lighting rig failed: ${it.message}") }
    }
}
