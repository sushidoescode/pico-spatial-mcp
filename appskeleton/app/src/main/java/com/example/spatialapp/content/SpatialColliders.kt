/**
 * Generated by pico-spatial-mcp generate_collider_kotlin — VERIFIED runtime collider recipe.
 *
 * USAGE (in your SpatialView.initial, after the scene model is loaded + added):
 *   withContext(Dispatchers.Main) {
 *     SpatialColliders.attachPhysicsWorld(model)        // REQUIRED on-device for rayCast
 *     SpatialColliders.attachColliders { content.addEntity(it) }
 *   }
 *   // then: val hit = SpatialColliders.rayCast(model.scene, origin, dir)
 *
 * Facts baked in: PhysicsWorldComponent is REQUIRED on-device; only PRIMITIVE shapes
 * register (no static/convex mesh); createBox takes FULL extents; the 5-arg
 * CollisionComponent ctor is the public one; no RigidBody needed for static colliders.
 */
object SpatialColliders {
    private const val TAG = "SpatialColliders"

    private fun physMat() = PhysicsMaterialResource(0.5f, 0.5f, 0f)

    /** REQUIRED: enrolls the scene's colliders into the queryable PhysX world. Call once,
     *  on Dispatchers.Main, on the scene-root entity (or a common ancestor of the colliders). */
    fun attachPhysicsWorld(root: Entity) {
        runCatching { root.components.set(PhysicsWorldComponent()) }
            .onFailure { Log.e(TAG, "PhysicsWorldComponent failed: ${it.message}") }
    }

    /** Attach one primitive collider entity at a world position. Returns it (already given
     *  a TransformComponent + CollisionComponent); pass it to content.addEntity / addChild. */
    fun box(name: String, pos: Vector3, fullExtents: Vector3): Entity = collider(name, pos, ShapeResource.createBox(fullExtents))
    fun sphere(name: String, pos: Vector3, radius: Float): Entity = collider(name, pos, ShapeResource.createSphere(radius))
    fun capsule(name: String, pos: Vector3, radius: Float, height: Float): Entity = collider(name, pos, ShapeResource.createCapsule(radius, height))

    private fun collider(name: String, pos: Vector3, shape: ShapeResource): Entity {
        val e = Entity()
        e.setName(name)
        e.components.set(TransformComponent(pos, Quat.identity(), Vector3(1f, 1f, 1f)))
        runCatching {
            e.components.set(
                CollisionComponent(
                    listOf(shape), physMat(),
                    CollisionResponseMode.COLLIDER_FULL,
                    CollisionFilter.COLLISION_FILTER_DEFAULT,
                    CollisionInfoDetailLevel.BRIEF,
                ),
            )
        }.onFailure { Log.e(TAG, "collider '$name' failed: ${it.message}") }
        return e
    }

    /** Attach all configured colliders. `add` is content.addEntity (world frame) or an
     *  ancestor's addChild (local frame). */
    fun attachColliders(add: (Entity) -> Unit) {
        // Room as 6 thin box "walls" (real rayCast, correct inward normals).
        add(box("Col_Floor", Vector3(0f, 0f, -1.2f), Vector3(5.6f, 0.12f, 5.6f)))
        add(box("Col_Ceil", Vector3(0f, 2.6f, -1.2f), Vector3(5.6f, 0.12f, 5.6f)))
        add(box("Col_WallL", Vector3(-2.8f, 1.3f, -1.2f), Vector3(0.12f, 2.6f, 5.6f)))
        add(box("Col_WallR", Vector3(2.8f, 1.3f, -1.2f), Vector3(0.12f, 2.6f, 5.6f)))
        add(box("Col_WallBack", Vector3(0f, 1.3f, -4f), Vector3(5.6f, 2.6f, 0.12f)))
        add(box("Col_WallFront", Vector3(0f, 1.3f, 1.5999999999999999f), Vector3(5.6f, 2.6f, 0.12f)))
        add(box("HomeEnvBed", Vector3(0f, 0.25f, -1.8f), Vector3(1.9f, 0.5f, 2.2f)))
    }

    /** Cast a ray against the registered colliders; returns the nearest hit (position +
     *  surface normal + distance) or null. @MainThread. */
    fun rayCast(scene: Scene?, origin: Vector3, direction: Vector3, maxDistance: Float = 60f): CollisionCastResult? =
        scene?.rayCast(origin, direction, maxDistance, CollisionCastHitMode.NEAREST,
            CollisionGroup(CollisionGroup.COLLISION_GROUP_ALL), null)?.results?.firstOrNull()
}

